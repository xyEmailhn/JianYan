def 主():
    参数 = sys.argv[1:]
    if not 参数:
        print("用法：python3 parser_参考实现.py [-统计|-基准] 文件.简", file=sys.stderr)
        return 2

    模式 = "树"
    路径 = 参数[0]
    if len(参数) >= 2 and 参数[0].startswith("-"):
        模式 = 参数[0]
        路径 = 参数[1]

    try:
        with open(路径, encoding="utf-8") as f:
            源 = f.read()
    except OSError:
        print("打不开文件：%s" % 路径, file=sys.stderr)
        return 1

    词们 = 切词(源)
    P = 语法器(词们, 路径)

    t0 = time.time()
    根 = 解析程序(P)
    毫秒 = (time.time() - t0) * 1000

    if 模式 == "-基准":
        轮数, 总节点 = 0, 0
        t0 = time.time()
        秒 = 0.0
        while 秒 < 1.0:
            P2 = 语法器(词们, 路径)
            根2 = 解析程序(P2)
            总节点 += P2.节点数
            轮数 += 1
            秒 = time.time() - t0
        MB = len(源.encode("utf-8")) * 轮数 / (1024.0 * 1024.0)
        print("轮数       %d" % 轮数)
        print("每轮节点   %d" % (总节点 // 轮数))
        print("耗时       %.3f 秒" % 秒)
        print("吞吐       %.1f MB/s" % (MB / 秒))
        return 0

    计数 = {}
    最深 = 统计树(根, 计数)

    if 模式 == "-统计":
        字节 = len(源.encode("utf-8"))
        print("文件       %s" % 路径)
        print("字节数     %d" % 字节)
        print("词数       %d" % len(词们))
        print("节点数     %d" % sum(计数.values()))
        print("树深       %d 层" % (最深 + 1))
        print("耗时       %.2f 毫秒" % 毫秒)
        print("--- 节点分布 ---")
        for 名 in sorted(计数, key=lambda k: -计数[k]):
            print("%s %d" % (名, 计数[名]))
    else:
        出 = []
        打印树(根, 0, 出)
        print("\n".join(出))

    for 行, 列, 话 in P.警告:
        print("%s:%d:%d: 提示：%s" % (路径, 行, 列, 话), file=sys.stderr)
    for 行, 列, 话 in P.错误:
        print("%s:%d:%d: 语法错误：%s" % (路径, 行, 列, 话), file=sys.stderr)
    print("\n共 %d 个节点，%d 个语法错误，%d 个提示，耗时 %.2f 毫秒"
          % (P.节点数, len(P.错误), len(P.警告), 毫秒), file=sys.stderr)

    return 1 if P.错误 else 0


if __name__ == "__main__":
    sys.exit(主())
