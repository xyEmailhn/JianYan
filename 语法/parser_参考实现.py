def 解析语句(P):
    t = P.当前()

    if 是关(t, "私有"):
        P.吃()
        下一个 = P.当前()
        if (是关(下一个, "函数") and not 是符(P.看(1), "(")) \
                or 是关(下一个, "结构") or 是关(下一个, "枚举") \
                or 是关(下一个, "接口") or 是关(下一个, "实现"):
            P.报错(t, "`私有` 只能修饰变量、常量、令 或顶层的定义")
            跳到行尾(P)
            return None
        return 解析声明(P, {"私有"})
    if 是关(t, "不可变"):
        P.吃()
        return 解析声明(P, {"不可变"})

    if 是关(t, "常量") or 是关(t, "令") or 是声明开头(P):
        return 解析声明(P)

    if 是关(t, "返回"):
        P.吃()
        n = 新(P, "返回")
        if P.当前().种类 != 换 and not 是符(P.当前(), "}"):
            加(n, 解析表达式(P))
        P.吃换行()
        return n
    if 是关(t, "如果"):
        return 解析如果(P)
    if 是关(t, "当"):
        return 解析当(P)
    if 是关(t, "重复循环直到"):
        return 解析重复(P)
    if 是关(t, "对"):
        return 解析对(P)
    if 是关(t, "匹配"):
        return 解析匹配(P)
    if 是关(t, "循环"):
        P.吃()
        n = 新(P, "循环")
        加(n, 解析块(P))
        P.吃换行()
        return n

    if 是关(t, "打断") or 是关(t, "继续"):
        P.吃()
        n = 新(P, "打断" if 是关(t, "打断") else "继续")
        P.吃换行()
        return n

    if 是关(t, "线程"):
        P.吃()
        n = 新(P, "线程")
        加(n, 解析块(P))
        P.吃换行()
        return n
    if 是关(t, "发送"):
        P.吃()
        n = 新(P, "发送")
        加(n, 解析表达式(P))
        P.期望符(",", "`发送` 要写 `发送 通道, 值`")
        加(n, 解析表达式(P))
        P.吃换行()
        return n
    if 是关(t, "关闭"):
        P.吃()
        n = 新(P, "关闭")
        加(n, 解析表达式(P))
        P.吃换行()
        return n
    if 是关(t, "不安全"):
        P.吃()
        n = 新(P, "不安全")
        加(n, 解析块(P))
        P.吃换行()
        return n

    n = 新(P, "表达式语句")
    加(n, 解析表达式(P))
    if P.吃关("失败返回"):
        n.标志.add("失败返回")
    P.吃换行()
    return n


