def 解析块(P):
    起 = P.当前()
    n = 新(P, "块")
    if not P.期望符("{", "一块代码要用 { 开头"):
        return n
    P.吃换行()

    while not 是符(P.当前(), "}") and P.当前().种类 != 终:
        原位 = P.位
        if P.当前().种类 == 换:
            P.吃()
            continue
        加(n, 解析语句(P))
        if P.位 == 原位:                    # 一个词都没动，说明卡住了
            P.报错(P.当前(), "这一句看不懂，已跳过")
            P.吃()
    P.期望符("}", "一块代码要用 } 收尾")
    return n


def 解析模式(P):
    t = P.当前()
    文 = []
    括号深 = 0
    while P.当前().种类 != 终:
        if 括号深 == 0 and 是符(P.当前(), ":"):
            break
        if 括号深 == 0 and P.当前().种类 == 换:
            break
        if 是符(P.当前(), "("):
            括号深 += 1
        if 是符(P.当前(), ")"):
            括号深 -= 1
        if 括号深 < 0:
            break
        文.append(P.吃().文字)
    if not 文:
        P.报错(t, "`例` 后面要写一个模式，比如 `例 成功(值):`")
        return 新(P, "模式", "?")
    return 新(P, "模式", "".join(文))


