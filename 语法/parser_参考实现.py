def 解析外部(P, 标志=None):
    标志 = 标志 or set()
    关 = P.吃()
    n = 新(P, "外部")
    n.标志 |= set(标志)

    if P.吃关("类型"):
        名 = P.期望名("外部类型名")
        加(n, 新(P, "名字", 名.文字 if 名 else ""))
        P.吃换行()
        return n

    名 = P.当前()
    if not P.吃关("函数"):
        P.报错(名, "`外部` 后面要写 `函数` 或 `类型`，实际是 %s" % 说词(名))
        跳到行尾(P)
        return n
    函数名 = P.期望名("外部函数名")
    f = 新(P, "函数", 函数名.文字 if 函数名 else "")
    解析参数清单(P, f)
    if P.吃符("->"):
        加(f, 解析类型(P))
    P.吃换行()
    加(n, f)
    return n


def 解析宏(P, 标志=None):
    标志 = 标志 or set()
    关 = P.吃()
    n = 新(P, "宏")
    n.标志 |= set(标志)
    名 = P.期望名("宏名")
    if 名:
        n.文字 = 名.文字
    P.期望符("(", "宏的参数清单要用 ( 开头")
    if not 是符(P.当前(), ")"):
        while True:
            参 = P.期望名("宏的参数名")
            if 参:
                加(n, 新(P, "名字", 参.文字))
            if not P.吃符(","):
                break
    P.期望符(")", "宏的参数清单要用 ) 收尾")
    加(n, 解析块(P))
    P.吃换行()
    return n


def 解析顶层(P, 标志=None):
    t = P.当前()

    if 是关(t, "模块"):
        return 解析模块(P)
    if 是关(t, "引入"):
        return 解析引入(P)
    if 是关(t, "导出"):
        return 解析导出(P)
    if 是关(t, "函数") or 是关(t, "异步"):
        return 解析函数(P, 标志)
    if 是关(t, "结构"):
        return 解析结构(P, 标志)
    if 是关(t, "枚举"):
        return 解析枚举(P, 标志)
    if 是关(t, "接口"):
        return 解析接口(P, 标志)
    if 是关(t, "实现"):
        return 解析实现(P, 标志)
    if 是关(t, "常量") or 是关(t, "令") or 是声明开头(P):
        return 解析声明(P, 标志)
    if 是关(t, "外部"):
        return 解析外部(P, 标志)
    if 是关(t, "宏"):
        return 解析宏(P, 标志)

    if 是关(t, "编译期"):
        P.吃()
        n = 新(P, "编译期")
        加(n, 解析函数(P))
        return n

    if 是关(t, "测试"):
        P.吃()
        n = 新(P, "测试")
        名 = P.当前()
        if 名.种类 == 串:
            n.文字 = 名.文字
            P.吃()
        else:
            P.报错(名, "`测试` 后面要写一个用引号包起来的名字，比如 测试 \"加法应正确\" { }")
        加(n, 解析块(P))
        P.吃换行()
        return n

    P.报错(t, "顶层只能写 模块 / 引入 / 函数 / 结构 / 枚举 / 接口 / 实现 / 常量 / 测试 / 宏 / 外部，实际是 %s" % 说词(t))
    跳到行尾(P)
    return None


def 解析程序(P):
    根 = 新(P, "程序")
    P.吃换行()
    if 是关(P.当前(), "模块"):
        加(根, 解析模块(P))
    while P.当前().种类 != 终:
        if P.当前().种类 == 换:
            P.吃()
            continue
        原位 = P.位
        加(根, 解析顶层(P))
        if P.位 == 原位:
            P.报错(P.当前(), "这一行看不懂，已跳过")
            P.吃()
    return 根


