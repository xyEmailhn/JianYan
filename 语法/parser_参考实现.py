def 读路径(P):
    首 = P.期望名("模块路径")
    if not 首:
        return ""
    文 = 首.文字
    while P.吃符("."):
        段 = P.期望名("点号后面要跟名字")
        if not 段:
            break
        文 += "." + 段.文字
    return 文


def 跳到行尾(P):
    while P.当前().种类 not in (换, 终):
        if 是符(P.当前(), "}"):
            return
        P.吃()
    if P.当前().种类 == 换:
        P.吃()


def 解析模块(P):
    起 = P.吃()
    文 = 读路径(P)
    n = 新(P, "模块", 文)
    if not 文:
        跳到行尾(P)
    else:
        P.吃换行()
    return n


def 解析引入(P):
    起 = P.吃()
    n = 新(P, "引入", 读路径(P))
    if P.吃关("为"):
        别名 = P.期望名("别名")
        if 别名:
            加(n, 新(P, "名字", 别名.文字))
    if P.吃符("{"):
        while True:
            名 = P.期望名("要引入的名字")
            if 名:
                加(n, 新(P, "名字", 名.文字))
            if not P.吃符(","):
                break
        P.期望符("}", "要引入的名字清单要用 } 收尾")
    P.吃换行()
    return n


def 解析导出(P):
    起 = P.吃()
    n = 新(P, "导出", 读路径(P))
    P.吃换行()
    return n


def 解析泛型(P, 父):
    if not P.吃符("["):
        return
    while True:
        名 = P.期望名("泛型参数名")
        if not 名:
            break
        文 = 名.文字
        if P.吃符(":"):
            文 += ": "
            while True:
                约 = P.期望名("约束名（接口名）")
                if not 约:
                    break
                文 += 约.文字
                if not P.吃关("与"):
                    break
                文 += " 与 "
        加(父, 新(P, "泛型", 文))
        if not P.吃符(","):
            break
    P.期望符("]", "泛型参数清单要用 ] 收尾")


def 解析参数(P):
    if 是符(P.当前(), ")"):
        return None
    名 = P.期望名("参数名")
    if not 名:
        return None
    n = 新(P, "参数", 名.文字)
    P.期望符(":", "参数名后面要写冒号和类型")
    if P.吃关("借用"):
        n.标志.add("借用")
    if P.吃关("可变借用"):
        n.标志.add("可变借用")
    加(n, 解析类型(P))
    return n


def 解析参数清单(P, 函数节):
    P.期望符("(", "函数的参数清单要用 ( 开头")
    if not 是符(P.当前(), ")"):
        while True:
            参 = 解析参数(P)
            加(函数节, 参)
            if not P.吃符(","):
                break
    P.期望符(")", "参数清单要用 ) 收尾")


def 解析函数(P, 标志=None):
    标志 = 标志 or set()
    起 = P.当前()
    if P.吃关("异步"):
        标志.add("异步")
    关 = P.当前()
    if not P.吃关("函数"):
        P.报错(关, "这里应该写 `函数`，实际是 %s" % 说词(关))
        return None
    名 = P.期望名("函数名")
    n = 新(P, "函数", 名.文字 if 名 else "")
    n.标志 |= set(标志)

    解析泛型(P, n)
    解析参数清单(P, n)
    if P.吃符("->"):
        加(n, 解析类型(P))

    if P.吃符("="):
        体 = 新(P, "返回")
        加(体, 解析表达式(P))
        加(n, 体)
        P.吃换行()
    else:
        加(n, 解析块(P))
    return n


def 解析签名或函数(P):
    """接口里的函数：只有签名，或者带一个默认实现"""
    关 = P.吃()
    名 = P.期望名("函数名")
