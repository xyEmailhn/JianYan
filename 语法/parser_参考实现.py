def 类型清单(P):
    """括号里的类型清单，返回 ["整数", "字符串"] 这样的列表"""
    项 = []
    if 是符(P.当前(), "]") or 是符(P.当前(), ")"):
        return 项
    while True:
        项.append(类型文(P))
        if not P.吃符(","):
            break
    return 项


def 类型前缀(P):
    t = P.当前()

    if t.种类 == 关 and t.文字 in 基本类型词:
        P.吃()
        return t.文字

    if 是关(t, "自身"):          # 接口里的 Self
        P.吃()
        return t.文字

    if 是关(t, "通道"):          # 通道[整数] 既是类型也是构造
        P.吃()
        P.期望符("[", "通道要写明里面装什么类型，比如 通道[整数]")
        内 = 类型文(P)
        P.期望符("]", "通道的类型要用 ] 收尾")
        return "通道[" + 内 + "]"

    if 是关(t, "映射"):
        P.吃()
        P.期望符("[", "映射要写明键和值的类型")
        键 = 类型文(P)
        if P.吃符(","):
            pass
        else:
            P.期望符(",", "映射的键和值之间要写逗号")
        值 = 类型文(P)
        P.期望符("]", "映射的类型清单要用 ] 收尾")
        return "映射[%s, %s]" % (键, 值)

    if 是关(t, "可空") or 是关(t, "元组"):
        是空 = 是关(t, "可空")
        P.吃()
        P.期望符("[", "这种类型后面要跟方括号，比如 可空[整数]")
        if 是空:
            内 = 类型文(P)
        else:
            内 = ", ".join(类型清单(P))
        P.期望符("]", "类型清单要用 ] 收尾")
        return "%s[%s]" % (t.文字, 内)

    if 是关(t, "结果"):
        P.吃()
        P.期望符("[", "结果要写明成功值和错误原因的类型")
        成 = 类型文(P)
        if P.吃符(","):
            pass
        else:
            P.期望符(",", "成功类型和错误类型之间要写逗号")
        错 = 类型文(P)
        P.期望符("]", "类型清单要用 ] 收尾")
        return "结果[%s, %s]" % (成, 错)

    if 是关(t, "函数"):
        P.吃()
        P.期望符("(", "函数类型要写出参数")
        参 = ", ".join(类型清单(P))
        P.期望符(")", "参数清单要用 ) 收尾")
        文 = "函数(%s)" % 参
        if P.吃符("->"):
            文 += " -> " + 类型文(P)
        return 文

    if t.种类 == 标:
        名 = t.文字
        P.吃()
        if P.吃符("["):
            内 = 类型清单(P)
            P.期望符("]", "类型清单要用 ] 收尾")
            # 数组[整数] 是早期写法，等价于 整数 组。认它，但提醒一句
            if 名 == "数组" and len(内) == 1:
                P.警告.append((t.行, t.列, "`数组[%s]` 建议写成 `%s 组`，后一种是规范写法" % (内[0], 内[0])))
                return 内[0] + " 组"
            return "%s[%s]" % (名, ", ".join(内))
        return 名

    P.报错(t, "这里应该写一个类型（比如 整数、字符串、映射[字符串, 整数]），实际是 %s" % 说词(t))
    return "?"


def 类型文(P):
    """解析一个类型，返回它的规范文字。T 组 → "T 组"；数组[T] → "T 组" """
    文 = 类型前缀(P)
    while 是关(P.当前(), "组"):
        P.吃()
        文 += " 组"
        if P.吃符("["):
            t = P.当前()
            if t.种类 == 数:
                文 += t.文字
                P.吃()
            else:
                P.报错(t, "定长数组的方括号里要写个数")
            P.期望符("]", "定长数组的长度要用 ] 收尾")
            文 += "]"
    return 文


def 解析类型(P):
    t = P.当前()
    return 新(P, "类型", 类型文(P))


def 是类型开头(t):
    if t.种类 == 关 and t.文字 in 基本类型词:
        return True
    return t.种类 == 关 and t.文字 in {"映射", "可空", "结果", "元组", "函数", "通道", "自身"}


