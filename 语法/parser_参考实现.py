def 是函数类型声明(P):
    """`函数(` 开头：是函数类型的变量声明，还是匿名函数？试着读一遍类型再退回来"""
    if not (是关(P.当前(), "函数") and 是符(P.看(1), "(")):
        return False
    原位, 原错, 原警 = P.位, len(P.错误), len(P.警告)
    类型文(P)
    成立 = len(P.错误) == 原错 and P.当前().种类 == 标 and 是符(P.看(1), "=")
    P.位 = 原位
    del P.错误[原错:]
    del P.警告[原警:]
    return 成立


def 是声明开头(P):
    a = P.当前()
    if 是类型开头(a):
        if 是关(a, "函数"):
            return 是函数类型声明(P)
        return True
    if a.种类 != 标:
        return False

    b = P.看(1)
    if b.种类 == 标:
        return True
    if 是关(b, "组"):
        return True
    if 是符(b, "["):
        深 = 0
        i = P.位 + 1
        while i < len(P.词们):
            t = P.词们[i]
            if 是符(t, "["):
                深 += 1
            elif 是符(t, "]"):
                深 -= 1
                if 深 == 0:
                    i += 1
                    break
            elif t.种类 in (换, 终):
                return False
            i += 1
        if i >= len(P.词们):
            return False
        return P.词们[i].种类 == 标
    return False


