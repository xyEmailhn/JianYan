def 转义(s):
    return s.replace("\n", "\\n").replace("\t", "\\t").replace("\r", "\\r")


def 打印树(n, 深=0, 出=None):
    出 = 出 if 出 is not None else []
    行 = "  " * 深 + n.种类
    if n.文字:
        行 += " " + 转义(n.文字)
    标 = [名 for 名 in 标志顺序 if 名 in n.标志]
    if 标:
        行 += " [" + " ".join(标) + "]"
    出.append(行)

    最深 = 深
    for 子 in n.子:
        d = 打印树(子, 深 + 1, 出)
        if d > 最深:
            最深 = d
    return 最深


def 统计树(n, 计数, 深=0):
    计数[n.种类] = 计数.get(n.种类, 0) + 1
    最深 = 深
    for 子 in n.子:
        d = 统计树(子, 计数, 深 + 1)
        if d > 最深:
            最深 = d
    return 最深


