def 解析后缀(P):
    n = 解析基本(P)
    while True:
        t = P.当前()
        if 是符(t, "("):
            P.吃()
            c = 新(P, "调用")
            加(c, n)
            解析实参(P, c)
            P.期望符(")", "调用要用 ) 收尾")
            n = c
        elif 是符(t, "["):
            P.吃()
            x = 新(P, "下标")
            加(x, n)
            加(x, 解析表达式(P))
            P.期望符("]", "下标要用 ] 收尾")
            n = x
        elif 是符(t, "."):
            P.吃()
            m = 新(P, "成员")
            加(m, n)
            名 = P.期望成员名()
            if 名:
                m.文字 = 名.文字
            n = m
        else:
            break
    return n


def 解析花括号(P):
    起 = P.吃()
    P.吃换行()
    n = 新(P, "数组字面量")
    if P.吃符("}"):
        return n

    首 = 解析表达式(P)
    if P.吃符(":"):
        n.种类 = "映射字面量"
        加(n, 首)
        加(n, 解析表达式(P))
        while P.吃符(","):
            P.吃换行()
            if 是符(P.当前(), "}"):
                break
            加(n, 解析表达式(P))
            P.期望符(":", "映射的每一项都要写成 `键: 值`")
            加(n, 解析表达式(P))
    else:
        加(n, 首)
        while P.吃符(","):
            P.吃换行()
            if 是符(P.当前(), "}"):
                break
            加(n, 解析表达式(P))
    P.吃换行()
    P.期望符("}", "集合要用 } 收尾")
    return n


def 解析匿名函数(P):
    起 = P.吃()
    n = 新(P, "匿名函数")
    解析参数清单(P, n)
    if P.吃符("->"):
        加(n, 解析类型(P))
    if P.吃符("="):
        体 = 新(P, "返回")
        加(体, 解析表达式(P))
        加(n, 体)
    else:
        加(n, 解析块(P))
    return n


def 解析通道(P):
    起 = P.吃()
    n = 新(P, "通道")
    P.期望符("[", "通道要写明里面装什么类型，比如 通道[整数]")
    加(n, 解析类型(P))
    P.期望符("]", "通道的类型要用 ] 收尾")
    if P.吃符("("):
        if not 是符(P.当前(), ")"):
            加(n, 解析表达式(P))
        P.期望符(")", "通道的容量要用 ) 收尾")
    return n


def 解析基本(P):
    t = P.当前()

    if t.种类 in (数, 浮, 串):
        P.吃()
        种类 = {数: "整数", 浮: "浮点", 串: "字符串"}[t.种类]
        return 新(P, 种类, t.文字)

    if t.种类 == 标:
        P.吃()
        return 新(P, "名字", t.文字)

    if t.种类 == 关:
        if t.文字 in ("真", "假"):
            P.吃()
            return 新(P, t.文字)
        if t.文字 == "空":
            P.吃()
            return 新(P, "空")
        if t.文字 in ("借用", "可变借用", "复制", "移动", "等待", "接收"):
            P.吃()
            n = 新(P, t.文字)
            加(n, 解析一元(P))
            return n
        if t.文字 in ("成功", "失败"):
            P.吃()
            n = 新(P, t.文字)
            if P.吃符("("):
                加(n, 解析表达式(P))
                P.期望符(")", "成功/失败 的括号要用 ) 收尾")
            return n
        # 类型名后面跟括号是类型转换：整数(3.9)、字符串(端口)
        if t.文字 in 基本类型词 and 是符(P.看(1), "("):
            P.吃()
            return 新(P, "名字", t.文字)
        if t.文字 == "通道":
            return 解析通道(P)
        if t.文字 == "函数":
            return 解析匿名函数(P)

    if 是符(t, "("):
        P.吃()
        n = 解析表达式(P)
        P.期望符(")", "括号要用 ) 配对")
        return n
    if 是符(t, "{"):
        return 解析花括号(P)

    if t.种类 == 终:
        P.报错(t, "这里需要一个表达式，但文件已经结束了（可能是少了 }）")
    elif t.种类 == 换:
        P.报错(t, "这里需要一个表达式，但这一行已经结束")
    elif t.种类 == 错:
        P.报错(t, "这里有个词法错误，无法继续解析")
    else:
        P.报错(t, "这里需要一个表达式，实际是 %s" % 说词(t))

    if t.种类 not in (换, 终):
        P.吃()
    return 新(P, "错误")


