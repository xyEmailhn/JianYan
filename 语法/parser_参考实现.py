# 符号按长度从长到短排：先试三个字的，再试两个字的，最后试一个字的。
# 这就是"最长匹配"——<<< 必须被当成一个整体，不能拆成 << 和 <。
符号表 = ["<<<", ">>>", "..", "==", "!=", "<<", ">>", "<=", ">=", "->",
          "//", "^^", "~~", "(", ")", "{", "}", "[", "]", ",", ":", ".",
          "+", "-", "*", "/", "%", "^", "&", "|", "!", "~", "#", "=", "_"]


class 词:
    __slots__ = ("种类", "文字", "行", "列")

    def __init__(self, 种类, 文字, 行, 列):
        self.种类 = 种类
        self.文字 = 文字
        self.行 = 行
        self.列 = 列

    def __repr__(self):
        return "%s(%r)" % (self.种类, self.文字)


def 是汉字(c):
    o = ord(c)
    return 0x4E00 <= o <= 0x9FFF or 0x3400 <= o <= 0x4DBF or 0xF900 <= o <= 0xFAFF


def 是名字字符(c):
    return c.isalnum() or c == "_" or 是汉字(c)


def 切词(源):
    """把源码切成词。返回列表，最后一个一定是 终。"""
    词们 = []
    i, n = 0, len(源)
    行, 列 = 1, 1

    def 记(种类, 起点, 起行, 起列):
        词们.append(词(种类, 源[起点:i], 起行, 起列))

    while i < n:
        c = 源[i]

        # 空白（不含换行）
        if c in " \t\r":
            i += 1
            列 += 1
            continue

        # 换行：简言用它分隔语句，所以它是个正式的词
        if c == "\n":
            词们.append(词(换, "\n", 行, 列))
            i += 1
            行 += 1
            列 = 1
            continue

        # 注释：-- 到行末，--[[ ]] 到对应收尾
        if c == "-" and i + 1 < n and 源[i + 1] == "-":
            if 源.startswith("--[[", i):
                i += 4
                列 += 4
                while i < n and 源[i:i + 2] != "]]":
                    if 源[i] == "\n":
                        行 += 1
                        列 = 1
                    else:
                        列 += 1
                    i += 1
                i = min(i + 2, n)
                列 += 2
            else:
                while i < n and 源[i] != "\n":
                    i += 1
                    列 += 1
            continue

        # 长字符串 [[ 原样文本 ]]
        if 源[i:i + 2] == "[[":
            起, 起行, 起列 = i, 行, 列
            i += 2
            列 += 2
            while i < n and 源[i:i + 2] != "]]":
                if 源[i] == "\n":
                    行 += 1
                    列 = 1
                else:
                    列 += 1
                i += 1
            i = min(i + 2, n)
            记(串, 起, 起行, 起列)
            continue

        # 普通字符串 "..."，支持 \" \\ \n \t
        if c == '"':
            起, 起行, 起列 = i, 行, 列
            i += 1
            列 += 1
            while i < n and 源[i] != '"':
                if 源[i] == "\\" and i + 1 < n:
                    i += 2
                    列 += 2
                    continue
                if 源[i] == "\n":
                    行 += 1
                    列 = 1
                else:
                    列 += 1
                i += 1
            i = min(i + 1, n)
            记(串, 起, 起行, 起列)
            continue

        # 数字
        if c.isdigit():
            起, 起行, 起列 = i, 行, 列
            if 源[i:i + 2].lower() in ("0x", "0b"):
                i += 2
                while i < n and (源[i].isalnum() or 源[i] == "_"):
                    i += 1
                列 += i - 起
                记(数, 起, 起行, 起列)
                continue
            while i < n and (源[i].isdigit() or 源[i] == "_"):
                i += 1
                列 += 1
            是浮点 = False
            if i < n and 源[i] == "." and i + 1 < n and 源[i + 1].isdigit():
                是浮点 = True
                i += 1
                列 += 1
                while i < n and (源[i].isdigit() or 源[i] == "_"):
                    i += 1
                    列 += 1
            if i < n and 源[i] in "eE":
                后面 = 源[i + 1:i + 2]
                再后 = 源[i + 2:i + 3]
                if 后面.isdigit() or (后面 in "+-" and 再后.isdigit()):
                    是浮点 = True
                    i += 1
                    列 += 1
                    if i < n and 源[i] in "+-":
                        i += 1
                        列 += 1
                    while i < n and 源[i].isdigit():
                        i += 1
                        列 += 1
            记(浮 if 是浮点 else 数, 起, 起行, 起列)
            continue

        # 名字 / 关键字
        if 是名字字符(c):
            起, 起行, 起列 = i, 行, 列
            while i < n and 是名字字符(源[i]):
                i += 1
                列 += 1
            文 = 源[起:i]
            记(关 if 文 in 关键字集 else 标, 起, 起行, 起列)
            continue

        # 符号：最长匹配
        命中 = None
        for s in 符号表:
            if 源.startswith(s, i):
                命中 = s
                break
        if 命中:
            起, 起行, 起列 = i, 行, 列
            i += len(命中)
            列 += len(命中)
            记(符, 起, 起行, 起列)
            continue

        # 认不出来的字：照样产出一个词，别让程序卡住
        起, 起行, 起列 = i, 行, 列
        i += 1
        列 += 1
        记(错, 起, 起行, 起列)

    词们.append(词(终, "", 行, 列))
    return 词们


