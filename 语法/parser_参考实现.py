class 语法器:
    def __init__(self, 词们, 文件名):
        self.词们 = 词们
        self.位 = 0
        self.文件名 = 文件名
        self.错误 = []
        self.警告 = []
        self.静默 = False
        self.节点数 = 0

    # ---- 取词 ----
    def 当前(self):
        return self.词们[self.位]

    def 看(self, k):
        return self.词们[min(self.位 + k, len(self.词们) - 1)]

    def 吃(self):
        t = self.当前()
        if self.位 + 1 < len(self.词们):
            self.位 += 1
        return t

    def 吃符(self, s):
        if 是符(self.当前(), s):
            self.吃()
            return True
        return False

    def 吃关(self, s):
        if 是关(self.当前(), s):
            self.吃()
            return True
        return False

    def 吃换行(self):
        while self.当前().种类 == 换:
            self.吃()

    # ---- 报错 ----
    def 报错(self, t, 话):
        self.错误.append((t.行, t.列, 话))

    def 期望符(self, s, 为什么=""):
        if self.吃符(s):
            return True
        t = self.当前()
        self.报错(t, "这里应该写 `%s`（%s），实际是 %s" % (s, 为什么, 说词(t)))
        return False

    def 期望关(self, s, 为什么=""):
        if self.吃关(s):
            return True
        t = self.当前()
        self.报错(t, "这里应该写 `%s`（%s），实际是 %s" % (s, 为什么, 说词(t)))
        return False

    def 期望名(self, 为什么=""):
        t = self.当前()
        if t.种类 == 标:
            self.吃()
            return t
        if t.种类 == 关:
            self.报错(t, "这里需要一个名字（%s），但 `%s` 是语言保留的关键字，不能当名字用" % (为什么, t.文字))
        else:
            self.报错(t, "这里需要一个名字（%s），实际是 %s" % (为什么, 说词(t)))
        return None

    def 期望成员名(self):
        t = self.当前()
        if t.种类 in (标, 关):
            self.吃()
            return t
        self.报错(t, "点号后面要跟字段名或方法名，实际是 %s" % 说词(t))
        return None


def 是(t, 文):
    return t.文字 == 文


def 是关(t, 文):
    return t.种类 == 关 and t.文字 == 文


def 是符(t, 文):
    return t.种类 == 符 and t.文字 == 文


def 说词(t):
    if t.种类 == 终:
        return "文件结尾"
    if t.种类 == 换:
        return "换行"
    return "`%s`" % t.文字


def 新(P, 种类, 文字=""):
    P.节点数 += 1
    return 节(种类, 文字)


