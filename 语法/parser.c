/* ============================================================================
 *  第二部分：树节点长什么样
 *  ----------------------------------------------------------------------------
 *  一个节点只记三件事：
 *    1. 我是什么（种类）
 *    2. 我叫什么 / 我身上那段原文（文字）
 *    3. 我的孩子们（子、子数）
 *  文字不复制源码，只记"从哪儿开始、多长"，省内存也省时间。
 * ========================================================================== */

typedef struct 节点 节点;

struct 节点 {
    unsigned char 种类;      /* 节_xxx */
    unsigned 标志;           /* 标_xxx 的组合 */
    int 行, 列;              /* 在源码里的位置，报错用 */
    const char *文字;        /* 指向源码，或指向堆上的一段（类型名那种拼出来的） */
    int 文字长;
    unsigned char 文字堆;    /* 1 表示这段文字是 malloc 出来的，释放树时要 free */
    节点 **子;
    int 子数, 容量;
};

static long g_节点数 = 0;

static 节点 *新节点(节点种类 种类, int 行, int 列)
{
    节点 *n = (节点 *)calloc(1, sizeof(节点));
    if (!n) { fprintf(stderr, "内存不够了\n"); exit(3); }
    n->种类 = (unsigned char)种类;
    n->行 = 行;
    n->列 = 列;
    g_节点数++;
    return n;
}

/* 挂一个孩子。孩子多了就扩容，策略是"每次翻倍"，平均下来每个孩子只搬一次 */
static void 加子(节点 *父, 节点 *子)
{
    if (!子) return;
    if (父->子数 == 父->容量) {
        父->容量 = 父->容量 ? 父->容量 * 2 : 4;
        父->子 = (节点 **)realloc(父->子, sizeof(节点 *) * (size_t)父->容量);
        if (!父->子) { fprintf(stderr, "内存不够了\n"); exit(3); }
    }
    父->子[父->子数++] = 子;
}

/* 给节点挂一段"拼出来的文字"（比如 映射[字符串, 整数]）。这段文字是堆上的，得复制 */
static void 设文字(节点 *n, const char *文字, int 长度)
{
    char *p = (char *)malloc((size_t)长度 + 1);
    if (!p) { fprintf(stderr, "内存不够了\n"); exit(3); }
    memcpy(p, 文字, (size_t)长度);
    p[长度] = '\0';
    n->文字 = p;
    n->文字长 = 长度;
    n->文字堆 = 1;
}

/* 给节点挂一段"源码里的文字"，不复制，直接指过去 */
static void 指文字(节点 *n, const 词 *t)
{
    n->文字 = t->起点;
    n->文字长 = t->长度;
}

/* ============================================================================
 *  第三部分：拼字符串用的小工具
 *  ----------------------------------------------------------------------------
 *  类型要"拼"出来：映射 + [ + 字符串 + , + 整数 + ] → "映射[字符串, 整数]"
 *  直接拿 sprintf 拼会很难看，所以写个二十行的增长缓冲，够用一辈子。
 * ========================================================================== */

typedef struct {
    char *p;
    int 长, 容量;
} 文本;

static void 文本加(文本 *t, const char *s, int n)
{
    if (t->长 + n + 1 > t->容量) {
        int 新容量 = t->容量 ? t->容量 : 64;
        while (新容量 < t->长 + n + 1) 新容量 *= 2;
        t->p = (char *)realloc(t->p, (size_t)新容量);
        if (!t->p) { fprintf(stderr, "内存不够了\n"); exit(3); }
        t->容量 = 新容量;
    }
    memcpy(t->p + t->长, s, (size_t)n);
    t->长 += n;
    t->p[t->长] = '\0';
}

static void 文本放(文本 *t, const char *s)
{
    文本加(t, s, (int)strlen(s));
}

static void 文本加词(文本 *t, const 词 *k)
{
    文本加(t, k->起点, k->长度);
}

/* ============================================================================
 *  第四部分：语法分析器的状态
 *  ----------------------------------------------------------------------------
 *  做法叫"递归下降"：一条语法规则写成一个函数，函数里按顺序去"吃"词。
 *  吃到了就往后挪一格；不该出现的东西出现了，就报错。
 *
 *  为什么先把所有词读进数组？
 *    因为有几处要"往前看两个词"才能决定走哪条路，比如
 *        整数 甲 = 1         ← 声明
 *        甲 = 1              ← 赋值
 *    词都在数组里，往前看只是读一下下标，不用重新扫源码。
 * ========================================================================== */

typedef struct {
    词 *词们;
    int 词数;
    int 位;              /* 现在看到第几个词 */
    const char *源;
    int 源长;
    const char *文件名;
    int 错误数;
    int 警告数;
    int 静默;            /* 1 = 试读阶段，报错只计数不打印（用于"往回退一步"的试探） */
    节点 *根;
} 语法器;

static 词 *当前(语法器 *P) { return &P->词们[P->位]; }

/* 往前看第 k 个词（k=0 就是当前）。越界就停在最后一个词上，调用处不用管边界 */
static 词 *看(语法器 *P, int k)
{
    int i = P->位 + k;
    if (i >= P->词数) i = P->词数 - 1;
    if (i < 0) i = 0;
    return &P->词们[i];
}

/* 这个词的文字是不是 文？（比较的是字节，不看种类） */
static int 词是(const 词 *t, const char *文)
{
    int n = (int)strlen(文);
    return t->长度 == n && memcmp(t->起点, 文, (size_t)n) == 0;
}

static int 词是关(const 词 *t, const char *文) { return t->种类 == 词_关键字 && 词是(t, 文); }
static int 词是符(const 词 *t, const char *文) { return t->种类 == 词_符号 && 词是(t, 文); }

/* 吃一个词：返回它，并把位置往后挪一格 */
static 词 *吃(语法器 *P)
{
    词 *t = 当前(P);
    if (P->位 + 1 < P->词数) P->位++;
    return t;
}

static int 吃符(语法器 *P, const char *s)
{
    if (词是符(当前(P), s)) { 吃(P); return 1; }
    return 0;
}

static int 吃关(语法器 *P, const char *s)
{
    if (词是关(当前(P), s)) { 吃(P); return 1; }
    return 0;
}

/* 把连续的换行一次吃干净。简言用换行分隔语句，多几个空行不该报错 */
static void 吃换行(语法器 *P)
{
    while (当前(P)->种类 == 词_换行) 吃(P);
}

/* ============================================================================
 *  第五部分：报错
 *  ----------------------------------------------------------------------------
 *  报错是语法分析器的产品之一。好的报错要回答三个问题：
 *    哪儿错了？   → 文件名:行:列，还把那一行原文抄出来，底下画个箭头
 *    错在什么？   → "这里应该写 `{`"
 *    实际看到啥？ → "实际是 `继续`"
 * ========================================================================== */

/* 把第 行 的起点找出来（从文件头数换行符）。只在报错时调用，不用管快不快 */
static int 行首位置(const char *源, int 源长, int 行)
{
    int 当前行 = 1;
    for (int i = 0; i < 源长; i++) {
        if (当前行 == 行) return i;
        if (源[i] == '\n') 当前行++;
    }
    return 源长;
}

/* 从行首往后数 列-1 个"字"（一个汉字算一个，和词法器的列号规则一致），返回字节偏移 */
static int 按列找字节(const char *p, int 字节数, int 列)
{
    int i = 0, 字符 = 1;
    while (i < 字节数 && 字符 < 列) {
        unsigned char c = (unsigned char)p[i];
        int 宽 = 1;
        if (c >= 0xF0) 宽 = 4;
        else if (c >= 0xE0) 宽 = 3;
        else if (c >= 0xC0) 宽 = 2;
        i += 宽;
        字符++;
    }
    return i > 字节数 ? 字节数 : i;
}

static void 报错(语法器 *P, int 行, int 列, const char *格式, ...)
{
    char 话[512];
    va_list 参数;
    va_start(参数, 格式);
    vsnprintf(话, sizeof(话), 格式, 参数);
    va_end(参数);

    P->错误数++;
    if (P->静默) return;
    fprintf(stderr, "%s:%d:%d: 语法错误：%s\n", P->文件名, 行, 列, 话);

    /* 把出错那行抄出来，底下一个 ^ 指到列 */
    int 起 = 行首位置(P->源, P->源长, 行);
    int 止 = 起;
    while (止 < P->源长 && P->源[止] != '\n') 止++;
    if (止 > 起) {
        int 缩进 = fprintf(stderr, "  %d | ", 行);
        fwrite(P->源 + 起, 1, (size_t)(止 - 起), stderr);
        fputc('\n', stderr);
        for (int i = 0; i < 缩进; i++) fputc(' ', stderr);
        int 字节偏移 = 按列找字节(P->源 + 起, 止 - 起, 列);
        for (int i = 0; i < 字节偏移; i++) fputc(' ', stderr);
        fputs("^\n", stderr);
    }
}

static void 警告(语法器 *P, int 行, int 列, const char *格式, ...)
{
    char 话[512];
    va_list 参数;
    va_start(参数, 格式);
    vsnprintf(话, sizeof(话), 格式, 参数);
    va_end(参数);
    P->警告数++;
    if (P->静默) return;
    fprintf(stderr, "%s:%d:%d: 提示：%s\n", P->文件名, 行, 列, 话);
}

/* 给报错用：把"当前这个词"说成人话 */
static void 说词(const 词 *t, char *out, int 大小)
{
    if (t->种类 == 词_文件结束) { snprintf(out, (size_t)大小, "文件结尾"); return; }
    if (t->种类 == 词_换行)     { snprintf(out, (size_t)大小, "换行"); return; }
    int n = t->长度 < 40 ? t->长度 : 40;
    snprintf(out, (size_t)大小, "`%.*s`", n, t->起点);
}

/* 下面这些函数互相调用（比如"如果"里要解析表达式，"函数"里要解析块），
 * 先把名字报上来，C 才知道它们存在。这叫前向声明，C 里很常见。 */
static 节点 *解析表达式(语法器 *P);
static 节点 *解析常量(语法器 *P, unsigned 标志);
static 节点 *解析函数(语法器 *P, unsigned 标志);
static 节点 *解析语句(语法器 *P);
static void 跳到行尾(语法器 *P);

/* ============================================================================
 *  第六部分：吃不到就报错的小助手
 *  ----------------------------------------------------------------------------
 *  语法规则里到处是"这里必须是个左括号""这里必须是个名字"。
 *  把它们包成函数，解析代码就能写成一句人话：
 *      期望符(P, "{", "函数体要用 { 开头");
 * ========================================================================== */

static int 期望符(语法器 *P, const char *s, const char *为什么)
{
    if (吃符(P, s)) return 1;
    char 实际[64];
    说词(当前(P), 实际, sizeof(实际));
    报错(P, 当前(P)->行, 当前(P)->列, "这里应该写 `%s`（%s），实际是 %s", s, 为什么, 实际);
    return 0;
}

static int 期望关(语法器 *P, const char *s, const char *为什么)
{
    if (吃关(P, s)) return 1;
    char 实际[64];
    说词(当前(P), 实际, sizeof(实际));
    报错(P, 当前(P)->行, 当前(P)->列, "这里应该写 `%s`（%s），实际是 %s", s, 为什么, 实际);
    return 0;
}

/* 要一个名字。关键字不能拿来当名字，这是语言规则，不是实现偷懒 */
static 词 *期望名(语法器 *P, const char *为什么)
{
    词 *t = 当前(P);
    if (t->种类 == 词_标识符) { 吃(P); return t; }
    char 实际[64];
    说词(t, 实际, sizeof(实际));
    if (t->种类 == 词_关键字)
        报错(P, t->行, t->列, "这里需要一个名字（%s），但 `%.*s` 是语言保留的关键字，不能当名字用", 为什么, t->长度, t->起点);
    else
        报错(P, t->行, t->列, "这里需要一个名字（%s），实际是 %s", 为什么, 实际);
    return NULL;
}

/* ============================================================================
 *  第七部分：类型
 *  ----------------------------------------------------------------------------
 *  类型的语法是"前缀 + 后缀"两段：
 *      前缀：整数 / 映射[K,V] / 可空[T] / 函数(A)->R …
 *      后缀：组 / 组[10]        ← 所以"整数 组"读作"整数的组"
 *  解析完直接拼成一段规范文字存进节点，后面打印、报错都用它。
 * ========================================================================== */

static int 是基本类型词(const 词 *t)
{
    static const char *表[] = {
        "整数", "整数8", "整数16", "整数32", "整数64",
        "浮点", "布尔值", "字符串", "空值", "任意", "类型", NULL
    };
    if (t->种类 != 词_关键字) return 0;
    for (int i = 0; 表[i]; i++)
        if (词是(t, 表[i])) return 1;
    return 0;
}

static void 解析类型文(语法器 *P, 文本 *out);

/* 括号里的类型清单：T, T, T。返回个数 */
static int 解析类型清单(语法器 *P, 文本 *out)
{
    int 个数 = 0;
    if (词是符(当前(P), "]") || 词是符(当前(P), ")")) return 0;
    for (;;) {
        if (个数) 文本放(out, ", ");
        解析类型文(P, out);
        个数++;
        if (!吃符(P, ",")) break;
    }
    return 个数;
}

/* 前缀部分：整数、映射[...]、可空[...]、函数(...) -> ...
 * 返回 1 表示认出来了，0 表示"这不像类型"，让调用处去报错 */
static int 解析类型前缀(语法器 *P, 文本 *out)
{
    词 *t = 当前(P);

    if (是基本类型词(t)) {
        文本加词(out, t);
        吃(P);
        return 1;
    }

    /* 自身：接口/实现里指"当前这个类型"，相当于别的语言里的 Self */
    if (词是关(t, "自身")) {
        文本加词(out, t);
        吃(P);
        return 1;
    }

    /* 通道[整数]：既是类型（声明变量时写），也是构造（造通道时写） */
    if (词是关(t, "通道")) {
        文本加词(out, t);
        吃(P);
        期望符(P, "[", "通道要写明里面装什么类型，比如 通道[整数]");
        文本放(out, "[");
        解析类型文(P, out);
        期望符(P, "]", "通道的类型要用 ] 收尾");
        文本放(out, "]");
        return 1;
    }

    if (词是关(t, "映射")) {
        吃(P);
        文本放(out, "映射[");
        if (!期望符(P, "[", "映射要写明键和值的类型")) return 1;
        解析类型文(P, out);
        if (吃符(P, ",")) 文本放(out, ", "); else 期望符(P, ",", "映射的键和值之间要写逗号");
        解析类型文(P, out);
        期望符(P, "]", "映射的类型清单要用 ] 收尾");
        文本放(out, "]");
        return 1;
    }

    if (词是关(t, "可空") || 词是关(t, "元组")) {
        int 是可空 = 词是关(t, "可空");
        文本加词(out, t);
        吃(P);
        期望符(P, "[", "这种类型后面要跟方括号，比如 可空[整数]");
        文本放(out, "[");
        if (是可空) {
            解析类型文(P, out);
        } else {
            解析类型清单(P, out);
        }
        期望符(P, "]", "类型清单要用 ] 收尾");
        文本放(out, "]");
        return 1;
    }

    if (词是关(t, "结果")) {
        吃(P);
        文本放(out, "结果[");
        期望符(P, "[", "结果要写明成功值和错误原因的类型");
        解析类型文(P, out);
        if (吃符(P, ",")) 文本放(out, ", "); else 期望符(P, ",", "成功类型和错误类型之间要写逗号");
        解析类型文(P, out);
        期望符(P, "]", "类型清单要用 ] 收尾");
        文本放(out, "]");
        return 1;
    }

    if (词是关(t, "函数")) {
        吃(P);
        文本放(out, "函数(");
        期望符(P, "(", "函数类型要写出参数");
        解析类型清单(P, out);
        期望符(P, ")", "参数清单要用 ) 收尾");
        文本放(out, ")");
        if (吃符(P, "->")) {
            文本放(out, " -> ");
            解析类型文(P, out);
        }
        return 1;
    }

    if (t->种类 == 词_标识符) {
        int 是数组糖 = 词是(t, "数组");
        int 起点长 = out->长;
        文本加词(out, t);
        吃(P);
        if (吃符(P, "[")) {
            文本 内 = {0};
            int 个数 = 解析类型清单(P, &内);
            期望符(P, "]", "类型清单要用 ] 收尾");
            if (是数组糖 && 个数 == 1) {
                /* 数组[整数] 是早期写法，等价于 整数 组。认它，但提醒一句 */
                警告(P, t->行, t->列, "`数组[%.*s]` 建议写成 `%.*s 组`，后一种是规范写法",
                    内.长, 内.p ? 内.p : "", 内.长, 内.p ? 内.p : "");
                out->长 = 起点长;                      /* 把刚写进去的"数组"退掉 */
                if (out->p) out->p[起点长] = '\0';
                文本放(out, 内.p ? 内.p : "");
                文本放(out, " 组");
            } else {
                文本放(out, "[");
                文本放(out, 内.p ? 内.p : "");
                文本放(out, "]");
            }
            free(内.p);
        }
        return 1;
    }

    return 0;
}

static void 解析类型文(语法器 *P, 文本 *out)
{
    if (!解析类型前缀(P, out)) {
        char 实际[64];
        说词(当前(P), 实际, sizeof(实际));
        报错(P, 当前(P)->行, 当前(P)->列, "这里应该写一个类型（比如 整数、字符串、映射[字符串, 整数]），实际是 %s", 实际);
        文本放(out, "?");
        return;
    }

    /* 后缀：组 / 组[10] */
    while (词是关(当前(P), "组")) {
        吃(P);
        文本放(out, " 组");
        if (吃符(P, "[")) {
            文本放(out, "[");
            词 *数 = 当前(P);
            if (数->种类 == 词_整数) { 文本加词(out, 数); 吃(P); }
            else 报错(P, 数->行, 数->列, "定长数组的方括号里要写个数");
            期望符(P, "]", "定长数组的长度要用 ] 收尾");
            文本放(out, "]");
        }
    }
}

/* 解析一个类型，直接返回节点（文字就是规范写法） */
static 节点 *解析类型(语法器 *P)
{
    词 *起 = 当前(P);
    文本 t = {0};
    解析类型文(P, &t);
    节点 *n = 新节点(节_类型, 起->行, 起->列);
    设文字(n, t.p ? t.p : "?", t.长);
    free(t.p);
    return n;
}

/* 是不是"类型的开头"。用来区分 `整数 甲 = 1`（声明）和 `甲 = 1`（赋值） */
static int 是类型开头(const 词 *t)
{
    if (是基本类型词(t)) return 1;
    if (词是关(t, "映射") || 词是关(t, "可空") || 词是关(t, "结果")
        || 词是关(t, "元组") || 词是关(t, "函数")
        || 词是关(t, "通道") || 词是关(t, "自身")) return 1;
    return 0;
}

/* ============================================================================
 *  第八部分：模块、引入、导出
 *  ----------------------------------------------------------------------------
 *  模块路径是 `a.b.c` 这种点分名字，读进来拼成一段文字。
 * ========================================================================== */

static void 读路径(语法器 *P, 文本 *out)
{
    词 *首 = 期望名(P, "模块路径");
    if (!首) return;
    文本加词(out, 首);
    while (吃符(P, ".")) {
        词 *段 = 期望名(P, "点号后面要跟名字");
        if (!段) break;
        文本放(out, ".");
        文本加词(out, 段);
    }
}

static 节点 *解析模块(语法器 *P)
{
    词 *起 = 吃(P);                     /* 吃掉"模块" */
    节点 *n = 新节点(节_模块, 起->行, 起->列);
    文本 t = {0};
    读路径(P, &t);
    设文字(n, t.p ? t.p : "", t.长);
    free(t.p);
    if (t.长 == 0) 跳到行尾(P); else 吃换行(P);
    return n;
}

static 节点 *解析引入(语法器 *P)
{
    词 *起 = 吃(P);                     /* 吃掉"引入" */
    节点 *n = 新节点(节_引入, 起->行, 起->列);
    文本 t = {0};
    读路径(P, &t);
    设文字(n, t.p ? t.p : "", t.长);
    free(t.p);

    if (吃关(P, "为")) {
        词 *别名 = 期望名(P, "别名");
        if (别名) {
            节点 *a = 新节点(节_名字, 别名->行, 别名->列);
            指文字(a, 别名);
            加子(n, a);
        }
    }

    if (吃符(P, "{")) {
        for (;;) {
            词 *名 = 期望名(P, "要引入的名字");
            if (名) {
                节点 *a = 新节点(节_名字, 名->行, 名->列);
                指文字(a, 名);
                加子(n, a);
            }
            if (!吃符(P, ",")) break;
        }
        期望符(P, "}", "要引入的名字清单要用 } 收尾");
    }

    吃换行(P);
    return n;
}

static 节点 *解析导出(语法器 *P)
{
    词 *起 = 吃(P);
    节点 *n = 新节点(节_导出, 起->行, 起->列);
    文本 t = {0};
    读路径(P, &t);
    设文字(n, t.p ? t.p : "", t.长);
    free(t.p);
    吃换行(P);
    return n;
}

/* ============================================================================
 *  第九部分：函数、结构、枚举、接口、实现
 * ========================================================================== */

static 节点 *解析块(语法器 *P);          /* 下面才写，先打个招呼 */

/* 泛型参数：[T: 可比较, U: 可比较 与 可打印]
 * 每个参数一个孩子，文字写成 "T: 可比较" 这样一眼能看懂的样子 */
static void 解析泛型(语法器 *P, 节点 *父)
{
    if (!吃符(P, "[")) return;
    for (;;) {
        词 *名 = 期望名(P, "泛型参数名");
        if (!名) break;
        文本 t = {0};
        文本加词(&t, 名);
        if (吃符(P, ":")) {
            文本放(&t, ": ");
            for (;;) {
                词 *约 = 期望名(P, "约束名（接口名）");
                if (!约) break;
                文本加词(&t, 约);
                if (!吃关(P, "与")) break;
                文本放(&t, " 与 ");
            }
        }
        节点 *g = 新节点(节_泛型, 名->行, 名->列);
        设文字(g, t.p ? t.p : "", t.长);
        free(t.p);
        加子(父, g);
        if (!吃符(P, ",")) break;
    }
    期望符(P, "]", "泛型参数清单要用 ] 收尾");
}

/* 参数：名字: 类型 / 名字: 借用 类型 / 名字: 可变借用 类型 */
static 节点 *解析参数(语法器 *P)
{
    if (词是符(当前(P), ")")) return NULL;
    词 *名 = 期望名(P, "参数名");
    if (!名) return NULL;
    节点 *n = 新节点(节_参数, 名->行, 名->列);
    指文字(n, 名);
    期望符(P, ":", "参数名后面要写冒号和类型");
    if (吃关(P, "借用"))   n->标志 |= 标_借用;
    if (吃关(P, "可变借用")) n->标志 |= 标_可变借用;
    加子(n, 解析类型(P));
    return n;
}

/* 参数清单，挂在函数节点下面 */
static void 解析参数清单(语法器 *P, 节点 *函数节点)
{
    期望符(P, "(", "函数的参数清单要用 ( 开头");
    if (!词是符(当前(P), ")")) {
        for (;;) {
            节点 *p = 解析参数(P);
            if (p) 加子(函数节点, p);
            if (!吃符(P, ",")) break;
        }
    }
    期望符(P, ")", "参数清单要用 ) 收尾");
}

/* 函数：可以带 异步；可以有泛型；返回值可省（省了就是空值）
 * 函数体可以是块，也可以写成 `= 表达式`（一行函数） */
static 节点 *解析函数(语法器 *P, unsigned 标志)
{
    词 *起 = 当前(P);
    if (吃关(P, "异步")) 标志 |= 标_异步;
    词 *关 = 当前(P);
    if (!吃关(P, "函数")) {
        char 实际[64];
        说词(当前(P), 实际, sizeof(实际));
        报错(P, 当前(P)->行, 当前(P)->列, "这里应该写 `函数`，实际是 %s", 实际);
        return NULL;
    }
    词 *名 = 期望名(P, "函数名");
    节点 *n = 新节点(节_函数, 关->行, 关->列);
    n->标志 = 标志;
    if (名) 指文字(n, 名);
    (void)起;

    解析泛型(P, n);
    解析参数清单(P, n);
    if (吃符(P, "->")) 加子(n, 解析类型(P));

    if (吃符(P, "=")) {
        节点 *体 = 新节点(节_返回, 当前(P)->行, 当前(P)->列);
        加子(体, 解析表达式(P));
        加子(n, 体);
        吃换行(P);
    } else {
        加子(n, 解析块(P));
    }
    return n;
}

/* 结构：结构 名 [泛型] { 字段: 类型 ... } */
static 节点 *解析结构(语法器 *P, unsigned 标志)
{
    词 *关 = 吃(P);
    词 *名 = 期望名(P, "结构名");
    节点 *n = 新节点(节_结构, 关->行, 关->列);
    n->标志 = 标志;
    if (名) 指文字(n, 名);
    解析泛型(P, n);
    期望符(P, "{", "结构体要用 { 开头");
    吃换行(P);
    while (!词是符(当前(P), "}") && 当前(P)->种类 != 词_文件结束) {
        if (当前(P)->种类 == 词_换行) { 吃(P); continue; }
        词 *字段名 = 期望名(P, "字段名");
        if (!字段名) { 跳到行尾(P); continue; }
        节点 *f = 新节点(节_字段, 字段名->行, 字段名->列);
        指文字(f, 字段名);
        期望符(P, ":", "字段名后面要写冒号和类型");
        加子(f, 解析类型(P));
        吃换行(P);
        加子(n, f);
    }
    期望符(P, "}", "结构体要用 } 收尾");
    吃换行(P);
    return n;
}

/* 枚举：枚举 名 { 变体  变体(字段: 类型, ...) } */
static 节点 *解析枚举(语法器 *P, unsigned 标志)
{
    词 *关 = 吃(P);
    词 *名 = 期望名(P, "枚举名");
    节点 *n = 新节点(节_枚举, 关->行, 关->列);
    n->标志 = 标志;
    if (名) 指文字(n, 名);
    解析泛型(P, n);
    期望符(P, "{", "枚举要用 { 开头");
    吃换行(P);
    while (!词是符(当前(P), "}") && 当前(P)->种类 != 词_文件结束) {
        if (当前(P)->种类 == 词_换行) { 吃(P); continue; }
        词 *变体名 = 期望名(P, "变体名");
        if (!变体名) { 跳到行尾(P); continue; }
        节点 *v = 新节点(节_变体, 变体名->行, 变体名->列);
        指文字(v, 变体名);
        if (吃符(P, "(")) {
            if (!词是符(当前(P), ")")) {
                for (;;) {
                    词 *字段名 = 期望名(P, "变体字段名");
                    if (字段名) {
                        节点 *f = 新节点(节_字段, 字段名->行, 字段名->列);
                        指文字(f, 字段名);
                        期望符(P, ":", "变体字段名后面要写冒号和类型");
                        加子(f, 解析类型(P));
                        加子(v, f);
                    }
                    if (!吃符(P, ",")) break;
                }
            }
            期望符(P, ")", "变体的字段清单要用 ) 收尾");
        }
        吃换行(P);
        加子(n, v);
    }
    期望符(P, "}", "枚举要用 } 收尾");
    吃换行(P);
    return n;
}

/* 接口里的函数可以只写签名（不写函数体），也可以顺手给个默认实现。
 * 判断方法很直接：参数和返回类型后面如果是换行或 }，就是签名；是 { 就是有实现。 */
static 节点 *解析签名或函数(语法器 *P)
{
    词 *关 = 吃(P);                          /* 函数 */
    词 *名 = 期望名(P, "函数名");
    节点 *f = 新节点(节_函数, 关->行, 关->列);
    if (名) 指文字(f, 名);
    解析泛型(P, f);
    解析参数清单(P, f);
    if (吃符(P, "->")) 加子(f, 解析类型(P));

    if (当前(P)->种类 == 词_换行 || 词是符(当前(P), "}")) {
        吃换行(P);
        return f;                             /* 只有签名 */
    }
    加子(f, 解析块(P));
    吃换行(P);
    return f;
}

/* 接口：接口 名 [泛型] [继承 A, B] { 函数 签名 或 带默认实现的函数 } */
static 节点 *解析接口(语法器 *P, unsigned 标志)
{
    词 *关 = 吃(P);
    词 *名 = 期望名(P, "接口名");
    节点 *n = 新节点(节_接口, 关->行, 关->列);
    n->标志 = 标志;
    if (名) 指文字(n, 名);
    解析泛型(P, n);

    if (吃关(P, "继承")) {
        for (;;) {
            词 *父名 = 期望名(P, "被继承的接口名");
            if (父名) {
                节点 *a = 新节点(节_名字, 父名->行, 父名->列);
                指文字(a, 父名);
                加子(n, a);
            }
            if (!吃符(P, ",")) break;
        }
    }

    期望符(P, "{", "接口要用 { 开头");
    吃换行(P);
    while (!词是符(当前(P), "}") && 当前(P)->种类 != 词_文件结束) {
        if (当前(P)->种类 == 词_换行) { 吃(P); continue; }
        if (词是关(当前(P), "函数")) {
            节点 *f = 解析签名或函数(P);
            if (f) 加子(n, f);
        } else if (词是关(当前(P), "常量")) {
            加子(n, 解析常量(P, 0));
        } else {
            char 实际[64];
            说词(当前(P), 实际, sizeof(实际));
            报错(P, 当前(P)->行, 当前(P)->列, "接口里只能写函数签名或常量，实际是 %s", 实际);
            跳到行尾(P);
        }
    }
    期望符(P, "}", "接口要用 } 收尾");
    吃换行(P);
    return n;
}

/* 实现：实现 类型 为 接口1, 接口2 { 函数... } */
static 节点 *解析实现(语法器 *P, unsigned 标志)
{
    词 *关 = 吃(P);
    节点 *n = 新节点(节_实现, 关->行, 关->列);
    n->标志 = 标志;
    加子(n, 解析类型(P));
    期望关(P, "为", "实现后面要写 `为`，再接接口名");
    for (;;) {
        词 *名 = 期望名(P, "接口名");
        if (名) {
            节点 *a = 新节点(节_名字, 名->行, 名->列);
            指文字(a, 名);
            加子(n, a);
        }
        if (!吃符(P, ",")) break;
    }
    期望符(P, "{", "实现块要用 { 开头");
    吃换行(P);
    while (!词是符(当前(P), "}") && 当前(P)->种类 != 词_文件结束) {
        if (当前(P)->种类 == 词_换行) { 吃(P); continue; }
        if (词是关(当前(P), "函数") || 词是关(当前(P), "异步")) {
            节点 *f = 解析函数(P, 0);
            if (f) 加子(n, f);
        } else {
            char 实际[64];
            说词(当前(P), 实际, sizeof(实际));
            报错(P, 当前(P)->行, 当前(P)->列, "实现块里只能写函数，实际是 %s", 实际);
            跳到行尾(P);
        }
    }
    期望符(P, "}", "实现块要用 } 收尾");
    吃换行(P);
    return n;
}

/* ============================================================================
 *  第十部分：语句
 *  ----------------------------------------------------------------------------
 *  语句就是"一个动作"。简言不用分号，所以每条语句以换行结束。
 *  这里能看到递归下降最直观的样子：规则里写什么，代码里就是什么。
 * ========================================================================== */

/* 出错以后，跳到这一行末尾。这样一行只有一个错，不会因为一个括号
 * 引发后面十行连环报错（那是最让人恼火的编译器行为） */
static void 跳到行尾(语法器 *P)
{
    while (当前(P)->种类 != 词_换行 && 当前(P)->种类 != 词_文件结束) {
        if (词是符(当前(P), "}")) return;      /* 别把块的右括号吃掉了 */
        吃(P);
    }
    if (当前(P)->种类 == 词_换行) 吃(P);
}

static 节点 *解析块(语法器 *P)
{
    词 *起 = 当前(P);
    节点 *n = 新节点(节_块, 起->行, 起->列);
    if (!期望符(P, "{", "一块代码要用 { 开头")) return n;
    吃换行(P);

    while (!词是符(当前(P), "}") && 当前(P)->种类 != 词_文件结束) {
        int 原位 = P->位;
        if (当前(P)->种类 == 词_换行) { 吃(P); continue; }
        节点 *句 = 解析语句(P);
        加子(n, 句);
        if (P->位 == 原位) {              /* 一个词都没动，说明卡住了，跳过去避免死循环 */
            报错(P, 当前(P)->行, 当前(P)->列, "这一句看不懂，已跳过");
            吃(P);
        }
    }
    期望符(P, "}", "一块代码要用 } 收尾");
    return n;
}

/* 声明：常量 / 变量 / 令
 *   常量 整数 圆周率 = 3.14
 *   私有 数组[字符串] 词们 = ...
 *   不可变 令 比例 = 0.5
 *   令 x = 1                     ← 不带类型的推导声明
 */
static 节点 *解析声明(语法器 *P, unsigned 标志)
{
    词 *t = 当前(P);

    if (词是关(t, "令")) {
        吃(P);
        词 *名 = 期望名(P, "变量名");
        节点 *n = 新节点(节_令, t->行, t->列);
        n->标志 = 标志;
        if (名) 指文字(n, 名);
        if (期望符(P, "=", "令 声明要用 = 给出初值")) 加子(n, 解析表达式(P));
        吃换行(P);
        return n;
    }

    if (词是关(t, "常量")) {
        吃(P);
        节点 *n = 新节点(节_常量, t->行, t->列);
        n->标志 = 标志;
        加子(n, 解析类型(P));
        词 *名 = 期望名(P, "常量名");
        if (名) 指文字(n, 名);
        if (期望符(P, "=", "常量声明要用 = 给出值")) 加子(n, 解析表达式(P));
        吃换行(P);
        return n;
    }

    /* 剩下的就是"类型 名字 = 初值" */
    节点 *n = 新节点(节_变量, t->行, t->列);
    n->标志 = 标志;
    加子(n, 解析类型(P));
    词 *名 = 期望名(P, "变量名");
    if (名) 指文字(n, 名);
    if (吃符(P, "=")) {
        加子(n, 解析表达式(P));
    } else if (!标志) {
        期望符(P, "=", "变量声明要用 = 给出初值（不写初值就写 `令` 让它自己推导）");
    }
    吃换行(P);
    return n;
}

/* 常量单独包一层，是因为接口里要复用（接口可以声明常量） */
static 节点 *解析常量(语法器 *P, unsigned 标志) { return 解析声明(P, 标志); }

/* 语句开头的 `函数(` 有两种可能：
 *     函数(整数) -> 整数 f = ...      ← 函数类型的变量声明
 *     函数(x: 整数) -> 整数 { ... }    ← 匿名函数表达式
 * 分不清就"先按类型读一遍，读通了才算声明，否则原样退回去"。
 * 退回去这件事在解析器里叫回溯，会多花一点时间，但只在这一处用。 */
static int 是函数类型声明(语法器 *P)
{
    if (!(词是关(当前(P), "函数") && 词是符(看(P, 1), "("))) return 0;

    int 原位 = P->位, 原错 = P->错误数, 原警 = P->警告数, 原静默 = P->静默;
    P->静默 = 1;
    文本 t = {0};
    解析类型文(P, &t);
    free(t.p);
    int 成立 = (P->错误数 == 原错) && 当前(P)->种类 == 词_标识符 && 词是符(看(P, 1), "=");
    P->位 = 原位;
    P->错误数 = 原错;
    P->警告数 = 原警;
    P->静默 = 原静默;
    return 成立;
}

/* 这一句是不是"声明"？靠看前两个词判断：
 *   整数 甲   → 第一个是类型关键字，是声明
 *   词频项 甲 → 两个名字连在一起，是声明
 *   数组[T] 甲 → 名字 + 方括号 + 名字，是声明
 *   甲 = 1    → 名字后面是 =，是赋值语句
 */
static int 是声明开头(语法器 *P)
{
    词 *a = 当前(P);
    if (是类型开头(a)) {
        if (词是关(a, "函数")) return 是函数类型声明(P);
        return 1;
    }
    if (a->种类 != 词_标识符) return 0;

    词 *b = 看(P, 1);
    if (b->种类 == 词_标识符) return 1;
    if (词是关(b, "组")) return 1;

    if (词是符(b, "[")) {
        /* 跳过方括号，看紧跟其后的是不是一个名字 */
        int 深 = 0;
        int i = P->位 + 1;
        while (i < P->词数) {
            词 *t = &P->词们[i];
            if (词是符(t, "[")) 深++;
            else if (词是符(t, "]")) {
                深--;
                if (深 == 0) { i++; break; }
            } else if (t->种类 == 词_换行 || t->种类 == 词_文件结束) {
                return 0;
            }
            i++;
        }
        if (i >= P->词数) return 0;
        return P->词们[i].种类 == 词_标识符;
    }
    return 0;
}

/* 匹配的一条分支：例 模式 : 块
 * 模式先按文本存下来（比如 `失败(原因)`、`0~9`、`_`）。
 * 等以后做类型检查时，再把里面的名字拆出来变成真正的结构。 */
static 节点 *解析模式(语法器 *P)
{
    词 *起 = 当前(P);
    节点 *n = 新节点(节_模式, 起->行, 起->列);
    文本 t = {0};
    int 括号深 = 0;
    while (当前(P)->种类 != 词_文件结束) {
        if (括号深 == 0 && 词是符(当前(P), ":")) break;
        if (括号深 == 0 && 当前(P)->种类 == 词_换行) break;
        if (词是符(当前(P), "(")) 括号深++;
        if (词是符(当前(P), ")")) 括号深--;
        if (括号深 < 0) break;
        文本加词(&t, 吃(P));
    }
    if (t.长 == 0) {
        报错(P, 起->行, 起->列, "`例` 后面要写一个模式，比如 `例 成功(值):`");
        文本放(&t, "?");
    }
    设文字(n, t.p ? t.p : "?", t.长);
    free(t.p);
    return n;
}

static 节点 *解析匹配(语法器 *P)
{
    词 *关 = 吃(P);                       /* 匹配 */
    节点 *n = 新节点(节_匹配, 关->行, 关->列);
    加子(n, 解析表达式(P));
    期望符(P, "{", "匹配要用 { 包住所有分支");
    吃换行(P);

    while (!词是符(当前(P), "}") && 当前(P)->种类 != 词_文件结束) {
        if (当前(P)->种类 == 词_换行) { 吃(P); continue; }
        词 *t = 当前(P);
        if (词是关(t, "例")) {
            吃(P);
            节点 *支 = 新节点(节_例, t->行, t->列);
            加子(支, 解析模式(P));
            期望符(P, ":", "模式后面要写冒号，再接这一段要做什么");
            加子(支, 解析块(P));
            加子(n, 支);
        } else if (词是关(t, "默认")) {
            吃(P);
            节点 *支 = 新节点(节_默认, t->行, t->列);
            期望符(P, ":", "默认后面要写冒号，再接这一段要做什么");
            加子(支, 解析块(P));
            加子(n, 支);
        } else {
            char 实际[64];
            说词(t, 实际, sizeof(实际));
            报错(P, t->行, t->列, "匹配里只能写 `例 ...:` 或 `默认:`，实际是 %s", 实际);
            跳到行尾(P);
        }
    }
    期望符(P, "}", "匹配要用 } 收尾");
    吃换行(P);
    return n;
}

/* 如果 / 否则如果 / 否则
 * 关键点：`否则如果` 是一个词（词法器里就是整体），所以这里不用再看后面跟了啥 */
static 节点 *解析如果(语法器 *P)
{
    词 *关 = 吃(P);                       /* 如果 */
    节点 *n = 新节点(节_如果, 关->行, 关->列);
    加子(n, 解析表达式(P));
    期望关(P, "就", "`如果` 的条件后面要写 `就`");
    加子(n, 解析块(P));

    while (词是关(当前(P), "否则如果")) {
        词 *t = 吃(P);
        节点 *支 = 新节点(节_否则如果, t->行, t->列);
        加子(支, 解析表达式(P));
        期望关(P, "就", "`否则如果` 的条件后面要写 `就`");
        加子(支, 解析块(P));
        加子(n, 支);
    }

    if (词是关(当前(P), "否则")) {
        词 *t = 吃(P);
        节点 *支 = 新节点(节_否则, t->行, t->列);
        加子(支, 解析块(P));
        加子(n, 支);
    }
    吃换行(P);
    return n;
}

static 节点 *解析当(语法器 *P)
{
    词 *关 = 吃(P);
    节点 *n = 新节点(节_当, 关->行, 关->列);
    加子(n, 解析表达式(P));
    期望关(P, "就", "`当` 的条件后面要写 `就`");
    加子(n, 解析块(P));
    吃换行(P);
    return n;
}

static 节点 *解析重复(语法器 *P)
{
    词 *关 = 吃(P);                       /* 重复循环直到 */
    节点 *n = 新节点(节_重复, 关->行, 关->列);
    加子(n, 解析表达式(P));
    加子(n, 解析块(P));
    吃换行(P);
    return n;
}

/* 对 的两种写法：
 *   对 i: 1~5 { }              数着圈跑
 *   对 i: 1~5, 步长: 2 { }     隔一个跑一次
 *   对 词 在 词们 { }           把数组里的东西一个个拿出来
 *   对 键, 值 在 表 { }         映射同时给键和值
 */
static 节点 *解析对(语法器 *P)
{
    词 *关 = 吃(P);
    节点 *n = 新节点(节_对, 关->行, 关->列);

    词 *名 = 期望名(P, "循环变量名");
    if (名) 指文字(n, 名);

    if (吃符(P, ",")) {
        词 *名2 = 期望名(P, "第二个循环变量名");
        if (名2) {
            节点 *b = 新节点(节_名字, 名2->行, 名2->列);
            指文字(b, 名2);
            加子(n, b);
        }
    }

    if (吃符(P, ":")) {
        n->标志 |= 标_范围;
        加子(n, 解析表达式(P));
        if (期望符(P, "~", "范围要用 ~ 连接起点和终点")) {
            加子(n, 解析表达式(P));
        }
        if (吃符(P, ",") && !词是关(当前(P), "步长")) {
            报错(P, 当前(P)->行, 当前(P)->列, "范围循环的逗号后面只能写 `步长: 数字`");
        }
        if (吃关(P, "步长")) {
            n->标志 |= 标_步长;
            期望符(P, ":", "`步长` 后面要写冒号");
            加子(n, 解析表达式(P));
        }
    } else if (吃关(P, "在")) {
        n->标志 |= 标_遍历;
        加子(n, 解析表达式(P));
    } else {
        char 实际[64];
        说词(当前(P), 实际, sizeof(实际));
        报错(P, 当前(P)->行, 当前(P)->列,
             "`对` 后面要么写 `: 起点~终点`，要么写 `在 容器`，实际是 %s", 实际);
    }

    加子(n, 解析块(P));
    吃换行(P);
    return n;
}

static 节点 *解析语句(语法器 *P)
{
    词 *t = 当前(P);

    /* --- 带前缀修饰的声明 --- */
    if (词是关(t, "私有")) {
        吃(P);
        if ((词是关(当前(P), "函数") && !词是符(看(P, 1), "("))
            || 词是关(当前(P), "结构") || 词是关(当前(P), "枚举")
            || 词是关(当前(P), "接口") || 词是关(当前(P), "实现")) {
            报错(P, t->行, t->列, "`私有` 只能修饰变量、常量、令 或顶层的定义");
            跳到行尾(P);
            return NULL;
        }
        return 解析声明(P, 标_私有);
    }
    if (词是关(t, "不可变")) {
        吃(P);
        return 解析声明(P, 标_不可变);
    }

    /* --- 声明 --- */
    if (词是关(t, "常量") || 词是关(t, "令") || 是声明开头(P))
        return 解析声明(P, 0);

    /* --- 控制流 --- */
    if (词是关(t, "返回")) {
        吃(P);
        节点 *n = 新节点(节_返回, t->行, t->列);
        if (当前(P)->种类 != 词_换行 && !词是符(当前(P), "}")) 加子(n, 解析表达式(P));
        吃换行(P);
        return n;
    }
    if (词是关(t, "如果"))   return 解析如果(P);
    if (词是关(t, "当"))     return 解析当(P);
    if (词是关(t, "重复循环直到")) return 解析重复(P);
    if (词是关(t, "对"))     return 解析对(P);
    if (词是关(t, "匹配"))   return 解析匹配(P);
    if (词是关(t, "循环")) {
        吃(P);
        节点 *n = 新节点(节_循环, t->行, t->列);
        加子(n, 解析块(P));
        吃换行(P);
        return n;
    }

    if (词是关(t, "打断") || 词是关(t, "继续")) {
        吃(P);
        节点 *n = 新节点(词是关(t, "打断") ? 节_打断 : 节_继续, t->行, t->列);
        吃换行(P);
        return n;
    }

    /* --- 并发 --- */
    if (词是关(t, "线程")) {
        吃(P);
        节点 *n = 新节点(节_线程, t->行, t->列);
        加子(n, 解析块(P));
        吃换行(P);
        return n;
    }
    if (词是关(t, "发送")) {
        吃(P);
        节点 *n = 新节点(节_发送, t->行, t->列);
        加子(n, 解析表达式(P));
        期望符(P, ",", "`发送` 要写 `发送 通道, 值`");
        加子(n, 解析表达式(P));
        吃换行(P);
        return n;
    }
    if (词是关(t, "关闭")) {
        吃(P);
        节点 *n = 新节点(节_关闭, t->行, t->列);
        加子(n, 解析表达式(P));
        吃换行(P);
        return n;
    }
    if (词是关(t, "不安全")) {
        吃(P);
        节点 *n = 新节点(节_不安全, t->行, t->列);
        加子(n, 解析块(P));
        吃换行(P);
        return n;
    }

    /* --- 表达式语句 --- */
    节点 *n = 新节点(节_表达式语句, t->行, t->列);
    加子(n, 解析表达式(P));
    if (吃关(P, "失败返回")) n->标志 |= 标_失败返回;
    吃换行(P);
    return n;
}

/* ============================================================================
 *  第十一部分：表达式
 *  ----------------------------------------------------------------------------
 *  表达式是语法里最难的一段，因为要处理"谁先算"。
 *  办法很朴素：把优先级表格从低到高，一级写一个函数，低的函数调用高的函数。
 *
 *      赋值  =  拼接  ["=" 赋值]
 *      拼接  =  或  {".." 或}
 *      或    =  与  {"或" 与}
 *      ...
 *      一元  =  (非|!|#|~~|-|+) 一元 | 幂
 *      幂    =  后缀 ["^" 幂]
 *      后缀  =  基本 {"(" ... ")" | "[" ... "]" | "." 名字}
 *
 *  每个函数都是"先要一个更紧的，然后看后面还有没有同级运算"。
 *  "或"比"与"松，所以"或"函数调用"与"函数——这一条就决定了 a 或 b 与 c 是 a 或 (b 与 c)。
 * ========================================================================== */

static 节点 *造二元(节点 *左, 节点 *右, const 词 *运算)
{
    节点 *n = 新节点(节_二元, 运算->行, 运算->列);
    指文字(n, 运算);              /* 运算符直接指向源码，不用复制 */
    加子(n, 左);
    加子(n, 右);
    return n;
}

