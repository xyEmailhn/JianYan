/* 赋值是右结合：a = b = c 读作 a = (b = c)，先算右边 */
static 节点 *解析赋值(语法器 *P)
{
    节点 *左 = 解析拼接(P);
    if (词是符(当前(P), "=")) {
        词 *符 = 吃(P);
        节点 *n = 新节点(节_赋值, 符->行, 符->列);
        指文字(n, 符);
        加子(n, 左);
        加子(n, 解析赋值(P));
        return n;
    }
    return 左;
}

/* 一个通用的左结合循环：解析下一级，然后"只要还看到这几个符号，就继续往左挂" */
static 节点 *左结合(语法器 *P, 节点 *(*下一级)(语法器 *), const char **符号们, int 符号数)
{
    节点 *左 = 下一级(P);
    for (;;) {
        词 *t = 当前(P);
        if (t->种类 != 词_符号 && t->种类 != 词_关键字) break;
        int 命中 = 0;
        for (int i = 0; i < 符号数; i++)
            if (词是(t, 符号们[i])) { 命中 = 1; break; }
        if (!命中) break;

        吃(P);
        节点 *右 = 下一级(P);
        左 = 造二元(左, 右, t);
    }
    return 左;
}

