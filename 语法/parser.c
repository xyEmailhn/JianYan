static 节点 *解析位或(语法器 *P) { static const char *表[] = { "|" }; return 左结合(P, 解析位异或, 表, 1); }
static 节点 *解析位异或(语法器 *P) { static const char *表[] = { "^^" }; return 左结合(P, 解析位与, 表, 1); }
static 节点 *解析位与(语法器 *P) { static const char *表[] = { "&" }; return 左结合(P, 解析相等, 表, 1); }
static 节点 *解析相等(语法器 *P) { static const char *表[] = { "==", "!=" }; return 左结合(P, 解析比较, 表, 2); }
static 节点 *解析比较(语法器 *P) { static const char *表[] = { "<<", ">>", "<=", ">=" }; return 左结合(P, 解析移位, 表, 4); }
static 节点 *解析移位(语法器 *P) { static const char *表[] = { "<<<", ">>>" }; return 左结合(P, 解析加法, 表, 2); }
static 节点 *解析加法(语法器 *P) { static const char *表[] = { "+", "-" }; return 左结合(P, 解析乘法, 表, 2); }
static 节点 *解析乘法(语法器 *P) { static const char *表[] = { "*", "/", "//", "%" }; return 左结合(P, 解析一元, 表, 4); }

/* 一元：符号在前，只作用于紧跟着的那一个东西。-甲 是"负的甲"，不是"负的甲加乙" */
static 节点 *解析一元(语法器 *P)
{
    词 *t = 当前(P);
    int 是一元 = 0;
    if (t->种类 == 词_关键字 && 词是(t, "非")) 是一元 = 1;
    else if (t->种类 == 词_符号
             && (词是(t, "!") || 词是(t, "#") || 词是(t, "~~")
                 || 词是(t, "-") || 词是(t, "+"))) 是一元 = 1;

    if (是一元) {
        吃(P);
        节点 *n = 新节点(节_一元, t->行, t->列);
        指文字(n, t);
        加子(n, 解析一元(P));
        return n;
    }
    return 解析幂(P);
}

/* 乘方右结合：2^3^2 = 2^(3^2)，和数学课本一致 */
static 节点 *解析幂(语法器 *P)
{
    节点 *左 = 解析后缀(P);
    if (词是符(当前(P), "^")) {
        词 *符 = 吃(P);
        节点 *n = 新节点(节_二元, 符->行, 符->列);
        指文字(n, 符);
        加子(n, 左);
        加子(n, 解析幂(P));
        return n;
    }
    return 左;
}

/* 成员名的宽容：`值.布尔(真)` 里的"布尔"、`值.空值` 里的"空值"在词法上是关键字，
 * 但它们作为结构体字段名、枚举变体名是好名字，所以这里两种都收 */
static 词 *期望成员名(语法器 *P)
{
    词 *t = 当前(P);
    if (t->种类 == 词_标识符 || t->种类 == 词_关键字) { 吃(P); return t; }
    char 实际[64];
    说词(t, 实际, sizeof(实际));
    报错(P, t->行, t->列, "点号后面要跟字段名或方法名，实际是 %s", 实际);
    return NULL;
}

static void 解析实参(节点 *父, 语法器 *P)
{
    if (词是符(当前(P), ")")) return;
    for (;;) {
        加子(父, 解析表达式(P));
        if (!吃符(P, ",")) break;
        吃换行(P);
    }
}

/* 后缀：一个东西后面挂括号、方括号、点号。可以一直挂下去：a.b(1)[2].c */
static 节点 *解析后缀(语法器 *P)
{
    节点 *n = 解析基本(P);
    for (;;) {
        词 *t = 当前(P);
        if (词是符(t, "(")) {
            吃(P);
            节点 *c = 新节点(节_调用, t->行, t->列);
            加子(c, n);
            解析实参(c, P);
            期望符(P, ")", "调用要用 ) 收尾");
            n = c;
        } else if (词是符(t, "[")) {
            吃(P);
            节点 *x = 新节点(节_下标, t->行, t->列);
            加子(x, n);
            加子(x, 解析表达式(P));
            期望符(P, "]", "下标要用 ] 收尾");
            n = x;
        } else if (词是符(t, ".")) {
            吃(P);
            节点 *m = 新节点(节_成员, t->行, t->列);
            加子(m, n);
            词 *名 = 期望成员名(P);
            if (名) 指文字(m, 名);
            n = m;
        } else {
            break;
        }
    }
    return n;
}

/* 花括号：可能是数组 {1, 2, 3}，也可能是映射 {"a": 1}。看第一个后面有没有冒号 */
static 节点 *解析花括号(语法器 *P)
{
    词 *起 = 吃(P);                          /* { */
    吃换行(P);

    节点 *n = 新节点(节_数组字面量, 起->行, 起->列);
    if (吃符(P, "}")) return n;              /* 空集合 */

    节点 *首 = 解析表达式(P);
    if (吃符(P, ":")) {
        n->种类 = 节_映射字面量;
        加子(n, 首);
        加子(n, 解析表达式(P));
        while (吃符(P, ",")) {
            吃换行(P);
            if (词是符(当前(P), "}")) break;   /* 允许最后多一个逗号 */
            加子(n, 解析表达式(P));
            期望符(P, ":", "映射的每一项都要写成 `键: 值`");
            加子(n, 解析表达式(P));
        }
    } else {
        加子(n, 首);
        while (吃符(P, ",")) {
            吃换行(P);
            if (词是符(当前(P), "}")) break;
            加子(n, 解析表达式(P));
        }
    }
    吃换行(P);
    期望符(P, "}", "集合要用 } 收尾");
    return n;
}

/* 匿名函数：函数(甲: 整数) -> 整数 { 返回 甲 + 1 }
 * 它本身就是个表达式，所以能直接当参数传：数组.过滤(函数(x) -> 布尔值 { ... }) */
static 节点 *解析匿名函数(语法器 *P)
{
    词 *起 = 吃(P);                          /* 函数 */
    节点 *n = 新节点(节_匿名函数, 起->行, 起->列);
    解析参数清单(P, n);
    if (吃符(P, "->")) 加子(n, 解析类型(P));
    if (吃符(P, "=")) {
        节点 *体 = 新节点(节_返回, 当前(P)->行, 当前(P)->列);
        加子(体, 解析表达式(P));
        加子(n, 体);
    } else {
        加子(n, 解析块(P));
    }
    return n;
}

/* 通道[整数](10)：类型写在方括号里，容量写在圆括号里（可省） */
static 节点 *解析通道(语法器 *P)
{
    词 *起 = 吃(P);                          /* 通道 */
    节点 *n = 新节点(节_通道, 起->行, 起->列);
    期望符(P, "[", "通道要写明里面装什么类型，比如 通道[整数]");
    加子(n, 解析类型(P));
    期望符(P, "]", "通道的类型要用 ] 收尾");
    if (吃符(P, "(")) {
        if (!词是符(当前(P), ")")) 加子(n, 解析表达式(P));
        期望符(P, ")", "通道的容量要用 ) 收尾");
    }
    return n;
}

/* 一个"最基本的东西"：字面量、名字、括号、花括号、几个带前缀的关键字 */
static 节点 *解析基本(语法器 *P)
{
    词 *t = 当前(P);

    /* --- 字面量 --- */
    if (t->种类 == 词_整数 || t->种类 == 词_浮点 || t->种类 == 词_字符串) {
        吃(P);
        节点 *n = 新节点(t->种类 == 词_整数 ? 节_整数
                         : t->种类 == 词_浮点 ? 节_浮点 : 节_字符串,
                         t->行, t->列);
        指文字(n, t);
        return n;
    }

    /* --- 名字 --- */
    if (t->种类 == 词_标识符) {
        吃(P);
        节点 *n = 新节点(节_名字, t->行, t->列);
        指文字(n, t);
        return n;
    }

    /* --- 关键字 --- */
    if (t->种类 == 词_关键字) {
        if (词是(t, "真") || 词是(t, "假")) {
            吃(P);
            return 新节点(词是(t, "真") ? 节_真 : 节_假, t->行, t->列);
        }
        if (词是(t, "空")) {
            吃(P);
            return 新节点(节_空, t->行, t->列);
        }
        if (词是(t, "借用") || 词是(t, "可变借用") || 词是(t, "复制")
            || 词是(t, "移动") || 词是(t, "等待") || 词是(t, "接收")) {
            吃(P);
            节点种类 种 = 节_借用;
            if (词是(t, "可变借用")) 种 = 节_可变借用;
            else if (词是(t, "复制")) 种 = 节_复制;
            else if (词是(t, "移动")) 种 = 节_移动;
            else if (词是(t, "等待")) 种 = 节_等待;
            else if (词是(t, "接收")) 种 = 节_接收;
            节点 *n = 新节点(种, t->行, t->列);
            加子(n, 解析一元(P));
            return n;
        }
        if (词是(t, "成功") || 词是(t, "失败")) {
            吃(P);
            节点 *n = 新节点(词是(t, "成功") ? 节_成功 : 节_失败, t->行, t->列);
            if (吃符(P, "(")) {
                加子(n, 解析表达式(P));
                期望符(P, ")", "成功/失败 的括号要用 ) 收尾");
            }
            return n;
        }
        /* 类型名后面跟括号，是"类型转换"，写法像函数调用：整数(3.9)、字符串(端口)。
         * 这是规范里定的显式转换，不写就会报"禁止隐式转换"。 */
        if (是基本类型词(t) && 词是符(看(P, 1), "(")) {
            吃(P);
            节点 *n = 新节点(节_名字, t->行, t->列);
            指文字(n, t);
            return n;
        }
        if (词是(t, "通道")) return 解析通道(P);
        if (词是(t, "函数")) return 解析匿名函数(P);

        /* 新建 点{ x: 1.0, y: 2.0 }
         *
         * 为什么非要有这三个字？因为 `点{1, 2}` 在语句开头根本分不开：
         * 解析器看见 `点` 是个名字，后面紧跟的 `{` 只能当代码块，
         * 于是写成 `点{1,2}` 会被拆成"名字 点 + 一块 { 1, 2 }"。
         * 光靠"期望类型"（`点 p = {1,2}`）能覆盖声明位置，
         * 但表达式位置——`球们.追加(点{0,0})`、`返回 点{1,1}`——就没了指望。
         * 加一个关键字，让"我要构造某个结构体"这件事显式写出来，歧义从根上消失。
         * （规范 §18.7 悬了很久，这里拍板。） */
        if (词是(t, "新建")) {
            吃(P);
            词 *名 = 期望名(P, "结构体名");
            节点 *n = 新节点(节_结构字面量, t->行, t->列);
            if (名) 指文字(n, 名);
            if (!期望符(P, "{", "新建 后面要跟 `{ 字段: 值 }`")) return n;

            吃换行(P);
            if (吃符(P, "}")) return n;

            for (;;) {
                /* 两种写法都收：
                 *   新建 点{ x: 1.0, y: 2.0 }      ← 按名字，字段顺序随便
                 *   新建 点{ 1.0, 2.0 }            ← 按声明顺序
                 * 判断方法：标识符后面紧跟冒号，就是"名字: 值"。 */
                if ((当前(P)->种类 == 词_标识符 || 当前(P)->种类 == 词_关键字)
                    && 词是符(看(P, 1), ":")) {
                    词 *k = 吃(P);
                    吃(P);                            /* : */
                    节点 *项 = 新节点(节_字段, k->行, k->列);
                    指文字(项, k);
                    加子(项, 解析表达式(P));
                    加子(n, 项);
                } else {
                    加子(n, 解析表达式(P));
                }
                if (!吃符(P, ",")) break;
                吃换行(P);
                if (词是符(当前(P), "}")) break;         /* 允许最后多一个逗号 */
            }
            吃换行(P);
            期望符(P, "}", "结构体字面量要用 } 收尾");
            return n;
        }
    }

    /* --- 符号开头 --- */
    if (词是符(t, "(")) {
        吃(P);
        节点 *n = 解析表达式(P);
        期望符(P, ")", "括号要用 ) 配对");
        return n;
    }
    if (词是符(t, "{")) return 解析花括号(P);

    /* --- 到这儿都不认识：报错，给个占位节点，别让程序崩 --- */
    char 实际[64];
    说词(t, 实际, sizeof(实际));
    if (t->种类 == 词_文件结束)
        报错(P, t->行, t->列, "这里需要一个表达式，但文件已经结束了（可能是少了 }）");
    else if (t->种类 == 词_换行)
        报错(P, t->行, t->列, "这里需要一个表达式，但这一行已经结束");
    else if (t->种类 == 词_错误)
        报错(P, t->行, t->列, "这里有个词法错误，无法继续解析");
    else
        报错(P, t->行, t->列, "这里需要一个表达式，实际是 %s", 实际);

    if (t->种类 != 词_换行 && t->种类 != 词_文件结束) 吃(P);
    return 新节点(节_错误, t->行, t->列);
}

/* ============================================================================
 *  第十二部分：顶层
 *  ----------------------------------------------------------------------------
 *  顶层就是"文件里最外层能写的东西"：模块、引入、函数、结构、常量……
 *  ========================================================================== */

static 节点 *解析外部(语法器 *P, unsigned 标志)
{
    词 *关 = 吃(P);                          /* 外部 */
    节点 *n = 新节点(节_外部, 关->行, 关->列);
    n->标志 = 标志;

    if (吃关(P, "类型")) {
        词 *名 = 期望名(P, "外部类型名");
        节点 *a = 新节点(节_名字, 名 ? 名->行 : 关->行, 名 ? 名->列 : 关->列);
        if (名) 指文字(a, 名);
        加子(n, a);
        吃换行(P);
        return n;
    }

    /* 外部函数：只有签名，没有函数体，由 C 那边提供实现 */
    词 *名 = 当前(P);
    if (!吃关(P, "函数")) {
        char 实际[64];
        说词(名, 实际, sizeof(实际));
        报错(P, 名->行, 名->列, "`外部` 后面要写 `函数` 或 `类型`，实际是 %s", 实际);
        跳到行尾(P);
        return n;
    }
    词 *函数名 = 期望名(P, "外部函数名");
    节点 *f = 新节点(节_函数, 名->行, 名->列);
    if (函数名) 指文字(f, 函数名);
    解析参数清单(P, f);
    if (吃符(P, "->")) 加子(f, 解析类型(P));
    吃换行(P);
    加子(n, f);
    return n;
}

static 节点 *解析宏(语法器 *P, unsigned 标志)
{
    词 *关 = 吃(P);
    节点 *n = 新节点(节_宏, 关->行, 关->列);
    n->标志 = 标志;
    词 *名 = 期望名(P, "宏名");
    if (名) 指文字(n, 名);

    期望符(P, "(", "宏的参数清单要用 ( 开头");
    if (!词是符(当前(P), ")")) {
        for (;;) {
            词 *参数 = 期望名(P, "宏的参数名");
            if (参数) {
                节点 *a = 新节点(节_名字, 参数->行, 参数->列);
                指文字(a, 参数);
                加子(n, a);
            }
            if (!吃符(P, ",")) break;
        }
    }
    期望符(P, ")", "宏的参数清单要用 ) 收尾");
    加子(n, 解析块(P));
    吃换行(P);
    return n;
}

static 节点 *解析顶层(语法器 *P, unsigned 标志)
{
    词 *t = 当前(P);

    if (词是关(t, "模块")) return 解析模块(P);
    if (词是关(t, "引入")) return 解析引入(P);
    if (词是关(t, "导出")) return 解析导出(P);
    if (词是关(t, "函数") || 词是关(t, "异步")) return 解析函数(P, 标志);
    if (词是关(t, "结构")) return 解析结构(P, 标志);
    if (词是关(t, "枚举")) return 解析枚举(P, 标志);
    if (词是关(t, "接口")) return 解析接口(P, 标志);
    if (词是关(t, "实现")) return 解析实现(P, 标志);
    if (词是关(t, "常量") || 词是关(t, "令") || 是声明开头(P)) return 解析声明(P, 标志);
    if (词是关(t, "外部")) return 解析外部(P, 标志);
    if (词是关(t, "宏"))   return 解析宏(P, 标志);

    if (词是关(t, "编译期")) {
        吃(P);
        节点 *n = 新节点(节_编译期, t->行, t->列);
        加子(n, 解析函数(P, 0));
        return n;
    }

    if (词是关(t, "测试")) {
        吃(P);
        节点 *n = 新节点(节_测试, t->行, t->列);
        词 *名 = 当前(P);
        if (名->种类 == 词_字符串) { 指文字(n, 名); 吃(P); }
        else 报错(P, 名->行, 名->列, "`测试` 后面要写一个用引号包起来的名字，比如 测试 \"加法应正确\" { }");
        加子(n, 解析块(P));
        吃换行(P);
        return n;
    }

    char 实际[64];
    说词(t, 实际, sizeof(实际));
    报错(P, t->行, t->列,
         "顶层只能写 模块 / 引入 / 函数 / 结构 / 枚举 / 接口 / 实现 / 常量 / 测试 / 宏 / 外部，实际是 %s", 实际);
    跳到行尾(P);
    return NULL;
}

static 节点 *解析程序(语法器 *P)
{
    节点 *根 = 新节点(节_程序, 1, 1);
    吃换行(P);

    if (词是关(当前(P), "模块")) 加子(根, 解析模块(P));

    while (当前(P)->种类 != 词_文件结束) {
        if (当前(P)->种类 == 词_换行) { 吃(P); continue; }
        int 原位 = P->位;
        加子(根, 解析顶层(P, 0));
        if (P->位 == 原位) {
            报错(P, 当前(P)->行, 当前(P)->列, "这一行看不懂，已跳过");
            吃(P);
        }
    }
    return 根;
}

/* ============================================================================
 *  第十三部分：把树打印出来
 *  ----------------------------------------------------------------------------
 *  缩进两格表示"我是上面那个的孩子"。这样一眼能看出层次：
 *      变量 甲
 *        类型 整数
 *        二元 +
 *          整数 1
 *          整数 2
 * ========================================================================== */

static void 打印标志(unsigned 标)
{
    if (!标) return;
    struct { unsigned 位; const char *名; } 表[] = {
        { 标_异步, "异步" }, { 标_不可变, "不可变" }, { 标_私有, "私有" },
        { 标_失败返回, "失败返回" }, { 标_范围, "范围" }, { 标_遍历, "遍历" },
        { 标_步长, "步长" }, { 标_借用, "借用" }, { 标_可变借用, "可变借用" }
    };
    printf(" [");
    int 首 = 1;
    for (int i = 0; i < (int)(sizeof(表) / sizeof(表[0])); i++) {
        if (标 & 表[i].位) {
            if (!首) printf(" ");
            printf("%s", 表[i].名);
            首 = 0;
        }
    }
    printf("]");
}

/* 打印一段文字，把换行、制表符变成 \n \t 这样的转义。
 * 为什么？因为树是"一行一个节点"，如果原文里有换行，树就会被撑断，
 * 后面用网页画树也不好看。 */
static void 打印文字(const char *p, int n)
{
    for (int i = 0; i < n; i++) {
        unsigned char c = (unsigned char)p[i];
        if (c == '\n') fputs("\\n", stdout);
        else if (c == '\t') fputs("\\t", stdout);
        else if (c == '\r') fputs("\\r", stdout);
        else fputc((int)c, stdout);
    }
}

/* 返回这棵子树最深有几层 */
static int 打印树(节点 *n, int 深)
{
    if (!n) return 深;
    for (int i = 0; i < 深; i++) fputs("  ", stdout);
    printf("%s", 节名[n->种类]);
    if (n->文字长 > 0) { fputc(' ', stdout); 打印文字(n->文字, n->文字长); }
    打印标志(n->标志);
    fputc('\n', stdout);

    int 最深 = 深;
    for (int i = 0; i < n->子数; i++) {
        int d = 打印树(n->子[i], 深 + 1);
        if (d > 最深) 最深 = d;
    }
    return 最深;
}

static long 节计数[sizeof(节名) / sizeof(节名[0])];

static int 统计树(节点 *n, int 深)
{
    if (!n) return 深;
    节计数[n->种类]++;
    int 最深 = 深;
    for (int i = 0; i < n->子数; i++) {
        int d = 统计树(n->子[i], 深 + 1);
        if (d > 最深) 最深 = d;
    }
    return 最深;
}

/* 释放整棵树。基准模式要反复解析，不释放会把内存吃光 */
static void 释放树(节点 *n)
{
    if (!n) return;
    for (int i = 0; i < n->子数; i++) 释放树(n->子[i]);
    free(n->子);
    if (n->文字堆) free((void *)n->文字);
    free(n);
}

/* ============================================================================
 *  第十四部分：主函数
 *  ----------------------------------------------------------------------------
 *  用法：
 *      简语法 文件.简            打印语法树
 *      简语法 -统计 文件.简      只报节点数、深度、耗时
 *      简语法 -词 文件.简        顺便把词也打出来（调试词法用）
 *      简语法 -基准 文件.简      反复解析，测速度
 * ========================================================================== */

/* 把源码一次切成词，全放进数组。之后解析只需要动下标，速度就上来了 */
static 词 *切好所有词(const char *源, int 源长, int *out数, int *out错误)
{
    扫描器 L;
    初始化(&L, 源, 源长);

    int 容量 = 4096, 数 = 0;
    词 *词们 = (词 *)malloc(sizeof(词) * (size_t)容量);
    if (!词们) { fprintf(stderr, "内存不够了\n"); exit(3); }

    for (;;) {
        词 t = 下一个词(&L);
        if (数 == 容量) {
            容量 *= 2;
            词们 = (词 *)realloc(词们, sizeof(词) * (size_t)容量);
            if (!词们) { fprintf(stderr, "内存不够了\n"); exit(3); }
        }
        词们[数++] = t;
        if (t.种类 == 词_文件结束) break;
    }
    *out数 = 数;
    *out错误 = L.错误数;
    return 词们;
}

static void 备好语法器(语法器 *P, 词 *词们, int 词数, const char *源, int 源长, const char *文件名)
{
    memset(P, 0, sizeof(*P));
    P->词们 = 词们;
    P->词数 = 词数;
    P->位 = 0;
    P->源 = 源;
    P->源长 = 源长;
    P->文件名 = 文件名;
}

/* 下一棒（语义分析）要把这个文件整个 #include 进去复用解析结果。
 * 它定义 简_只要语法 之后，主函数和"打印树"这些只有命令行才用的东西就不再编进去。 */
#ifndef 简_只要语法

int main(int argc, char **argv)
{
    if (argc < 2) {
        fprintf(stderr,
            "简言 · 语法分析器\n"
            "用法：\n"
            "  简语法 文件.简            打印语法树\n"
            "  简语法 -统计 文件.简      统计节点数、深度、耗时\n"
            "  简语法 -词 文件.简        先打印词，再打印树\n"
            "  简语法 -基准 文件.简      反复解析，测速度\n");
        return 2;
    }

    建关键字表();

    const char *模式 = "树";
    const char *路径 = argv[1];
    if (argc >= 3 && argv[1][0] == '-') {
        模式 = argv[1];
        路径 = argv[2];
    }

    int 源长 = 0;
    char *源 = 读文件(路径, &源长);
    if (!源) {
        fprintf(stderr, "打不开文件：%s\n", 路径);
        return 1;
    }

    int 词数 = 0, 词法错误 = 0;
    词 *词们 = 切好所有词(源, 源长, &词数, &词法错误);
    if (词法错误) fprintf(stderr, "词法阶段有 %d 个错误，下面继续尝试解析\n", 词法错误);

    if (strcmp(模式, "-词") == 0) {
        for (int i = 0; i < 词数; i++) 打印词(词们[i]);
        fputc('\n', stderr);
    }

    语法器 P;
    备好语法器(&P, 词们, 词数, 源, 源长, 路径);

    /* ---------------- 基准模式：只测解析，不打印 ---------------- */
    if (strcmp(模式, "-基准") == 0) {
        struct timespec 起, 止;

        /* 先跑三次热身，让 CPU 缓存和分支预测进入状态 */
        for (int 轮 = 0; 轮 < 3; 轮++) {
            备好语法器(&P, 词们, 词数, 源, 源长, 路径);
            g_节点数 = 0;
            节点 *根 = 解析程序(&P);
            释放树(根);
        }
        if (P.错误数) {
            fprintf(stderr, "这份源码有语法错误，基准数据没有意义\n");
            free(源); free(词们);
            return 1;
        }

        clock_gettime(CLOCK_MONOTONIC, &起);
        long 轮数 = 0, 总节点 = 0;
        double 秒 = 0;
        do {
            备好语法器(&P, 词们, 词数, 源, 源长, 路径);
            g_节点数 = 0;
            节点 *根 = 解析程序(&P);
            总节点 += g_节点数;
            释放树(根);
            轮数++;
            clock_gettime(CLOCK_MONOTONIC, &止);
            秒 = (止.tv_sec - 起.tv_sec) + (止.tv_nsec - 起.tv_nsec) / 1e9;
        } while (秒 < 0.4);

        double MB = (double)源长 * 轮数 / (1024.0 * 1024.0);
        printf("文件       %s（%.1f KB）\n", 路径, 源长 / 1024.0);
        printf("词数       %d\n", 词数);
        printf("轮数       %ld\n", 轮数);
        printf("每轮节点   %ld\n", 总节点 / 轮数);
        printf("耗时       %.3f 秒\n", 秒);
        printf("吞吐       %.1f MB/s\n", MB / 秒);
        printf("速度       %.1f 万词/秒\n", (double)词数 * 轮数 / 秒 / 10000.0);
        free(源);
        free(词们);
        return 0;
    }

    /* ---------------- 正常解析一次 ---------------- */
    struct timespec 起, 止;
    clock_gettime(CLOCK_MONOTONIC, &起);
    P.根 = 解析程序(&P);
    clock_gettime(CLOCK_MONOTONIC, &止);
    double 毫秒 = ((止.tv_sec - 起.tv_sec) * 1e9 + (止.tv_nsec - 起.tv_nsec)) / 1e6;

    if (strcmp(模式, "-统计") == 0) {
        int 最深 = 统计树(P.根, 0);
        printf("文件       %s\n", 路径);
        printf("字节数     %d\n", 源长);
        printf("词数       %d\n", 词数);
        printf("节点数     %ld\n", g_节点数);
        printf("树深       %d 层\n", 最深 + 1);
        printf("耗时       %.2f 毫秒\n", 毫秒);
        printf("吞吐       %.1f MB/s\n", 源长 / 1024.0 / 1024.0 / (毫秒 / 1000.0));
        printf("--- 节点分布 ---\n");
        for (int i = 0; i < (int)(sizeof(节名) / sizeof(节名[0])); i++) {
            if (节计数[i] == 0) continue;
            printf("%-12s %6ld\n", 节名[i], 节计数[i]);
        }
    } else {
        打印树(P.根, 0);
    }

    fprintf(stderr, "\n共 %ld 个节点，%d 个语法错误，%d 个提示，耗时 %.2f 毫秒\n",
            g_节点数, P.错误数, P.警告数, 毫秒);

    int 失败 = (词法错误 + P.错误数) > 0;
    释放树(P.根);
    free(词们);
    free(源);
    return 失败 ? 1 : 0;
}

#endif /* 简_只要语法 */
