/* ============================================================================
 *  简言 · 语法分析器（parser.c）
 *  ----------------------------------------------------------------------------
 *  上一棒是词法分析器：它把源码切成一个个"词"，比如
 *      整数 甲 = 1 + 2
 *    → [整数] [甲] [=] [1] [+] [2]
 *
 *  这一棒是语法分析器：它要判断这些词排成的**顺序**合不合法，并搭出一棵树。
 *  上面那行会被搭成：
 *      变量 甲
 *        类型 整数
 *        二元 +
 *          整数 1
 *          整数 2
 *
 *  为什么需要树？因为机器只会"从左往右看"，而"1 + 2"真正的意思藏在层次里。
 *  有了树，后面的类型检查、生成机器码才有东西可依。
 *
 *  ----------------------------------------------------------------------------
 *  这份代码为什么"看得懂"：
 *    - 一个函数只干一件事，函数名就是它干的事（解析如果语句、解析一元表达式）。
 *    - 递归下降：语法规则怎么写，函数就怎么调，一一对应。
 *    - 没有宏魔法，没有 goto，没有函数指针，没有位运算技巧。
 *    - 注释用中文，写"为什么"，不写"这行赋值给那个变量"。
 *
 *  编译（追求体积小、速度快）：
 *      gcc -O3 -flto -s -static -o 简语法 parser.c
 * ========================================================================== */

