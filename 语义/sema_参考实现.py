def 按目标检(n, 目标):
    """`学生 甲 = { ... }`：花括号按目标类型解释成结构体构造"""
    if 目标 and 目标[0] == "命名" and n.种类 == "数组字面量":
        s = 全局表.get(目标[1])
        if s and s.类 == "结构" and s.定义体:
            字段们 = [f for f in s.定义体.子 if f.种类 == "字段"]
            if len(n.子) != len(字段们):
                错(n, "`%s` 有 %d 个字段，这里给了 %d 个值。按声明顺序写全",
                   目标[1], len(字段们), len(n.子))
                for c in n.子:
                    检表达式(c)
                return 目标
            global 泛型名
            旧泛 = 泛型名
            泛型名 = 泛型参数名(s.定义体)
            for i, f in enumerate(字段们):
                ft = 未知
                for c in f.子:
                    if c.种类 == "类型":
                        ft = 节点类型(c)
                要求可赋值(ft, 检表达式(n.子[i]), n.子[i], "这个字段的类型对不上")
            泛型名 = 旧泛
            return 目标
    return 检表达式(n)


