def 拆泛型(文, 前缀):
    """`映射[A, B]` → ["A", "B"]；拆不动返回 None。
    按顶层逗号切，所以 `映射[字符串, 映射[字符串, 整数]]` 也不会切错。"""
    if not 文.startswith(前缀 + "["):
        return None
    内 = 文[len(前缀) + 1:]
    if not 内.endswith("]"):
        return None
    内 = 内[:-1]
    段, 深, 起 = [], 0, 0
    for i, c in enumerate(内):
        if c in "[(":
            深 += 1
        elif c in "])":
            深 -= 1
        elif c == "," and 深 == 0:
            段.append(内[起:i])
            起 = i + 1
    段.append(内[起:])
    return [s.strip() for s in 段]


def 读类型(文):
    文 = (文 or "").strip()
    if not 文:
        return 未知

    # 后缀：组 / 组[10]，可以叠（整数 组 组）
    长度 = 0
    m = re.search(r"\s*组(?:\[(\d+)\])?$", 文)
    if m:
        长度 = int(m.group(1) or 0)
        return 组(读类型(文[:m.start()]), 长度)

    # 前缀
    if 文 in 基本类型表:
        return 基本类型表[文]

    if 文 == "自身":
        return 当前自身 if 当前自身 else ("参数", "自身")

    段 = 拆泛型(文, "映射")
    if 段 is not None and len(段) == 2:
        return 映射(读类型(段[0]), 读类型(段[1]))

    段 = 拆泛型(文, "结果")
    if 段 is not None and len(段) == 2:
        return 结果(读类型(段[0]), 读类型(段[1]))

    段 = 拆泛型(文, "可空")
    if 段 is not None:
        return 可空(读类型(段[0]))

    段 = 拆泛型(文, "通道")
    if 段 is not None:
        return 通道(读类型(段[0]))

    段 = 拆泛型(文, "元组")
    if 段 is not None:
        return ("元组", tuple(读类型(x) for x in 段))

    if 文.startswith("函数("):
        内 = 文[3:]
        深, 收 = 0, -1
        for i, c in enumerate(内):
            if c == "(":
                深 += 1
            elif c == ")":
                深 -= 1
                if 深 == 0:
                    收 = i
                    break
        参文 = 内[1:收]
        参 = [读类型(x) for x in 参文.split(",")] if 参文.strip() else []
        余 = 内[收 + 1:].strip()
        返 = 空
        if 余.startswith("->"):
            返 = 读类型(余[2:])
        return 函数(参, 返)

    # 泛型参数优先
    if 文 in 泛型名:
        return ("参数", 文)

    if 文 in 全局表:
        s = 全局表[文]
        if s.类 in ("结构", "枚举", "接口", "外部类型"):
            return 命名(文)
        if s.类 in ("类型别名", "类型参数"):
            return s.型
        错(None, "`%s` 不能当类型用", 文)
        return 未知

    错(None, "不认识的类型 `%s`。检查一下拼写，或者这个类型是不是忘了定义", 文)
    return 未知


def 节点类型(n):
    if n is None or n.种类 != "类型":
        return 未知
    return 读类型(n.文字)


