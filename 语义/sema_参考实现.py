def 借用回滚(标记):
    while len(借用栈) > 标记:
        s, 可变 = 借用栈.pop()
        if 可变:
            s.可变借出 = False
        elif s.借出 > 0:
            s.借出 -= 1


def 记借用(s, 可变, 节点):
    if 可变:
        if s.可变借出:
            错(节点, "`%s` 已经被可变借用了。同一时刻只能有一个人改它", s.名)
            return False
        if s.借出 > 0:
            错(节点, "`%s` 正被别人借着看，不能同时可变借用。等那句用完再改", s.名)
            return False
        if not s.可变:
            错(节点, "`%s` 是常量或不可变变量，不能可变借用。声明时去掉 不可变 / 别用 常量", s.名)
            return False
        if s.已移动:
            错(节点, "`%s` 已经被移动走了，不能再借用", s.名)
            return False
        s.可变借出 = True
    else:
        if s.可变借出:
            错(节点, "`%s` 正被可变借用，这期间不能借去看。等改完再借", s.名)
            return False
        if s.已移动:
            错(节点, "`%s` 已经被移动走了，不能再借用", s.名)
            return False
        s.借出 += 1
    借用栈.append((s, 可变))
    return True


