def 型文(t):
    """把类型写回人能看的文字"""
    k = t[0]
    if k == "整数":
        w = t[1]
        return "整数" if w == 0 else "整数%d" % w
    if k == "浮点": return "浮点"
    if k == "布尔": return "布尔值"
    if k == "字符串": return "字符串"
    if k == "空": return "空值"
    if k == "任意": return "任意"
    if k == "类型": return "类型"
    if k == "未知": return "未知"
    if k == "命名" or k == "参数": return t[1]
    if k == "组":
        s = 型文(t[1]) + " 组"
        return s if not t[2] else s + "[%d]" % t[2]
    if k == "映射": return "映射[%s, %s]" % (型文(t[1]), 型文(t[2]))
    if k == "可空": return "可空[%s]" % 型文(t[1])
    if k == "结果": return "结果[%s, %s]" % (型文(t[1]), 型文(t[2]))
    if k == "通道": return "通道[%s]" % 型文(t[1])
    if k == "元组": return "元组[%s]" % ", ".join(型文(x) for x in t[1])
    if k == "函数":
        s = "函数(%s)" % ", ".join(型文(x) for x in t[1])
        return s if t[2][0] == "空" else s + " -> " + 型文(t[2])
    return "未知"


