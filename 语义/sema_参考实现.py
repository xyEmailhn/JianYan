@处("二元")
def _二元(n):
    运 = n.文字
    左, 右 = 检表达式(n.子[0]), 检表达式(n.子[1])

    if 运 == "..":
        if 可赋值(字符串, 左) and 可赋值(字符串, 右):
            return 字符串
        错(n, "`..` 只能拼字符串，左边是 %s，右边是 %s。数字要先写 字符串(x)", 型文(左), 型文(右))
        return 字符串
    if 运 in ("与", "或"):
        要求可赋值(布尔, 左, n.子[0], "`与`/`或` 的左边要是布尔值")
        要求可赋值(布尔, 右, n.子[1], "`与`/`或` 的右边要是布尔值")
        return 布尔
    if 运 in ("==", "!="):
        if not 可赋值(左, 右) and not 可赋值(右, 左):
            错(n, "比较的两边类型不一样：%s 和 %s。转成同一种再比", 型文(左), 型文(右))
        return 布尔
    if 运 in ("<<", ">>", "<=", ">="):
        if not 是数值(左) or not 是数值(右):
            错(n, "比较大小要用数字，这里是 %s 和 %s", 型文(左), 型文(右))
        return 布尔
    if 运 in ("|", "^^", "&", "<<<", ">>>"):
        if 左[0] != "整数":
            错(n.子[0], "位运算只能用在整数上，这里是 %s。浮点数没有「位」这回事", 型文(左))
        if 右[0] != "整数":
            错(n.子[1], "位运算的右边也要是整数，这里是 %s", 型文(右))
        return 整数
    if 运 in ("+", "-", "*", "/", "//", "%", "^"):
        if not 是数值(左) or not 是数值(右):
            if 运 == "+" and 左[0] == "字符串" and 右[0] == "字符串":
                错(n, "字符串拼接要用 `..`，不是 `+`。写成 甲 .. 乙")
                return 字符串
            错(n, "`%s` 两边都要是数字，这里是 %s 和 %s", 运, 型文(左), 型文(右))
            return 未知
        if 左[0] == "整数" and 右[0] == "整数" and 运 == "/":
            提示(n, "两个整数用 / 会得到浮点结果；想整除请写 //，想取余写 %%")
        if 左[0] == "浮点" or 右[0] == "浮点":
            if 运 in ("%", "//"):
                错(n, "`%s` 只能用在整数上。浮点取余请写 甲 - 取整(甲 / 乙) * 乙", 运)
            return 浮点
        return 左
    错(n, "不认识的运算符 `%s`（左边 %s，右边 %s）", 运, 型文(左), 型文(右))
    return 未知


