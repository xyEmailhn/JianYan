def 声明变量(n, 类):
    global 泛型名
    if not n.文字:
        return
    if 本层找(n.文字):
        错(n, "`%s` 在这一层已经有一个同名的了。换个名字，或者把它放到别的 { } 里", n.文字)

    声明型 = 未知
    if n.子 and n.子[0].种类 == "类型":
        声明型 = 节点类型(n.子[0])

    初值, 有初值 = 未知, False
    for c in n.子:
        if c.种类 in ("类型", "块"):
            continue
        初值 = 按目标检(c, 声明型)
        有初值 = True
        break

    if n.种类 == "令":
        声明型 = 初值
        if not 有初值:
            错(n, "`令` 要靠初值来推断类型，后面必须写 `= ...`")
    elif 有初值:
        要求可赋值(声明型, 初值, n, "初值类型和声明的类型对不上")

    s = 符(n.文字, 类, 声明型, n)
    s.可变 = (类 != "常量") and ("不可变" not in n.标志)
    登记(s)


