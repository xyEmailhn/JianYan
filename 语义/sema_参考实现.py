def 可赋值(目, 源):
    if 目 is None or 源 is None:
        return True
    if 目[0] in ("未知", "任意") or 源[0] in ("未知", "任意"):
        return True
    if 目[0] == "参数" or 源[0] == "参数":
        return True
    if 目 == 源:
        return True

    if 目[0] == "可空":
        return 源[0] == "空" or 可赋值(目[1], 源)
    if 目[0] == "整数" and 源[0] == "整数":
        return (目[1] or 32) >= (源[1] or 32)
    if 目[0] == "浮点" and 源[0] in ("整数", "浮点"):
        return True
    if 目[0] == "组" and 源[0] == "组":
        if 目[2] and 源[2] and 目[2] != 源[2]:
            return False
        if 目[2] and not 源[2]:
            return False
        return 可赋值(目[1], 源[1]) and 可赋值(源[1], 目[1])
    if 目[0] == "函数" and 源[0] == "函数":
        if len(目[1]) != len(源[1]):
            return False
        if any(not 可赋值(a, b) for a, b in zip(目[1], 源[1])):
            return False
        return 可赋值(源[2], 目[2])
    if 目[0] == "结果" and 源[0] == "结果":
        return 可赋值(目[1], 源[1]) and 可赋值(目[2], 源[2])
    if 是接口(目) and 源[0] == "命名":
        return 实现了(源, 目)
    return False


def 不匹配原因(目, 源):
    if 目[0] == "整数" and 源[0] == "整数" and (目[1] or 32) < (源[1] or 32):
        return "窄类型装不下宽类型，会悄悄丢数据。确实要截断就写 整数8(x) 这样显式转换"
    if 目[0] == "字符串" or 源[0] == "字符串":
        return "简言不做隐式转换，字符串和数字之间要写 字符串(x) 或 整数(x)"
    if 目[0] == "可空":
        return "这个位置不接受空值，要先确认它不为空"
    if 目[0] == "浮点":
        return "两者不是同一种数"
    return "两者的类型对不上"


def 要求可赋值(目, 源, 节点, 场景):
    if 可赋值(目, 源):
        return True
    错(节点, "%s：这里要 %s，给的是 %s。%s", 场景, 型文(目), 型文(源), 不匹配原因(目, 源))
    return False


