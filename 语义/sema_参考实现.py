def 读签名(文, 元素, 键):
    文 = 文.replace("@", 型文(元素 or 未知)).replace("!", 型文(键 or 未知))
    m = re.match(r"\s*\((.*)\)\s*(?:->\s*(.*))?$", 文)
    if m:
        参文 = m.group(1).strip()
        参 = [读类型(x) for x in 参文.split(",")] if 参文 else []
        返 = 读类型(m.group(2)) if m.group(2) else 空
        return 函数(参, 返)
    m = re.match(r"\s*->\s*(.*)$", 文)
    返 = 读类型(m.group(1)) if m else 空
    return 函数([], 返)


def 是内置属性(对象, 名):
    """签名以 `->` 开头的内置项是属性（词.长度），不是方法"""
    if not 对象:
        return False
    签 = 内置表.get((对象[0], 名))
    return 签 is not None and 签.startswith("->")


def 查内置(对象, 名):
    if not 对象:
        return None
    元素 = 键 = None
    if 对象[0] == "组":
        元素 = 对象[1]
    elif 对象[0] == "映射":
        键, 元素 = 对象[1], 对象[2]
    elif 对象[0] == "可空":
        元素 = 对象[1]
    elif 对象[0] == "结果":
        键, 元素 = 对象[1], 对象[2]
    签 = 内置表.get((对象[0], 名))
    return 读签名(签, 元素, 键) if 签 else None


def 查字段(定义体, 名):
    if 定义体 is None:
        return None
    global 泛型名
    旧 = 泛型名
    泛型名 = 泛型参数名(定义体)
    for f in 定义体.子:
        if f.种类 == "字段" and f.文字 == 名:
            t = 未知
            for c in f.子:
                if c.种类 == "类型":
                    t = 节点类型(c)
            泛型名 = 旧
            return t
    泛型名 = 旧
    return None


def 泛型参数名(声明):
    名们 = []
    for g in 声明.子:
        if g.种类 == "泛型":
            名们.append(g.文字.split(":")[0].strip())
    return 名们


def 查实现方法(对象, 名):
    global 当前自身
    for t, _, 块 in 实现表:
        if t != 对象:
            continue
        for f in 块.子:
            if f.种类 == "函数" and f.文字 == 名:
                旧 = 当前自身
                当前自身 = 对象
                签 = 函数签名(f)
                当前自身 = 旧
                return 签
    return None


def 查接口默认(对象, 名):
    for _, 接口名, 块 in 实现表:
        for f in 块.子:
            if f.种类 == "函数" and f.文字 == 名:
                return 函数签名(f)
        s = 全局表.get(接口名)
        if not s or not s.定义体:
            continue
        for f in s.定义体.子:
            if f.种类 != "函数" or f.文字 != 名:
                continue
            if any(c.种类 == "块" for c in f.子):
                return 函数签名(f)
    return None


def 成员类型(对象, 名, 处, 自动解包=False):
    if not 对象:
        return 未知

    if 对象[0] == "可空":
        if 名 in ("取值", "或默认", "有值"):
            return 查内置(对象, 名)
        已确认 = False
        if 处 is not None and 处.子:
            基 = 处.子[0]
            while 基 is not None and 基.种类 == "成员":
                基 = 基.子[0]
            if 基 is not None and 基.种类 == "名字":
                s = 查名字(基.文字)
                已确认 = bool(s and s.已判空)
        if not 自动解包 and not 已确认:
            错(处, "这是 %s，可能为空，不能直接取 `.%s`。先写 如果 它 != 空 就 { ... }，或者写 它.取值()",
               型文(对象), 名)
            return 未知

    内 = 查内置(对象, 名)
    if 内 is not None:
        return 内

    if 对象[0] == "命名" and 对象[1] in 全局表:
        s = 全局表[对象[1]]
        if s.类 in ("结构", "外部类型"):
            f = 查字段(s.定义体, 名)
            if f is not None:
                return f
            m = 查实现方法(对象, 名)
            if m is not None:
                return m

    m2 = 查接口默认(对象, 名)
    if m2 is not None:
        return m2

    错(处, "%s 没有叫 `%s` 的字段或方法", 型文(对象), 名)
    return 未知


def 查枚举变体(成员节点):
    if 成员节点 is None or 成员节点.种类 != "成员":
        return None, None
    基 = 成员节点.子[0]
    if 基.种类 != "名字":
        return None, None
    s = 查名字(基.文字)
    if not s or s.类 != "枚举" or not s.定义体:
        return None, None
    for v in s.定义体.子:
        if v.种类 == "变体" and v.文字 == 成员节点.文字:
            return v, s.型
    return None, None


def 变体构造类型(变体, 枚举型):
    项 = []
    for f in 变体.子:
        if f.种类 != "字段":
            continue
        for c in f.子:
            if c.种类 == "类型":
                项.append(节点类型(c))
    return 枚举型 if not 项 else 函数(项, 枚举型)


