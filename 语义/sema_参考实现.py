内置函数 = [("打印", 1), ("打印行", 1), ("读入", 0), ("退出", 1)]


def 分析(根):
    global 函数数, 结构数, 枚举数, 接口数
    for 名, 数 in 内置函数:
        s = 符(名, "函数", 函数([任意] * 数, 空))
        s.可变 = False
        全局表[名] = s

    for n in 根.子:
        if n.种类 == "函数":
            函数数 += 1
            if n.文字:
                全局表[n.文字] = 符(n.文字, "函数", 未知, n, n)
        elif n.种类 == "结构":
            结构数 += 1
            if n.文字:
                全局表[n.文字] = 符(n.文字, "结构", 命名(n.文字), n, n)
        elif n.种类 == "枚举":
            枚举数 += 1
            if n.文字:
                全局表[n.文字] = 符(n.文字, "枚举", 命名(n.文字), n, n)
        elif n.种类 == "接口":
            接口数 += 1
            if n.文字:
                全局表[n.文字] = 符(n.文字, "接口", 命名(n.文字), n, n)
        elif n.种类 == "变量" or n.种类 == "常量":
            if n.文字:
                全局表[n.文字] = 符(n.文字, "变量" if n.种类 == "变量" else "常量", 未知, n)

    # 补上类型
    for n in 根.子:
        if n.种类 == "函数" and n.文字 in 全局表:
            global 泛型名
            旧泛 = 泛型名
            泛型名 = 泛型参数名(n)
            全局表[n.文字].型 = 函数签名(n)
            泛型名 = 旧泛

    # 顶层变量、常量
    进层()
    for n in 根.子:
        if n.种类 in ("变量", "常量", "令"):
            声明变量(n, "常量" if n.种类 == "常量" else "变量")
    出层()

    for n in 根.子:
        if n.种类 == "实现":
            检实现块(n)

    for n in 根.子:
        if n.种类 == "函数":
            检函数体(n, None)
        elif n.种类 == "测试":
            检块(n.子[0])
        elif n.种类 == "编译期":
            for c in n.子:
                if c.种类 == "函数":
                    检函数体(c, None)


def 主():
    if len(sys.argv) < 2:
        print("用法：python3 sema_参考实现.py 文件.jy", file=sys.stderr)
