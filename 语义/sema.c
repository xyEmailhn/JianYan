/* 结构体字面量：`学生 甲 = { "张三", 18, 90.5 }`
 * 花括号本身在语法上是个"数组字面量"（因为它也可能是 {1,2,3}），
 * 到底当数组还是当结构，得看等号左边要的是什么。这叫"按目标解释"。 */
static 类型 *按目标检(节点 *n, 类型 *目标)
{
    /* `{}` 本身看不出是空组还是空表，目标类型说了算 */
    if (目标 && 目标->种 == 型_映射 && n && n->种类 == 节_数组字面量 && n->子数 == 0)
        return 目标;
    if (目标 && 目标->种 == 型_命名 && n && n->种类 == 节_数组字面量) {
        符号 *s = 查全局(目标->名, 目标->名长);
        if (s && s->类 == 符_结构 && s->定义体) {
            节点 *字段们[64];
            int 数 = 0;
            for (int i = 0; i < s->定义体->子数 && 数 < 64; i++)
                if (s->定义体->子[i]->种类 == 节_字段) 字段们[数++] = s->定义体->子[i];
            if (n->子数 != 数) {
                错(n, "`%s` 有 %d 个字段，这里给了 %d 个值。按声明顺序写全",
                    目标->名 ? 目标->名 : "结构", 数, n->子数);
                for (int i = 0; i < n->子数; i++) 检表达式(n->子[i]);
                return 目标;
            }
            设泛型环境(s->定义体);
            for (int i = 0; i < 数; i++) {
                类型 *ft = T未知;
                for (int k = 0; k < 字段们[i]->子数; k++)
                    if (字段们[i]->子[k]->种类 == 节_类型) ft = 节点类型(字段们[i]->子[k]);
                类型 *vt = 检表达式(n->子[i]);
                要求可赋值(ft, vt, n->子[i], "这个字段的类型对不上");
            }
            清泛型环境();
            return 目标;
        }
    }
    return 检表达式(n);
}

/* 取第 k 个字段的声明类型。字段节点的子[0] 是 节_类型。 */
static 类型 *字段声明类型(节点 *字段)
{
    for (int k = 0; k < 字段->子数; k++)
        if (字段->子[k]->种类 == 节_类型) return 节点类型(字段->子[k]);
    return T未知;
}

/* 新建 点{ x: 1.0, y: 2.0 }
 *
 * 和上面 `按目标检` 的区别在方向：那边是左边给了类型、花括号倒过来猜；
 * 这边花括号自己报了名字，不需要任何上下文，所以能写在表达式里——
 * `返回 三{...}`、`组.追加(三{...})`、`f(三{...})`，都能用。
 *
 * 代价是必须写清楚：字段按名字给（顺序随便），或者按声明顺序给全。
 * 只给一半又不写名字，那就只能报错——猜出来的代码比报错更难查。 */
static 类型 *检结构字面量(节点 *n)
{
    符号 *s = 查全局(n->文字, n->文字长);
    if (!s || s->类 != 符_结构) {
        错(n, "没有名为 `%.*s` 的结构体。`新建` 后面要跟一个已经定义过的结构体名",
            n->文字长, n->文字);
        for (int i = 0; i < n->子数; i++)
            检表达式(n->子[i]->种类 == 节_字段 && n->子[i]->子数 ? n->子[i]->子[0] : n->子[i]);
        return T未知;
    }
    if (!s->定义体) return s->型;

    节点 *字段们[64];
    int 数 = 0;
    for (int i = 0; i < s->定义体->子数 && 数 < 64; i++)
        if (s->定义体->子[i]->种类 == 节_字段) 字段们[数++] = s->定义体->子[i];

    int 已填[64];
    for (int i = 0; i < 64; i++) 已填[i] = 0;

    设泛型环境(s->定义体);
    int 位置 = 0;
    for (int i = 0; i < n->子数; i++) {
        节点 *项 = n->子[i];
        if (项->种类 == 节_字段) {
            int k = -1;
            for (int j = 0; j < 数; j++)
                if (名同(项->文字, 项->文字长, 字段们[j]->文字, 字段们[j]->文字长)) { k = j; break; }
            if (k < 0) {
                错(项, "`%.*s` 里没有名为 `%.*s` 的字段", n->文字长, n->文字,
                    项->文字长, 项->文字);
                if (项->子数) 检表达式(项->子[0]);
                continue;
            }
            if (已填[k]) 错(项, "字段 `%.*s` 给了两次", 项->文字长, 项->文字);
            已填[k] = 1;
            类型 *vt = 项->子数 ? 检表达式(项->子[0]) : T未知;
            要求可赋值(字段声明类型(字段们[k]), vt, 项, "这个字段的类型对不上");
        } else {
            while (位置 < 数 && 已填[位置]) 位置++;
            if (位置 >= 数) {
                错(项, "`%.*s` 只有 %d 个字段，这里多给了值", n->文字长, n->文字, 数);
                检表达式(项);
                continue;
            }
            已填[位置] = 1;
            类型 *vt = 检表达式(项);
            要求可赋值(字段声明类型(字段们[位置]), vt, 项, "这个字段的类型对不上");
            位置++;
        }
    }

    for (int j = 0; j < 数; j++)
        if (!已填[j])
            提示(n, "字段 `%.*s` 没给值，会填成零",
                 字段们[j]->文字长, 字段们[j]->文字);

    清泛型环境();
    return s->型;
}

static 符号 *查变量符号(节点 *名节点, int 允许函数)
{
    符号 *s = 查名字(名节点->文字, 名节点->文字长);
    if (!s) {
        错(名节点, "找不到 `%.*s`。是不是拼错了，或者忘了在这之前声明？",
            名节点->文字长, 名节点->文字);
        return NULL;
    }
    if (!允许函数 && s->类 == 符_函数) {
        错(名节点, "`%.*s` 是个函数，这里需要一个值。要调用它请写 `%.*s(...)`",
            名节点->文字长, 名节点->文字, 名节点->文字长, 名节点->文字);
        return s;
    }
    return s;
}

/* 左值：能放到 = 左边的东西。只有三种：变量、字段、下标 */
static int 是左值(节点 *n)
{
    if (!n) return 0;
    if (n->种类 == 节_名字 || n->种类 == 节_成员 || n->种类 == 节_下标) return 1;
    return 0;
}

/* 数一数某个表达式里出现过哪些运算符，用来判断 二元 的性质 */
static int 是数值(类型 *t)
{
    if (!t) return 0;
    /* 类型参数 T 到底是什么数还不知道，先当数值放行，别冤枉泛型函数 */
    return t->种 == 型_整数 || t->种 == 型_浮点 || t->种 == 型_参数 || t->种 == 型_未知;
}

static 类型 *检名字(节点 *n)
{
    符号 *s = 查变量符号(n, 1);
    if (!s) return T未知;
    if (s->已移动) {
        错(n, "`%.*s` 的值已经被移动走了（写 移动 或作为参数传走），这里不能再用。要保留就写 `复制 %.*s`",
            n->文字长, n->文字, n->文字长, n->文字);
        return s->型;
    }
    if (s->可变借出) {
        错(n, "`%.*s` 正被可变借用，这期间不能直接用它", n->文字长, n->文字);
    }
    return s->型;
}

static 类型 *检二元(节点 *n)
{
    const char *运 = n->文字;
    int 长 = n->文字长;
    类型 *左 = 检表达式(n->子[0]);
    类型 *右 = 检表达式(n->子[1]);

    /* 字符串拼接：.. */
    if (名同(运, 长, "..", 2)) {
        if (可赋值(T字符串, 左) && 可赋值(T字符串, 右)) return T字符串;
        char *a = 型名(左), *b = 型名(右);
        错(n, "`..` 只能拼字符串，左边是 %s，右边是 %s。数字要先写 字符串(x)", a, b);
        free(a); free(b);
        return T字符串;
    }

    /* 逻辑：与 或 */
    if (名同(运, 长, "与", 3) || 名同(运, 长, "或", 3)) {
        要求可赋值(T布尔, 左, n->子[0], "`与`/`或` 的左边要是布尔值");
        要求可赋值(T布尔, 右, n->子[1], "`与`/`或` 的右边要是布尔值");
        return T布尔;
    }

    /* 比较：== != << >> <= >=  （简言里 << 是小于，>> 是大于） */
    if (名同(运, 长, "==", 2) || 名同(运, 长, "!=", 2)) {
        if (!可赋值(左, 右) && !可赋值(右, 左)) {
            char *a = 型名(左), *b = 型名(右);
            错(n, "比较的两边类型不一样：%s 和 %s。转成同一种再比", a, b);
            free(a); free(b);
        }
        return T布尔;
    }
    if (名同(运, 长, "<<", 2) || 名同(运, 长, ">>", 2) ||
        名同(运, 长, "<=", 2) || 名同(运, 长, ">=", 2)) {
        if (!是数值(左) || !是数值(右)) {
            char *a = 型名(左), *b = 型名(右);
            错(n, "比较大小要用数字，这里是 %s 和 %s", a, b);
            free(a); free(b);
        }
        return T布尔;
    }

    /* 位运算：| ^^ & 以及移位 <<< >>> */
    if (名同(运, 长, "|", 1) || 名同(运, 长, "^^", 2) || 名同(运, 长, "&", 1) ||
        名同(运, 长, "<<<", 3) || 名同(运, 长, ">>>", 3)) {
        if (左->种 != 型_整数) {
            char *a = 型名(左);
            错(n->子[0], "位运算只能用在整数上，这里是 %s。浮点数没有「位」这回事", a);
            free(a);
        }
        if (右->种 != 型_整数) {
            char *b = 型名(右);
            错(n->子[1], "位运算的右边也要是整数，这里是 %s", b);
            free(b);
        }
        return T整数;
    }

    /* 算术：+ - * / // % ^ */
    if (名同(运, 长, "+", 1) || 名同(运, 长, "-", 1) ||
        名同(运, 长, "*", 1) || 名同(运, 长, "/", 1) ||
        名同(运, 长, "//", 2) || 名同(运, 长, "%", 1) || 名同(运, 长, "^", 1)) {
        if (!是数值(左) || !是数值(右)) {
            /* 字符串 + 字符串 是初学者最容易写错的，单独给一句 */
            if (名同(运, 长, "+", 1) && 左->种 == 型_字符串 && 右->种 == 型_字符串) {
                错(n, "字符串拼接要用 `..`，不是 `+`。写成 甲 .. 乙");
                return T字符串;
            }
            char *a = 型名(左), *b = 型名(右);
            错(n, "`%.*s` 两边都要是数字，这里是 %s 和 %s", 长, 运, a, b);
            free(a); free(b);
            return T未知;
        }
        /* 整数除法和取余的特殊提示 */
        if (左->种 == 型_整数 && 右->种 == 型_整数 && 名同(运, 长, "/", 1)) {
            提示(n, "两个整数用 / 会得到浮点结果；想整除请写 //，想取余写 %%");
        }
        if (左->种 == 型_浮点 || 右->种 == 型_浮点) {
            if (名同(运, 长, "%", 1) || 名同(运, 长, "//", 2)) {
                错(n, "`%.*s` 只能用在整数上。浮点取余请写 甲 - 取整(甲 / 乙) * 乙", 长, 运);
            }
            return T浮点;
        }
        return 左;
    }

    char *a = 型名(左), *b = 型名(右);
    错(n, "不认识的运算符 `%.*s`（左边 %s，右边 %s）", 长, 运, a, b);
    free(a); free(b);
    return T未知;
}

static 类型 *检一元(节点 *n)
{
    const char *运 = n->文字;
    int 长 = n->文字长;
    类型 *内 = 检表达式(n->子[0]);

    if (名同(运, 长, "非", 3) || 名同(运, 长, "!", 1)) {
        要求可赋值(T布尔, 内, n->子[0], "`非` 后面要是布尔值");
        return T布尔;
    }
    if (名同(运, 长, "~~", 2)) {
        if (内->种 != 型_整数) {
            char *a = 型名(内);
            错(n, "按位取反只能用在整数上，这里是 %s", a);
            free(a);
        }
        return T整数;
    }
    if (名同(运, 长, "#", 1)) {
        /* #甲 是"甲有多长" */
        if (!查内置(内, "长度", 6)) {
            char *a = 型名(内);
            错(n, "`#` 是取长度，要放在字符串、数组、映射前面。%s 没有长度", a);
            free(a);
            return T整数;
        }
        return T整数;
    }
    if (名同(运, 长, "-", 1) || 名同(运, 长, "+", 1)) {
        if (!是数值(内)) {
            char *a = 型名(内);
            错(n, "正负号只能用在数字上，这里是 %s", a);
            free(a);
            return T未知;
        }
        return 内;
    }
    错(n, "不认识的一元运算符 `%.*s`", 长, 运);
    return T未知;
}

/* 检查一次调用的实参。签名 是 型_函数，声明节点 用来判断"这个参数要不要借用" */
static 类型 *检实参(节点 *调用, 类型 *签名, 节点 *声明节点)
{
    int 给 = 调用->子数 - 1;
    if (给 != 签名->项数) {
        错(调用, "参数个数不对：这个函数要 %d 个，这里给了 %d 个", 签名->项数, 给);
        /* 个数不对就不再逐个比类型，否则会刷出一堆连带错误 */
        for (int i = 1; i < 调用->子数; i++) 检表达式(调用->子[i]);
        return 签名->返回;
    }

    /* 找到声明里的参数节点（如果是从具名函数调用的） */
    节点 *参数节点[32];
    int 参数数 = 0;
    if (声明节点)
        for (int i = 0; i < 声明节点->子数 && 参数数 < 32; i++)
            if (声明节点->子[i]->种类 == 节_参数) 参数节点[参数数++] = 声明节点->子[i];

    for (int i = 1; i < 调用->子数; i++) {
        类型 *形 = 签名->项[i - 1];
        类型 *实 = 按目标检(调用->子[i], 形);

        /* 把没返回值的函数当值用，是最容易犯又最难查的错：
         *   `打印(山峰(...))` —— 山峰 只负责往输出里写东西，什么都不返回。
         * 后端会老老实实打印一个空值，gcc 里那就是一块没初始化的垃圾，
         * 混进 SVG 的路径数据里，画出来是一团无法解释的图形。
         * 这一步直接拦住，比事后对着几千行输出找那个多出来的字符强。
         * （之前踩过一次，代价是一张图渲染不出来。） */
        if (实 && 实->种 == 型_空 && 调用->子[i]->种类 == 节_调用)
            错(调用->子[i], "这个调用没有返回值，不能当参数用。它已经把东西写出去了，单独写一行就行");
        int 是借用参数 = 0;
        if (i - 1 < 参数数 && (参数节点[i - 1]->标志 & (标_借用 | 标_可变借用))) 是借用参数 = 1;

        if (是借用参数) {
            /* 借用参数：实参可以是值，也允许直接写变量名（编译器会隐式借）。
             * 类型仍然要对得上。 */
            if (!可赋值(形, 实) && 实->种 != 型_未知) {
                char *a = 型名(形), *b = 型名(实);
                错(调用->子[i], "第 %d 个参数要 %s，给的是 %s", i, a, b);
                free(a); free(b);
            }
        } else {
            要求可赋值(形, 实, 调用->子[i], "参数类型不对");
            /* 值参数：把变量整个搬走。这里只提示，不当错误——
             * 真正的移动检查要看这个变量后面还用不用，那是下一版的事。 */
            if (调用->子[i]->种类 == 节_名字 && !是复制类型(实))
                提示(调用->子[i], "`%.*s` 作为值参数传进去了，它的所有权会转给函数；如果后面还要用，请写 `借用 %.*s`",
                     调用->子[i]->文字长, 调用->子[i]->文字,
                     调用->子[i]->文字长, 调用->子[i]->文字);
        }
    }
    return 签名->返回;
}

static 类型 *检调用(节点 *n)
{
    节点 *被调 = n->子[0];
    类型 *目标;

    /* 类型转换写法：整数(3.9)、字符串(端口)。被调是个类型名，不是函数 */
    if (被调->种类 == 节_名字) {
        符号 *s = 查名字(被调->文字, 被调->文字长);
        if (s && (s->类 == 符_结构 || s->类 == 符_枚举 || s->类 == 符_接口)) {
            错(n, "`%.*s` 是个类型，不能当函数调用。要构造它请写 `%.*s{...}`",
                被调->文字长, 被调->文字, 被调->文字长, 被调->文字);
            for (int i = 1; i < n->子数; i++) 检表达式(n->子[i]);
            return 命名类型(被调->文字, 被调->文字长);
        }
    }

    if (被调->种类 == 节_成员) {
        类型 *枚举 = NULL;
        节点 *变体 = 查枚举变体(被调, &枚举);
        if (变体) {
            类型 *签 = 变体构造类型(变体, 枚举);
            if (签->种 == 型_函数) return 检实参(n, 签, NULL);
            错(n, "`%.*s` 这个变体没有字段，直接写 `%.*s`，不要加括号",
                被调->文字长, 被调->文字, 被调->文字长, 被调->文字);
            return 枚举;
        }
        /* x.方法(...)：成员类型就是方法签名，不再单独检一遍成员表达式 */
        类型 *对象 = 检表达式(被调->子[0]);
        目标 = 成员类型(对象, 被调->文字, 被调->文字长, 被调, 0);
        if (!目标 || 目标->种 != 型_函数) {
            if (目标 && 目标->种 != 型_未知) {
                char *a = 型名(目标);
                错(n, "`%.*s` 是 %s，不是函数，不能加括号调用", 被调->文字长, 被调->文字, a);
                free(a);
            }
            for (int i = 1; i < n->子数; i++) 检表达式(n->子[i]);
            return T未知;
        }
        return 检实参(n, 目标, NULL);
    }

    目标 = 检表达式(被调);

    /* 显式类型转换：整数(x)、浮点(x)、字符串(x)… */
    if (被调->种类 == 节_名字) {
        int 是转换 = 0;
        if (名同(被调->文字, 被调->文字长, "整数", 6) ||
            名同(被调->文字, 被调->文字长, "整数8", 7) ||
            名同(被调->文字, 被调->文字长, "整数16", 8) ||
            名同(被调->文字, 被调->文字长, "整数32", 8) ||
            名同(被调->文字, 被调->文字长, "整数64", 8) ||
            名同(被调->文字, 被调->文字长, "浮点", 6) ||
            名同(被调->文字, 被调->文字长, "字符串", 9) ||
            名同(被调->文字, 被调->文字长, "布尔值", 9)) 是转换 = 1;
        if (是转换) {
            类型 *真实 = 读类型(被调->文字, 被调->文字长, 被调->行, 被调->列);
            if (n->子数 != 2) {
                错(n, "类型转换只接一个值，比如 整数(3.9)");
                return 真实;
            }
            类型 *源 = 检表达式(n->子[1]);
            if (源->种 == 型_字符串 && !名同(被调->文字, 被调->文字长, "字符串", 9)) {
                提示(n, "从字符串转数字更安全的是 文本.转整数()，它会把失败原因告诉你");
            }
            return 真实;
        }
    }

    if (!目标 || 目标->种 == 型_未知 || 目标->种 == 型_任意) {
        for (int i = 1; i < n->子数; i++) 检表达式(n->子[i]);
        return T未知;
    }
    if (目标->种 != 型_函数) {
        char *a = 型名(目标);
        错(n, "这个位置的类型是 %s，不是函数，不能调用", a);
        free(a);
        for (int i = 1; i < n->子数; i++) 检表达式(n->子[i]);
        return T未知;
    }

    /* 用具名函数调用时，把它的声明节点找出来，好用上参数上的 借用 标记 */
    节点 *声明节点 = NULL;
    if (被调->种类 == 节_名字) {
        符号 *s = 查名字(被调->文字, 被调->文字长);
        if (s && s->类 == 符_函数) 声明节点 = s->定义体;
    }
    return 检实参(n, 目标, 声明节点);
}

static 类型 *检成员(节点 *n)
{
    类型 *枚举 = NULL;
    节点 *变体 = 查枚举变体(n, &枚举);
    if (变体) return 变体构造类型(变体, 枚举);

    类型 *对象 = 检表达式(n->子[0]);
    类型 *t = 成员类型(对象, n->文字, n->文字长, n, 0);
    /* `词.长度` 是属性不是方法：直接给它的值类型，否则会被当成函数 */
    if (t && t->种 == 型_函数 && 是内置属性(对象, n->文字, n->文字长)) return t->返回;
    return t;
}

static 类型 *检下标(节点 *n)
{
    类型 *对象 = 检表达式(n->子[0]);
    类型 *下标 = 检表达式(n->子[1]);

    switch (对象->种) {
    case 型_组:
        if (下标->种 != 型_整数 && 下标->种 != 型_未知) {
            char *a = 型名(下标);
            错(n->子[1], "数组下标要是整数，这里是 %s", a);
            free(a);
        }
        return 对象->元素;
    case 型_字符串:
        if (下标->种 != 型_整数 && 下标->种 != 型_未知) {
            char *a = 型名(下标);
            错(n->子[1], "字符串下标要是整数，这里是 %s", a);
            free(a);
        }
        return T字符串;
    case 型_映射:
        return 包装类型(型_可空, 对象->值);
    case 型_未知:
    case 型_任意:
        return T未知;
    default: {
        char *a = 型名(对象);
        错(n, "%s 不能用 [ ] 取东西。能用的只有数组、字符串、映射", a);
        free(a);
        return T未知;
    }
    }
}

static 类型 *检字面量(节点 *n)
{
    if (n->种类 == 节_数组字面量) {
        if (n->子数 == 0) return 组类型(T未知, 0);
        类型 *首 = 检表达式(n->子[0]);
        for (int i = 1; i < n->子数; i++) {
            类型 *t = 检表达式(n->子[i]);
            要求可赋值(首, t, n->子[i], "数组里每一项的类型要一样");
        }
        return 组类型(首, 0);
    }
    /* 映射字面量：键、值、键、值…… */
    if (n->子数 == 0) return 双参类型(型_映射, T未知, T未知);
    类型 *键 = 检表达式(n->子[0]);
    类型 *值 = n->子数 > 1 ? 检表达式(n->子[1]) : T未知;
    for (int i = 2; i + 1 < n->子数; i += 2) {
        类型 *k = 检表达式(n->子[i]);
        类型 *v = 检表达式(n->子[i + 1]);
        要求可赋值(键, k, n->子[i], "映射的键类型要一样");
        要求可赋值(值, v, n->子[i + 1], "映射的值类型要一样");
    }
    return 双参类型(型_映射, 键, 值);
}

/* 匿名函数没有闭包：抓不到外层的局部变量。
 * 之前这种情况会一路走到后端，生成一个同名符号，然后算出一个**看着正常**的错数。
 * 这里在语义阶段就拦下来，并把"为什么不行"说清楚。 */
/* 匿名函数没有闭包：抓不到外层的局部变量。
 * 判据是"层号"：符号登记时记了自己在第几层，匿名函数的形参和体内局部量
 * 都 >= 它自己那一层，外层变量则一定更浅。之前这种情况会一路走到后端，
 * 生成一个同名符号，算出一个**看着正常**的错数——比报错难查得多。 */
static void 查匿名越界(节点 *n, int 基层)
{
    if (!n) return;
    if (n->种类 == 节_名字 && n->文字长 > 0) {
        符号 *s = 查名字(n->文字, n->文字长);
        if (s && s->类 == 符_变量 && s->层 < 基层)
            错(n, "匿名函数用到了外层的 `%.*s`。这一版没有闭包，抓不到外层局部变量。\n"
                  "    把它改成匿名函数的形参传进来，或者把这段逻辑写成普通函数。",
               n->文字长, n->文字);
    }
    for (int i = 0; i < n->子数; i++) 查匿名越界(n->子[i], 基层);
}

/* 表格：创建 → 往里加一行 */
static 类型 *检表达式(节点 *n)
{
    if (!n) return T未知;
    表达式数++;

    switch (n->种类) {
    case 节_整数: return T整数;
    case 节_浮点: return T浮点;
    case 节_字符串: return T字符串;
    case 节_真: case 节_假: return T布尔;
    case 节_空: return T空;
    case 节_错误: return T未知;

    case 节_名字: {
        /* 基本类型名（整数、字符串…）出现在表达式里，表示"这个类型本身" */
        if (名同(n->文字, n->文字长, "整数", 6)) return T类型;
        if (名同(n->文字, n->文字长, "整数8", 7) ||
            名同(n->文字, n->文字长, "整数16", 8) ||
            名同(n->文字, n->文字长, "整数32", 8) ||
            名同(n->文字, n->文字长, "整数64", 8)) return T类型;
        if (名同(n->文字, n->文字长, "浮点", 6)) return T类型;
        if (名同(n->文字, n->文字长, "布尔值", 9)) return T类型;
        if (名同(n->文字, n->文字长, "字符串", 9)) return T类型;
        return 检名字(n);
    }

    case 节_二元: return 检二元(n);
    case 节_一元: return 检一元(n);

    case 节_赋值: {
        节点 *左 = n->子[0];
        节点 *右 = n->子[1];
        if (!是左值(左)) {
            错(左, "等号左边只能是变量、字段或数组元素，不能是一段算出来的值");
            检表达式(右);
            return 检表达式(左);
        }
        类型 *目 = 检表达式(左);
        类型 *源 = 按目标检(右, 目);
        要求可赋值(目, 源, 右, "赋值类型不对");

        /* 不可变的变量不许改：写成 s.字段 = ... 也要管住 s */
        节点 *根 = 左;
        while (根 && (根->种类 == 节_成员 || 根->种类 == 节_下标)) 根 = 根->子[0];
        if (根 && 根->种类 == 节_名字) {
            符号 *s = 查名字(根->文字, 根->文字长);
            if (s && !s->可变 && s->类 != 符_函数)
                错(根, "`%.*s` 是不可变的（常量、不可变变量，或者是 `借用` 参数），不能改。要改就声明成普通变量，或者参数写 `可变借用`",
                    根->文字长, 根->文字);
            /* 线程块里的赋值只认自己那一层的变量：外层变量是**按值**拷进来的，
             * 改它改的是副本，外面看不到。这种"写了等于没写"比报错难查得多。 */
            if (s && s->类 == 符_变量 && 线程层 >= 0 && s->层 <= 线程层)
                错(根, "线程块里改不了外层的 `%.*s`。线程体是独立函数，外层变量按值拷进来，"
                       "改了外面看不到。\n"
                       "    想让它把结果带出去，就 `发送` 到通道里，外面 `接收`。",
                    根->文字长, 根->文字);
        }
        return 目;
    }

    case 节_调用: return 检调用(n);
    case 节_成员: return 检成员(n);
    case 节_下标: return 检下标(n);
    case 节_数组字面量: case 节_映射字面量: return 检字面量(n);

    case 节_借用: case 节_可变借用: {
        节点 *内 = n->子[0];
        int 可变 = (n->种类 == 节_可变借用);
        if (内->种类 == 节_名字) {
            符号 *s = 查名字(内->文字, 内->文字长);
            if (!s) {
                错(内, "找不到 `%.*s`", 内->文字长, 内->文字);
                return T未知;
            }
            记借用(s, 可变, n);
            return s->型;
        }
        /* 借用字段也要记在根变量上，否则 s.名字 的借用管不住 s */
        节点 *根 = 内;
        while (根 && 根->种类 == 节_成员) 根 = 根->子[0];
        if (根 && 根->种类 == 节_名字) {
            符号 *s = 查名字(根->文字, 根->文字长);
            if (s) 记借用(s, 可变, n);
        }
        return 检表达式(内);
    }

    case 节_复制: {
        类型 *t = 检表达式(n->子[0]);
        if (是复制类型(t))
            提示(n, "简单类型（整数、浮点、布尔）本来就是复制的，不用写 复制");
        return t;
    }

    case 节_移动: {
        节点 *内 = n->子[0];
        类型 *t = 检表达式(内);
        if (是复制类型(t)) {
            提示(n, "简单类型（整数、浮点、布尔）是复制而不是移动，写 移动 没有意义");
            return t;
        }
        if (内->种类 == 节_名字) {
            符号 *s = 查名字(内->文字, 内->文字长);
            if (s) {
                if (s->已移动) 错(内, "`%.*s` 已经被移动过一次了", 内->文字长, 内->文字);
                else if (s->可变借出) 错(内, "`%.*s` 正被借用，不能移动", 内->文字长, 内->文字);
                else s->已移动 = 1;
            }
        }
        return t;
    }

    case 节_结构字面量: return 检结构字面量(n);

    case 节_成功: {
        类型 *内 = n->子数 ? 检表达式(n->子[0]) : T空;
        return 双参类型(型_结果, 内, T任意);
    }
    case 节_失败: {
        类型 *内 = n->子数 ? 检表达式(n->子[0]) : T空;
        return 双参类型(型_结果, T任意, 内);
    }

    case 节_等待:
        return 检表达式(n->子[0]);

    case 节_接收: {
        类型 *t = 检表达式(n->子[0]);
        if (t->种 == 型_通道) return 包装类型(型_可空, t->元素);
        if (t->种 != 型_未知) {
            char *a = 型名(t);
            错(n, "`接收` 后面要是通道，这里是 %s", a);
            free(a);
        }
        return T未知;
    }

    case 节_通道: {
        类型 *内 = n->子数 ? 节点类型(n->子[0]) : T未知;
        return 包装类型(型_通道, 内);
    }

    case 节_匿名函数: {
        类型 *旧返 = 当前返回类型;
        /* 匿名函数的参数登记进新的一层 */
        进层();
        int 基层 = 当前层;        类型 *项[32]; int 数 = 0;
        节点 *声明 = n;
        设泛型环境(声明);
        for (int i = 0; i < n->子数; i++) {
            节点 *p = n->子[i];
            if (p->种类 != 节_参数) continue;
            类型 *pt = T未知;
            for (int k = 0; k < p->子数; k++)
                if (p->子[k]->种类 == 节_类型) pt = 节点类型(p->子[k]);
            if (数 < 32) 项[数++] = pt;
            符号 *s = 造符号(p->文字, p->文字长, 符_变量, pt, p);
            s->可变 = !(p->标志 & 标_不可变);
            登记(s);
        }
        类型 *返 = T空;
        节点 *r = 取返回类型(n);
        if (r) 返 = 节点类型(r);
        当前返回类型 = 返;

        for (int i = 0; i < n->子数; i++) {
            if (n->子[i]->种类 == 节_块) 检块(n->子[i]);
            else if (n->子[i]->种类 == 节_返回) 检语句(n->子[i]);
        }
        查匿名越界(n, 基层);
        当前返回类型 = 旧返;
        清泛型环境();
        出层();
        return 函数类型(项, 数, 返);
    }

    case 节_表达式语句:
        return 检表达式(n->子[0]);

    default:
        /* 其它节点（如结构字面量）目前语法层还没产出，出现就放行 */
        for (int i = 0; i < n->子数; i++) 检表达式(n->子[i]);
        return T未知;
    }
}

/* ============================================================================
 *  第十部分：查语句
 *  ----------------------------------------------------------------------------
 *  语句是"动作"。检查语句就是看这个动作的前因后果对不对：
 *      变量声明 → 初值的类型能不能装进声明的类型
 *      返回     → 返回的东西能不能装进函数的返回类型
 *      如果     → 条件是不是布尔
 *      对       → 容器能不能遍历，循环变量该是什么类型
 * ========================================================================== */

static void 声明变量(节点 *n, int 类)
{
    if (n->文字长 == 0) return;
    if (本层找(n->文字, n->文字长))
        错(n, "`%.*s` 在这一层已经有一个同名的了。换个名字，或者把它放到别的 { } 里",
            n->文字长, n->文字);

    类型 *声明类型 = T未知;
    if (n->子数 > 0 && n->子[0]->种类 == 节_类型) 声明类型 = 节点类型(n->子[0]);

    类型 *初值 = T未知;
    int 有初值 = 0;
    for (int i = 0; i < n->子数; i++) {
        if (n->子[i]->种类 == 节_类型 || n->子[i]->种类 == 节_块) continue;
        初值 = 按目标检(n->子[i], 声明类型);
        有初值 = 1;
        break;
    }

    if (n->种类 == 节_令) {
        声明类型 = 初值;
        if (!有初值) 错(n, "`令` 要靠初值来推断类型，后面必须写 `= ...`");
    } else if (有初值) {
        要求可赋值(声明类型, 初值, n, "初值类型和声明的类型对不上");
    }

    符号 *s = 造符号(n->文字, n->文字长, 类, 声明类型, n);
    s->可变 = (类 != 符_常量) && !(n->标志 & 标_不可变);
    登记(s);
}

/* 一个块：进一层，逐句查，出一层 */
static void 检块(节点 *n)
{
    进层();
    for (int i = 0; i < n->子数; i++) 检语句(n->子[i]);
    出层();
}

/* 条件里出现 `x != 空` 时，把 x 标记成"这个分支里已经确认有值" */
static int 记解包(节点 *条件, 节点 *块)
{
    if (!条件 || 条件->种类 != 节_二元) return 0;
    if (!名同(条件->文字, 条件->文字长, "!=", 2) &&
        !名同(条件->文字, 条件->文字长, "==", 2)) return 0;

    节点 *左 = 条件->子[0], *右 = 条件->子[1];
    节点 *目标 = NULL;
    if (右->种类 == 节_空 && 左->种类 == 节_名字) 目标 = 左;
    else if (左->种类 == 节_空 && 右->种类 == 节_名字) 目标 = 右;
    if (!目标) return 0;

    符号 *s = 查名字(目标->文字, 目标->文字长);
    if (!s || s->型->种 != 型_可空) return 0;

    /* `!= 空` 的 then 分支里一定有值；`== 空` 的 else 分支里一定有值。
     * 这里只处理最常见的前者，够挡住绝大多数误报。 */
    if (名同(条件->文字, 条件->文字长, "!=", 2) && 块) {
        int 旧 = s->已判空;
        s->已判空 = 1;
        检块(块);
        s->已判空 = 旧;
        return 1;
    }
    return 0;
}

/* 模式里的名字（`例 成功(值):` 的 值）要登记进作用域，否则块里用它会说"找不到" */
static int 是标识字符(unsigned char c)
{
    return (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') ||
           (c >= '0' && c <= '9') || c == '_' || c >= 0x80;
}

/* 从 `形状.圆(半径)` 里认出"圆"和"半径" */
static void 绑定变体模式(节点 *模式, 类型 *枚举)
{
    if (!模式 || !枚举 || 枚举->种 != 型_命名) return;
    符号 *s = 查全局(枚举->名, 枚举->名长);
    if (!s || s->类 != 符_枚举 || !s->定义体) return;

    const char *p = 模式->文字;
    int 长 = 模式->文字长;
    int 括号 = -1;
    for (int i = 0; i < 长; i++) if (p[i] == '(') { 括号 = i; break; }

    /* 变体名：括号前最后一个点之后的部分；没有括号就是整串 */
    int 头 = 0;
    for (int i = 0; i < (括号 >= 0 ? 括号 : 长); i++) if (p[i] == '.') 头 = i + 1;
    int 头长 = (括号 >= 0 ? 括号 : 长) - 头;
    if (头长 <= 0) return;

    节点 *变体 = NULL;
    for (int i = 0; i < s->定义体->子数; i++) {
        节点 *v = s->定义体->子[i];
        if (v->种类 != 节_变体) continue;
        if (名同(v->文字, v->文字长, p + 头, 头长)) { 变体 = v; break; }
    }
    if (!变体) return;

    /* 括号里按逗号切，依次对应变体的字段 */
    节点 *字段们[16]; int 字段数 = 0;
    for (int i = 0; i < 变体->子数 && 字段数 < 16; i++)
        if (变体->子[i]->种类 == 节_字段) 字段们[字段数++] = 变体->子[i];

    if (括号 < 0) return;
    设泛型环境(s->定义体);
    int 序 = 0, j = 括号 + 1;
    while (j < 长 && p[j] != ')' && 序 < 字段数) {
        int 起 = j;
        while (j < 长 && p[j] != ',' && p[j] != ')') j++;
        int 名长 = j - 起;
        while (名长 > 0 && p[起 + 名长 - 1] == ' ') 名长--;
        类型 *ft = T未知;
        for (int k = 0; k < 字段们[序]->子数; k++)
            if (字段们[序]->子[k]->种类 == 节_类型) ft = 节点类型(字段们[序]->子[k]);
        if (名长 > 0) {
            符号 *b = 造符号(p + 起, 名长, 符_变量, ft, 模式);
            b->可变 = 0;
            登记(b);
        }
        序++;
        if (j < 长 && p[j] == ',') j++;
    }
    清泛型环境();
}

static void 登记模式绑定(节点 *模式)
{
    if (!模式) return;
    const char *p = 模式->文字;
    int 长 = 模式->文字长;
    for (int i = 0; i < 长; i++) {
        if (p[i] != '(') continue;
        int j = i + 1;
        while (j < 长 && p[j] != ')') {
            int 起 = j;
            while (j < 长 && p[j] != ',' && p[j] != ')' && p[j] != ':') j++;
            const char *名 = p + 起;
            int 名长 = j - 起;
            if (j < 长 && p[j] == ':') {
                /* `名字: 类型` 这种写法，取冒号后面的类型名，不登记（这里只有模式，没有类型） */
                while (j < 长 && p[j] != ',' && p[j] != ')') j++;
            } else if (名长 > 0) {
                int 全标识 = 1;
                for (int k = 0; k < 名长; k++)
                    if (!是标识字符((unsigned char)名[k])) { 全标识 = 0; break; }
                if (全标识) {
                    符号 *s = 造符号(名, 名长, 符_变量, T未知, 模式);
                    登记(s);
                }
            }
            if (j < 长 && p[j] == ',') j++;
        }
        i = j;
    }
}

/* 枚举的匹配要穷尽：每个变体都得有分支，或者写一个 默认。
 * 不是枚举的对象（整数、字符串、布尔……）编译器判不出穷尽，一律要求兜底。 */
static int 有兜底分支(节点 *匹配)
{
    for (int i = 1; i < 匹配->子数; i++) {
        节点 *支 = 匹配->子[i];
        if (支->种类 == 节_默认) return 1;
        if (支->种类 != 节_例 || 支->子数 == 0) continue;
        const char *p = 支->子[0]->文字;
        int 长 = 支->子[0]->文字长;
        while (长 > 0 && (*p == ' ' || *p == '\t')) { p++; 长--; }
        while (长 > 0 && (p[长 - 1] == ' ' || p[长 - 1] == '\t')) 长--;
        if (长 == 1 && p[0] == '_') return 1;
    }
    return 0;
}

/* 模式写法的检查：错在这里报，总比让后端生成一段 .变体 出来强。
 * 枚举的变体名不在这里管，交 绑定变体模式。 */
static void 检查模式(节点 *模, 类型 *对象)
{
    if (!模 || !对象 || 对象->种 == 型_未知) return;

    const char *p = 模->文字;
    int 长 = 模->文字长;
    while (长 > 0 && (*p == ' ' || *p == '\t')) { p++; 长--; }
    while (长 > 0 && (p[长 - 1] == ' ' || p[长 - 1] == '\t')) 长--;
    if (长 == 1 && p[0] == '_') return;
    if (长 == 0) { 错(模, "`例` 后面要写一个模式"); return; }

    if (对象->种 == 型_命名) {
        符号 *es = 查全局(对象->名, 对象->名长);
        if (es && es->类 == 符_枚举) return;
    }

    int 是字符串 = (长 >= 2 && p[0] == '"' && p[长 - 1] == '"');
    int 是布尔 = (名同(p, 长, "真", 3) || 名同(p, 长, "假", 3));
    int 有范围 = 0;
    if (!是字符串)
        for (int i = 0; i < 长; i++) if (p[i] == '~') { 有范围 = 1; break; }

    if (有范围) {
        if (对象->种 != 型_整数 && 对象->种 != 型_浮点) {
            char *a = 型名(对象);
            错(模, "范围模式 `%s` 只能用在数字上，这里匹配的是 %s", p, a);
            free(a);
        }
        return;
    }

    if (是字符串) {
        if (对象->种 != 型_字符串) {
            char *a = 型名(对象);
            错(模, "模式 %s 是字符串，但匹配的对象是 %s", p, a);
            free(a);
        }
        return;
    }
    if (是布尔) {
        if (对象->种 != 型_布尔) {
            char *a = 型名(对象);
            错(模, "模式 `%s` 是布尔，但匹配的对象是 %s", p, a);
            free(a);
        }
        return;
    }

    int 像数字 = ((p[0] >= '0' && p[0] <= '9') || p[0] == '-' || p[0] == '+');
    if (像数字) {
        if (对象->种 != 型_整数 && 对象->种 != 型_浮点) {
            char *a = 型名(对象);
            错(模, "模式 %s 是数字，但匹配的对象是 %s", p, a);
            free(a);
        }
        return;
    }

    错(模, "看不懂这个模式：`%.*s`。非枚举的 匹配 支持字面量（`例 0:`、`例 \"好\":`）、"
           "范围（`例 1~9:`）和通配（`例 _:`）", 长, p);
}

static void 查穷尽(节点 *匹配, 类型 *对象)
{
    int 兜底 = 有兜底分支(匹配);
    int 是枚举 = 0;
    if (对象 && 对象->种 == 型_命名) {
        符号 *es = 查全局(对象->名, 对象->名长);
        是枚举 = (es && es->类 == 符_枚举 && es->定义体);
    }

    if (!是枚举) {
        /* 布尔只有两个值，`例 真:` 加 `例 假:` 写全了就是穷尽 */
        if (!兜底 && 对象 && 对象->种 == 型_布尔) {
            int 有真 = 0, 有假 = 0;
            for (int i = 1; i < 匹配->子数; i++) {
                节点 *支 = 匹配->子[i];
                if (支->种类 != 节_例 || 支->子数 == 0) continue;
                const char *p = 支->子[0]->文字;
                int 长 = 支->子[0]->文字长;
                while (长 > 0 && (*p == ' ' || *p == '\t')) { p++; 长--; }
                while (长 > 0 && (p[长 - 1] == ' ' || p[长 - 1] == '\t')) 长--;
                if (名同(p, 长, "真", 3)) 有真 = 1;
                if (名同(p, 长, "假", 3)) 有假 = 1;
            }
            if (有真 && 有假) return;
        }
        if (!兜底)
            错(匹配, "`匹配` 的对象不是枚举，编译器判不出穷尽，请补一行 `默认: { ... }`"
                     "（或者 `例 _: { ... }`）");
        return;
    }
    if (兜底) return;

    符号 *s = 查全局(对象->名, 对象->名长);

    /* 缺的可能不止一个，攒起来一次说完，别让人改一个编一次 */
    char 缺[512];
    int 缺长 = 0;
    缺[0] = '\0';
    for (int v = 0; v < s->定义体->子数; v++) {
        节点 *变体 = s->定义体->子[v];
        if (变体->种类 != 节_变体) continue;
        int 覆盖 = 0;
        for (int i = 1; i < 匹配->子数 && !覆盖; i++) {
            节点 *支 = 匹配->子[i];
            if (支->种类 != 节_例 || 支->子数 == 0) continue;
            节点 *模 = 支->子[0];
            for (int k = 0; k + 变体->文字长 <= 模->文字长; k++)
                if (memcmp(模->文字 + k, 变体->文字, 变体->文字长) == 0) { 覆盖 = 1; break; }
        }
        if (覆盖) continue;
        if (缺长 && 缺长 < 480) { memcpy(缺 + 缺长, "、", 3); 缺长 += 3; 缺[缺长] = '\0'; }
        if (缺长 + 变体->文字长 < 480) {
            memcpy(缺 + 缺长, 变体->文字, 变体->文字长);
            缺长 += 变体->文字长;
            缺[缺长] = '\0';
        }
    }
    if (缺长)
        错(匹配, "`匹配` 没有处理 `%s`，也没写 默认。枚举必须穷尽，补上缺的分支，或者加一行 `默认: { ... }`", 缺);
}

static void 检语句(节点 *n)
{
    if (!n) return;
    语句数++;
    int 借用标记 = 借用量;

    switch (n->种类) {
    case 节_块: 检块(n); break;

    case 节_变量: 声明变量(n, 符_变量); break;
    case 节_常量: 声明变量(n, 符_常量); break;
    case 节_令:  声明变量(n, 符_变量); break;

    case 节_返回: {
        节点 *值 = n->子数 ? n->子[0] : NULL;
        类型 *返 = 当前返回类型 ? 当前返回类型 : T空;
        if (!值) {
            if (返->种 != 型_空 && 返->种 != 型_未知) {
                char *a = 型名(返);
                错(n, "这个函数声明了返回 %s，`返回` 后面要写一个值", a);
                free(a);
            }
        } else {
            类型 *t = 按目标检(值, 返);
            if (返->种 == 型_空) {
                char *b = 型名(t);
                错(n, "这个函数没声明返回类型（等于返回空值），却返回了 %s", b);
                free(b);
            } else {
                要求可赋值(返, t, 值, "返回值的类型和函数声明的返回类型对不上");
            }
        }
        break;
    }

    case 节_如果: {
        /* 子：条件、块、[否则如果...]、[否则] */
        类型 *条 = 检表达式(n->子[0]);
        要求可赋值(T布尔, 条, n->子[0], "`如果` 的条件要是布尔值（用 ==、!=、<<、>> 这类比较得出）");
        if (!记解包(n->子[0], n->子[1]) && n->子[1]->种类 == 节_块) 检块(n->子[1]);

        for (int i = 2; i < n->子数; i++) {
            节点 *支 = n->子[i];
            if (支->种类 == 节_否则如果) {
                类型 *c = 检表达式(支->子[0]);
                要求可赋值(T布尔, c, 支->子[0], "`否则如果` 的条件要是布尔值");
                if (!记解包(支->子[0], 支->子[1]) && 支->子[1]->种类 == 节_块) 检块(支->子[1]);
            } else if (支->种类 == 节_否则) {
                if (支->子数 && 支->子[0]->种类 == 节_块) 检块(支->子[0]);
            }
        }
        break;
    }

    case 节_当: {
        类型 *条 = 检表达式(n->子[0]);
        要求可赋值(T布尔, 条, n->子[0], "`当` 的条件要是布尔值");
        当前循环深++;
        检块(n->子[1]);
        当前循环深--;
        break;
    }

    case 节_重复: {
        类型 *条 = 检表达式(n->子[0]);
        要求可赋值(T布尔, 条, n->子[0], "`重复循环直到` 后面要是布尔条件");
        当前循环深++;
        检块(n->子[1]);
        当前循环深--;
        break;
    }

    case 节_对: {
        类型 *容器 = T未知;
        int 是范围 = (n->标志 & 标_范围) != 0;
        节点 *块 = n->子[n->子数 - 1];
        /* `对 k, v 在 表` 时子[0] 是值变量名，容器在子[1] */
        int 双变量 = (!是范围 && n->子数 == 3 && n->子[0]->种类 == 节_名字);
        节点 *容器式 = 双变量 ? n->子[1] : n->子[0];

        进层();
        if (是范围) {
            类型 *起 = 检表达式(n->子[0]);
            类型 *止 = 检表达式(n->子[1]);
            if (起->种 != 型_整数 && 起->种 != 型_未知) {
                char *a = 型名(起);
                错(n->子[0], "范围循环的起点要是整数，这里是 %s", a);
                free(a);
            }
            if (止->种 != 型_整数 && 止->种 != 型_未知) {
                char *a = 型名(止);
                错(n->子[1], "范围循环的终点要是整数，这里是 %s", a);
                free(a);
            }
            容器 = T整数;
        } else {
            容器 = 检表达式(容器式);
            if (双变量 && 容器->种 != 型_映射 && 容器->种 != 型_未知) {
                char *a = 型名(容器);
                错(容器式, "只有映射能同时给出键和值，这里的 %s 不行——写成 `对 x 在 容器`", a);
                free(a);
            }
        }

        /* 循环变量该是什么类型 */
        类型 *变量型 = T未知;
        if (是范围) {
            变量型 = T整数;
        } else {
            switch (容器->种) {
            case 型_组:     变量型 = 容器->元素; break;
            case 型_映射:   变量型 = n->子数 >= 3 ? 容器->键 : 容器->键; break;
            case 型_字符串: 变量型 = T字符串; break;
            case 型_通道:   变量型 = 容器->元素; break;
            case 型_未知: case 型_任意: break;
            default: {
                char *a = 型名(容器);
                错(n->子[0], "%s 不能遍历。能遍历的是数组、映射、字符串、通道", a);
                free(a);
                break;
            }
            }
        }

        if (n->文字长) {
            符号 *s = 造符号(n->文字, n->文字长, 符_变量, 变量型, n);
            s->可变 = 0;        /* 循环变量是只读的，想改请自己另开一个 */
            登记(s);
        }
        /* 第二个循环变量（对 键, 值 在 表）：类型是映射的值类型 */
        if (双变量) {
            符号 *s2 = 造符号(n->子[0]->文字, n->子[0]->文字长, 符_变量, 容器->值, n->子[0]);
            s2->可变 = 0;
            登记(s2);
        }

        当前循环深++;
        if (块->种类 == 节_块) 检块(块);
        当前循环深--;
        出层();
        break;
    }

    case 节_匹配: {
        类型 *对象 = 检表达式(n->子[0]);
        查穷尽(n, 对象);
        for (int i = 1; i < n->子数; i++) {
            节点 *支 = n->子[i];
            if (支->种类 == 节_例) {
                进层();
                if (支->子数 > 0) {
                    检查模式(支->子[0], 对象);
                    登记模式绑定(支->子[0]);
                    绑定变体模式(支->子[0], 对象);
                }
                if (支->子数 > 1 && 支->子[1]->种类 == 节_块) 检块(支->子[1]);
                出层();
            } else if (支->种类 == 节_默认) {
                if (支->子数 && 支->子[0]->种类 == 节_块) 检块(支->子[0]);
            }
        }
        break;
    }

    case 节_循环:
        当前循环深++;
        检块(n->子[0]);
        当前循环深--;
        break;

    case 节_打断: case 节_继续:
        if (当前循环深 == 0)
            错(n, "`%s` 只能写在循环里，这里不在任何循环中",
                n->种类 == 节_打断 ? "打断" : "继续");
        break;

    case 节_线程: {
        int 旧 = 线程层;
        /* 线程体是一个独立的 void 函数，里面的 `返回` 只结束线程，
         * 不该被外层函数的返回类型管着（否则 `返回` 会被要求带一个值）。 */
        类型 *旧返 = 当前返回类型;
        线程层 = 当前层;
        当前返回类型 = T空;
        检块(n->子[0]);
        当前返回类型 = 旧返;
        线程层 = 旧;
        break;
    }

    case 节_发送: {
        类型 *管 = 检表达式(n->子[0]);
        类型 *值 = 检表达式(n->子[1]);
        if (管->种 == 型_通道) {
            要求可赋值(管->元素, 值, n->子[1], "往通道里送的值类型不对");
        } else if (管->种 != 型_未知) {
            char *a = 型名(管);
            错(n->子[0], "`发送` 的第一个参数要是通道，这里是 %s", a);
            free(a);
        }
        break;
    }

    case 节_关闭: {
        类型 *管 = 检表达式(n->子[0]);
        if (管->种 != 型_通道 && 管->种 != 型_未知) {
            char *a = 型名(管);
            错(n->子[0], "`关闭` 只能关通道，这里是 %s", a);
            free(a);
        }
        break;
    }

    case 节_不安全:
        检块(n->子[0]);
        break;

    case 节_表达式语句: {
        类型 *t = 检表达式(n->子[0]);
        (void)t;
        if (n->标志 & 标_失败返回) {
            if (!当前返回类型 || 当前返回类型->种 != 型_结果) {
                错(n, "`失败返回` 只能用在返回 结果 的函数里。这个函数%s",
                    当前返回类型 && 当前返回类型->种 == 型_空
                        ? "没有返回值" : "返回的不是 结果");
            }
        }
        break;
    }

    case 节_测试:
        当前在测试++;
        if (n->子数 && n->子[0]->种类 == 节_块) 检块(n->子[0]);
        当前在测试--;
        break;

    default:
        /* 声明类节点如果在语句位置出现，按声明处理 */
        if (n->种类 == 节_函数 || n->种类 == 节_结构) break;
        for (int i = 0; i < n->子数; i++) 检表达式(n->子[i]);
        break;
    }

    借用回滚(借用标记);
}

/* ============================================================================
 *  第十一部分：查一个函数
 *  ----------------------------------------------------------------------------
 *  函数的身体是检查的重点。进去之前先铺好三层东西：
 *      1. 泛型参数（T 这些）
 *      2. 参数（甲、乙，类型已定）
 *      3. 返回类型（`返回 xxx` 要拿它来对）
 * ========================================================================== */

/* 这个块是不是"必定返回"？用来发现"说好返回整数，结果某条路什么都不返回" */
static int 保证返回(节点 *n)
{
    if (!n) return 0;
    switch (n->种类) {
    case 节_返回: return 1;
    case 节_块:
        for (int i = n->子数 - 1; i >= 0; i--) {
            if (n->子[i]->种类 == 节_块 || n->子[i]->种类 == 节_如果 ||
                n->子[i]->种类 == 节_匹配 || n->子[i]->种类 == 节_返回)
                return 保证返回(n->子[i]);
        }
        return 0;
    case 节_如果: {
        /* 必须所有分支都返回，包括 否则 */
        int 有否则 = 0;
        for (int i = 2; i < n->子数; i++)
            if (n->子[i]->种类 == 节_否则) 有否则 = 1;
        if (!有否则) return 0;
        for (int i = 1; i < n->子数; i++) {
            节点 *支 = n->子[i];
            节点 *体 = (支->种类 == 节_块) ? 支 : (支->子数 ? 支->子[1] : NULL);
            if (支->种类 == 节_否则 && 支->子数) 体 = 支->子[0];
            if (!体 || !保证返回(体)) return 0;
        }
        return 1;
    }
    case 节_匹配: {
        int 有默认 = 0, 有分支 = 0;
        for (int i = 1; i < n->子数; i++) {
            if (n->子[i]->种类 == 节_默认) 有默认 = 1;
            if (n->子[i]->种类 == 节_例) 有分支 = 1;
        }
        /* 枚举穷尽的 匹配 不写 默认 也能覆盖全部情况，这时也算"必定返回" */
        if (!有默认 && !有分支) return 0;
        for (int i = 1; i < n->子数; i++) {
            节点 *支 = n->子[i];
            if (!支->子数) return 0;
            if (!保证返回(支->子[支->子数 - 1])) return 0;
        }
        return 1;
    }
    case 节_循环: return 1;      /* 死循环，后面走不到 */
    default: return 0;
    }
}

static void 检函数体(节点 *f, 类型 *自身)
{
    int 有体 = 0;
    for (int i = 0; i < f->子数; i++)
        if (f->子[i]->种类 == 节_块 || f->子[i]->种类 == 节_返回) 有体 = 1;
    if (!有体) return;                        /* 接口里的纯签名、外部函数，没有体 */

    类型 *旧自身 = 当前自身;
    节点 *旧函数 = 当前函数;
    类型 *旧返回 = 当前返回类型;
    int 旧循环 = 当前循环深;
    当前自身 = 自身;
    当前函数 = f;
    当前循环深 = 0;

    进层();
    设泛型环境(f);

    for (int i = 0; i < f->子数; i++) {
        节点 *p = f->子[i];
        if (p->种类 != 节_参数) continue;
        类型 *pt = T未知;
        for (int k = 0; k < p->子数; k++)
            if (p->子[k]->种类 == 节_类型) pt = 节点类型(p->子[k]);
        /* 借用参数：类型不变，但记下"它是借来的"，改它要报错（不可变借用） */
        符号 *s = 造符号(p->文字, p->文字长, 符_变量, pt, p);
        s->可变 = !(p->标志 & 标_借用);
        登记(s);
    }

    /* `实现 学生 为 可打印 { 函数 打印() -> 字符串 { 返回 名字 .. "岁" } }`
     * 方法体里直接写字段名就能用——相当于有个看不见的 `自身`。
     * 这是规范里定的写法，所以这里把字段当成普通名字登记进作用域。 */
    if (自身 && 自身->种 == 型_命名) {
        符号 *结构符号 = 查全局(自身->名, 自身->名长);
        if (结构符号 && 结构符号->类 == 符_结构 && 结构符号->定义体) {
            设泛型环境(结构符号->定义体);
            for (int i = 0; i < 结构符号->定义体->子数; i++) {
                节点 *fd = 结构符号->定义体->子[i];
                if (fd->种类 != 节_字段) continue;
                类型 *ft = T未知;
                for (int k = 0; k < fd->子数; k++)
                    if (fd->子[k]->种类 == 节_类型) ft = 节点类型(fd->子[k]);
                符号 *fs = 造符号(fd->文字, fd->文字长, 符_变量, ft, fd);
                登记(fs);
            }
            设泛型环境(f);
        }
    }

    节点 *返节点 = 取返回类型(f);
    当前返回类型 = 返节点 ? 节点类型(返节点) : T空;

    for (int i = 0; i < f->子数; i++) {
        if (f->子[i]->种类 == 节_块) {
            进层();
            for (int k = 0; k < f->子[i]->子数; k++) 检语句(f->子[i]->子[k]);
            出层();
        } else if (f->子[i]->种类 == 节_返回) {
            检语句(f->子[i]);
        }
    }

    /* 声明了要返回值，但最后一条语句不保证返回，提醒一句 */
    if (当前返回类型 && 当前返回类型->种 != 型_空 && 当前返回类型->种 != 型_未知) {
        int 有块 = 0; 节点 *体 = NULL;
        for (int i = 0; i < f->子数; i++)
            if (f->子[i]->种类 == 节_块) { 有块 = 1; 体 = f->子[i]; }
        if (有块 && !保证返回(体)) {
            char *a = 型名(当前返回类型);
            提示(f, "这个函数声明返回 %s，但不是所有路都会 `返回`。漏了的那条路会返回空值", a);
            free(a);
        }
    }

    清泛型环境();
    出层();

    当前自身 = 旧自身;
    当前函数 = 旧函数;
    当前返回类型 = 旧返回;
    当前循环深 = 旧循环;
}

/* 一个接口要求哪些方法、各是什么签名 */
static void 检实现块(节点 *n)
{
    /* 子[0] 是实现者类型，之后是接口名，节_函数 是方法 */
    类型 *自身 = n->子数 ? 节点类型(n->子[0]) : T未知;

    if (实现数 < 128) {
        int 首个接口 = -1;
        for (int i = 1; i < n->子数; i++)
            if (n->子[i]->种类 == 节_名字) { 首个接口 = i; break; }
        if (首个接口 > 0) {
            实现表[实现数].类型 = 自身;
            实现表[实现数].接口名 = n->子[首个接口]->文字;
            实现表[实现数].接口名长 = n->子[首个接口]->文字长;
            实现表[实现数].块 = n;
            实现数++;
        }
    }

    /* 方法体逐个查。
     * 查之前先把这一块里的方法名登记到一层临时作用域里：
     * 同一个实现块里的方法互相调用是常事（`招呼` 里调 `名字`），
     * 写 `名字()` 就该找到自己这个类型的方法，不必先有"自身"这个名字。
     * 用完就出层——别的类型也有同名方法，不能让它们互相看见。 */
    进层();
    for (int i = 0; i < n->子数; i++) {
        节点 *m = n->子[i];
        if (m->种类 != 节_函数 || !m->文字) continue;
        符号 *s = 造符号(m->文字, m->文字长, 符_函数, 函数签名(m), m);
        s->定义体 = m;
        s->可变 = 0;
        登记(s);
    }
    for (int i = 0; i < n->子数; i++)
        if (n->子[i]->种类 == 节_函数) 检函数体(n->子[i], 自身);
    出层();

    /* 接口要求的方法，是不是都给了 */
    for (int i = 1; i < n->子数; i++) {
        节点 *名 = n->子[i];
        if (名->种类 != 节_名字) continue;
        符号 *接 = 查全局(名->文字, 名->文字长);
        if (!接) {
            错(名, "找不到接口 `%.*s`", 名->文字长, 名->文字);
            continue;
        }
        if (接->类 != 符_接口) {
            错(名, "`%.*s` 不是接口，不能写在 `实现 … 为 …` 后面", 名->文字长, 名->文字);
            continue;
        }
        if (!接->定义体) continue;

        for (int k = 0; k < 接->定义体->子数; k++) {
            节点 *要 = 接->定义体->子[k];
            if (要->种类 != 节_函数) continue;

            节点 *给 = NULL;
            for (int m = 0; m < n->子数; m++)
                if (n->子[m]->种类 == 节_函数 &&
                    名同(n->子[m]->文字, n->子[m]->文字长, 要->文字, 要->文字长)) { 给 = n->子[m]; break; }

            if (!给) {
                /* 接口里带默认体的方法可以不实现 */
                int 有默认 = 0;
                for (int m = 0; m < 要->子数; m++)
                    if (要->子[m]->种类 == 节_块) 有默认 = 1;
                if (!有默认)
                    错(n, "`%.*s` 这个接口要求有 `%.*s` 方法，但这里没写",
                        名->文字长, 名->文字, 要->文字长, 要->文字);
                continue;
            }

            类型 *要签 = 函数签名(要);
            类型 *给签 = 函数签名(给);
            if (!可赋值(要签, 给签) || !可赋值(给签, 要签)) {
                char *x = 型名(要签), *y = 型名(给签);
                错(给, "`%.*s` 的签名和接口里的不一样：\n    接口要求 %s\n    这里写的 %s",
                    给->文字长, 给->文字, x, y);
                free(x); free(y);
            }
        }
    }
}

/* ============================================================================
 *  第十二部分：跑完整流程
 *  ----------------------------------------------------------------------------
 *  顺序不能乱：
 *      建花名册（名字都在了） → 记下谁实现了谁（类型比较要用） → 逐个查函数体
 *  因为"查函数体"时会问"这个结构实现了那个接口吗"，所以实现表必须先填。
 * ========================================================================== */

static void 打印符号表(void)
{
    printf("--- 全局符号表 ---\n");
    for (int b = 0; b < 全局桶数; b++) {
        for (符号 *s = 全局表[b]; s; s = s->链) {
            char *t = 型名(s->型);
            const char *类 =
                s->类 == 符_函数 ? "函数" : s->类 == 符_结构 ? "结构" :
                s->类 == 符_枚举 ? "枚举" : s->类 == 符_接口 ? "接口" :
                s->类 == 符_常量 ? "常量" : s->类 == 符_变量 ? "变量" :
                s->类 == 符_外部类型 ? "外部类型" : "其他";
            printf("%-6s %-24s %s\n", 类, s->名 ? s->名 : "?", t);
            free(t);
        }
    }
}

static void 分析(节点 *根)
{
    注册内置函数();
    建花名册(根);

    /* 数一数有多少个"东西" */
    for (int i = 0; i < 根->子数; i++) {
        switch (根->子[i]->种类) {
        case 节_函数: 函数数++; break;
        case 节_结构: 结构数++; break;
        case 节_枚举: 枚举数++; break;
        case 节_接口: 接口数++; break;
        default: break;
        }
    }

    /* 顶层变量和常量的初值也要查（它们可能在别处被用到） */
    进层();
    for (int i = 0; i < 根->子数; i++) {
        节点 *n = 根->子[i];
        if (n->种类 == 节_变量) 声明变量(n, 符_变量);
        else if (n->种类 == 节_常量) 声明变量(n, 符_常量);
        else if (n->种类 == 节_令) 声明变量(n, 符_变量);
    }
    出层();

    /* 实现块：先填"谁实现了谁"，再查方法体 */
    for (int i = 0; i < 根->子数; i++)
        if (根->子[i]->种类 == 节_实现) 检实现块(根->子[i]);

    /* 顶层函数 */
    for (int i = 0; i < 根->子数; i++) {
        节点 *n = 根->子[i];
        if (n->种类 == 节_函数) 检函数体(n, NULL);
        else if (n->种类 == 节_测试) {
            当前在测试++;
            检块(n->子[0]);
            当前在测试--;
        } else if (n->种类 == 节_编译期) {
            for (int k = 0; k < n->子数; k++)
                if (n->子[k]->种类 == 节_函数) 检函数体(n->子[k], NULL);
        } else if (n->种类 == 节_宏) {
            /* 宏的参数没有类型，块里的名字全是占位，跳过不查 */
        }
    }
}

/* 基准模式要反复跑，每轮开始前把"上一轮的记忆"擦干净 */
static void 重置语义状态(void)
{
    memset(全局表, 0, sizeof(全局表));
    诊断数 = 0; 错误数 = 0; 提示数 = 0;
    实现数 = 0;
    函数数 = 结构数 = 枚举数 = 接口数 = 语句数 = 表达式数 = 0;
    当前域 = NULL; 当前层 = 0;
    借用量 = 0;
    当前自身 = NULL; 当前返回类型 = NULL; 当前循环深 = 0; 当前在测试 = 0;
    泛型个数 = 0;
    for (int i = 0; i < 32; i++) 泛型实参[i] = NULL;
}

static void 打印诊断(void)
{
    for (int i = 0; i < 诊断数; i++) {
        诊断 *d = &诊断表[i];
        printf("[%s] 第 %d 行 第 %d 列：%s\n",
               d->级 ? "提示" : "错误", d->行, d->列, d->话);
    }
}

/* 反复跑"解析 + 语义"，看每秒能处理多少源码。
 * 词只切一遍（切词是上一棒的功劳，这里只测这一棒），解析和检查每轮都重跑。 */
static int 跑基准(const char *路径)
{
    int 源长 = 0;
    char *源 = 读文件(路径, &源长);
    if (!源) { fprintf(stderr, "打不开文件：%s\n", 路径); return 1; }

    int 词数 = 0, 词法错误 = 0;
    词 *词们 = 切好所有词(源, 源长, &词数, &词法错误);

    /* 热身三轮，让 CPU 缓存热起来 */
    for (int i = 0; i < 3; i++) {
        重置语义状态();
        语法器 P;
        备好语法器(&P, 词们, 词数, 源, 源长, 路径);
        节点 *根 = 解析程序(&P);
        分析(根);
        释放树(根);
    }

    struct timespec 起, 止;
    long 轮数 = 0;
    double 秒 = 0;
    clock_gettime(CLOCK_MONOTONIC, &起);
    do {
        重置语义状态();
        语法器 P;
        备好语法器(&P, 词们, 词数, 源, 源长, 路径);
        节点 *根 = 解析程序(&P);
        分析(根);
        释放树(根);
        轮数++;
        clock_gettime(CLOCK_MONOTONIC, &止);
        秒 = (止.tv_sec - 起.tv_sec) + (止.tv_nsec - 起.tv_nsec) / 1e9;
    } while (秒 < 0.5);

    printf("文件        %s（%.1f KB）\n", 路径, 源长 / 1024.0);
    printf("词数        %d\n", 词数);
    printf("轮数        %ld\n", 轮数);
    printf("每轮表达式  %ld\n", 表达式数);
    printf("耗时        %.3f 秒\n", 秒);
    printf("吞吐        %.1f MB/s\n", (double)源长 * 轮数 / 1048576.0 / 秒);
    printf("速度        %.1f 万表达式/秒\n", (double)表达式数 * 轮数 / 秒 / 10000.0);

    free(词们);
    free(源);
    return 0;
}

#ifndef 简_只要语义

int main(int argc, char **argv)
{
    if (argc < 2) {
        fprintf(stderr,
            "简言 · 语义分析器\n"
            "用法：\n"
            "  简语义 文件.jy            检查并报告问题\n"
            "  简语义 -符号表 文件.jy    顺便打印全局符号表\n"
            "  简语义 -基准 文件.jy      反复分析，测速度\n");
        return 2;
    }

    建常用类型();
    建关键字表();

    if (argc >= 3 && strcmp(argv[1], "-基准") == 0) return 跑基准(argv[2]);

    int 打表 = 0;
    const char *路径 = argv[1];
    if (strcmp(argv[1], "-符号表") == 0 && argc >= 3) {
        打表 = 1;
        路径 = argv[2];
    }

    int 源长 = 0;
    char *源 = 读文件(路径, &源长);
    if (!源) {
        fprintf(stderr, "打不开文件：%s\n", 路径);
        return 1;
    }

    struct timespec 起, 止;
    clock_gettime(CLOCK_MONOTONIC, &起);

    int 词数 = 0, 词法错误 = 0;
    词 *词们 = 切好所有词(源, 源长, &词数, &词法错误);

    语法器 P;
    备好语法器(&P, 词们, 词数, 源, 源长, 路径);
    节点 *根 = 解析程序(&P);

    if (词法错误 || P.错误数) {
        fprintf(stderr, "语法阶段就有 %d 个错误，语义分析可能不准，先修好语法\n",
                词法错误 + P.错误数);
    }

    分析(根);

    clock_gettime(CLOCK_MONOTONIC, &止);
    double 毫秒 = ((止.tv_sec - 起.tv_sec) * 1e9 + (止.tv_nsec - 起.tv_nsec)) / 1e6;

    printf("=== 语义检查：%s ===\n", 路径);
    printf("函数 %ld 个   结构 %ld 个   枚举 %ld 个   接口 %ld 个\n",
           函数数, 结构数, 枚举数, 接口数);
    printf("检查了 %ld 条语句、%ld 个表达式\n", 语句数, 表达式数);
    printf("\n");

    打印诊断();

    printf("\n--- 汇总 ---\n");
    printf("错误 %d 个，提示 %d 个\n", 错误数, 提示数);
    /* 耗时只往 stderr 走：stdout 要保持完全确定，才能和参考实现逐字节对答案 */
    fprintf(stderr, "耗时 %.2f 毫秒（%.1f 万表达式/秒）\n", 毫秒,
            毫秒 > 0 ? 表达式数 / 毫秒 / 10.0 : 0);

    if (打表) 打印符号表();

    int 失败 = (错误数 > 0) || (词法错误 + P.错误数) > 0;
    释放树(根);
    free(词们);
    free(源);
    return 失败 ? 1 : 0;
}

#endif /* 简_只要语义 */
