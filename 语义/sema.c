/* ============================================================================
 *  简言 · 语义分析器（sema.c）
 *  ----------------------------------------------------------------------------
 *  上一棒是语法分析器：它把源码搭成一棵树，能告诉你"这句话的结构对不对"。
 *  但它不知道这句话"讲不讲得通"。比如：
 *
 *      整数 甲 = "你好"          ← 结构完美，但类型不对
 *      打印(乙)                  ← 结构完美，但 乙 根本不存在
 *      引用 = 借用 甲
 *      甲 = 2                    ← 甲 被借走了，不能再改
 *
 *  这一棒就干三件事：
 *    1. 查名字：这个变量/函数/类型，到底存不存在？在哪一层？
 *    2. 查类型：两边能不能对上？函数参数给对了吗？返回值和声明的返回类型一致吗？
 *    3. 查所有权：被借出去的变量不能改；搬走的变量不能再用；可能为空的值不能直接当值用。
 *
 *  ----------------------------------------------------------------------------
 *  为什么分两遍看代码？
 *    函数 甲() { 乙() }
 *    函数 乙() { ... }
 *    甲 里用到 乙，可 乙 写在后面。如果边读边查，读到 甲 的那一行就找不到 乙。
 *  所以第一遍先把"有哪些名字"登记下来（只登记，不看函数体），
 *  第二遍才逐个函数进去查。这叫"先建花名册，再点名"。
 *
 *  ----------------------------------------------------------------------------
 *  三个原则，贯穿整份代码：
 *    - 报错不中断。发现一个错，记下来，接着查下一个。一次编译把问题都说完，
 *      而不是让人改一个、编一次、再改一个。
 *    - 每个错误都告诉人"怎么办"，不只说"错了"。
 *    - 认不出来的东西就当"任意"类型放行，绝不因为一处不懂就崩掉整份分析。
 *
 *  编译：
 *      gcc -O3 -flto -s -o 简语义 sema.c
 * ========================================================================== */

