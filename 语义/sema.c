/* 把签名文字里的 @ ! 换成真实类型，再读成 型_函数 */
static 类型 *读签名(const char *文, 类型 *元素, 类型 *键)
{
    char 缓[512];
    int 出 = 0;
    for (const char *p = 文; *p && 出 < (int)sizeof(缓) - 32; p++) {
        if (*p == '@' || *p == '!') {
            类型 *t = (*p == '@') ? 元素 : 键;
            char *e = t ? 类型文字(t) : strdup("未知");
            for (char *q = e; *q && 出 < (int)sizeof(缓) - 2; q++) 缓[出++] = *q;
            free(e);
        } else {
            缓[出++] = *p;
        }
    }
    缓[出] = '\0';

    型串 q = { 缓, 出, 0, 0, 0 };
    类型 *项[8]; int 数 = 0;
    型跳空(&q);
    if (型吃(&q, "(")) { 数 = 型读清单(&q, 项, 8, ')'); 型吃(&q, ")"); }
    类型 *返 = T空;
    if (型吃(&q, "->")) { 型跳空(&q); 返 = 读类型后缀(&q, 解析型文(&q)); }
    return 函数类型(项, 数, 返);
}

/* 零参数的"属性"：`词.长度`、`结果.是成功`。取它得到值，不是得到函数。
 * 判断依据是签名里没有参数表，直接以 `->` 开头。 */
static int 是内置属性(类型 *对象, const char *名, int 长)
{
    if (!对象) return 0;
    for (int i = 0; i < (int)(sizeof(内置表) / sizeof(内置表[0])); i++) {
        if (内置表[i].对象种 != 对象->种) continue;
        if (!名同(内置表[i].名, (int)strlen(内置表[i].名), 名, 长)) continue;
        return 内置表[i].签[0] == '-' && 内置表[i].签[1] == '>';
    }
    return 0;
}

/* 查内置方法。找到返回函数类型，找不到返回 NULL */
static 类型 *查内置(类型 *对象, const char *名, int 长)
{
    if (!对象) return NULL;
    类型 *元素 = NULL, *键 = NULL;
    /* 字符串的"元素"是它自己的一个字符，也就是 字符串。
     * 少了这一行，`文本.切分(",")` 会去找 `未知 组`，报一个连行号都没有的错。 */
    if (对象->种 == 型_字符串) 元素 = T字符串;
    else if (对象->种 == 型_组) 元素 = 对象->元素;
    else if (对象->种 == 型_映射) { 键 = 对象->键; 元素 = 对象->值; }
    else if (对象->种 == 型_可空) 元素 = 对象->元素;
    else if (对象->种 == 型_结果) { 键 = 对象->键; 元素 = 对象->值; }

    for (int i = 0; i < (int)(sizeof(内置表) / sizeof(内置表[0])); i++) {
        if (内置表[i].对象种 != 对象->种) continue;
        if (!名同(内置表[i].名, (int)strlen(内置表[i].名), 名, 长)) continue;
        return 读签名(内置表[i].签, 元素, 键);
    }
    return NULL;
}

/* 结构的字段：在结构的定义节点里找 节_字段 */
static 类型 *查字段(节点 *定义体, const char *名, int 长)
{
    if (!定义体) return NULL;
    设泛型环境(定义体);
    类型 *结果 = NULL;
    for (int i = 0; i < 定义体->子数; i++) {
        节点 *f = 定义体->子[i];
        if (f->种类 != 节_字段) continue;
        if (!名同(f->文字, f->文字长, 名, 长)) continue;
        for (int k = 0; k < f->子数; k++)
            if (f->子[k]->种类 == 节_类型) 结果 = 节点类型(f->子[k]);
        break;
    }
    清泛型环境();
    return 结果;
}

/* 结构的方法：在 实现 X 为 Y 的块里找同名函数 */
static 类型 *查实现方法(类型 *对象, const char *名, int 长)
{
    for (int i = 0; i < 实现数; i++) {
        if (!名同(实现表[i].类型->名, 实现表[i].类型->名长, 对象->名, 对象->名长)) continue;
        节点 *块 = 实现表[i].块;
        for (int k = 0; k < 块->子数; k++) {
            节点 *f = 块->子[k];
            if (f->种类 != 节_函数) continue;
            if (!名同(f->文字, f->文字长, 名, 长)) continue;
            /* 方法里的 `自身` 就是这个结构 */
            类型 *旧 = 当前自身;
            当前自身 = 对象;
            节点 *头 = f;
            类型 *签 = 函数签名(头);
            当前自身 = 旧;
            return 签;
        }
    }
    return NULL;
}

/* 接口的默认方法 */
static 类型 *查接口默认(类型 *对象, const char *名, int 长)
{
    (void)对象;
    for (int i = 0; i < 实现数; i++) {
        for (int j = 0; j < 实现表[i].块->子数; j++) {
            节点 *f = 实现表[i].块->子[j];
            if (f->种类 == 节_函数 && 名同(f->文字, f->文字长, 名, 长)) return 函数签名(f);
        }
        /* 去接口定义里找带默认体的方法 */
        符号 *s = 查全局(实现表[i].接口名, 实现表[i].接口名长);
        if (!s || !s->定义体) continue;
        for (int j = 0; j < s->定义体->子数; j++) {
            节点 *f = s->定义体->子[j];
            if (f->种类 != 节_函数) continue;
            if (!名同(f->文字, f->文字长, 名, 长)) continue;
            /* 有函数体才算默认方法 */
            for (int k = 0; k < f->子数; k++)
                if (f->子[k]->种类 == 节_块) return 函数签名(f);
        }
    }
    return NULL;
}

/* 枚举的变体：`形状.圆` 里的 `.圆` 不是字段，是"造一个圆"的入口。
 * 有字段的变体像函数（圆(1.0)），没字段的就是个值（点）。 */
static 节点 *查枚举变体(节点 *成员节点, 类型 **出枚举)
{
    if (!成员节点 || 成员节点->种类 != 节_成员) return NULL;
    节点 *基 = 成员节点->子[0];
    if (基->种类 != 节_名字) return NULL;
    符号 *s = 查名字(基->文字, 基->文字长);
    if (!s || s->类 != 符_枚举) return NULL;
    if (!s->定义体) return NULL;
    *出枚举 = s->型;
    for (int i = 0; i < s->定义体->子数; i++) {
        节点 *v = s->定义体->子[i];
        if (v->种类 != 节_变体) continue;
        if (名同(v->文字, v->文字长, 成员节点->文字, 成员节点->文字长)) return v;
    }
    *出枚举 = NULL;
    return NULL;
}

/* 变体带字段时，把它看成"参数是各字段、返回枚举"的函数 */
static 类型 *变体构造类型(节点 *变体, 类型 *枚举)
{
    类型 *项[16];
    int 数 = 0;
    for (int i = 0; i < 变体->子数 && 数 < 16; i++) {
        节点 *f = 变体->子[i];
        if (f->种类 != 节_字段) continue;
        for (int k = 0; k < f->子数; k++)
            if (f->子[k]->种类 == 节_类型) 项[数++] = 节点类型(f->子[k]);
    }
    if (数 == 0) return 枚举;
    return 函数类型(项, 数, 枚举);
}

/* 成员的总入口：给一个对象类型和一个名字，返回它的类型 */
static 类型 *成员类型(类型 *对象, const char *名, int 长, 节点 *处, int 自动解包)
{
    if (!对象) return T未知;

    if (对象->种 == 型_可空) {
        /* 可空值只能用这几个，其余必须先解包 */
        if (名同(名, 长, "取值", 6) || 名同(名, 长, "或默认", 9) || 名同(名, 长, "有值", 6))
            return 查内置(对象, 名, 长);
        /* 在 `如果 x != 空 就 { ... }` 的块里，x 已经确认有值了 */
        节点 *根 = 处;
        int 已确认 = 0;
        if (根 && 根->子数 > 0) {
            节点 *基 = 根->子[0];
            while (基 && 基->种类 == 节_成员) 基 = 基->子[0];
            if (基 && 基->种类 == 节_名字) {
                符号 *s = 查名字(基->文字, 基->文字长);
                if (s && s->已判空) 已确认 = 1;
            }
        }
        if (!自动解包 && !已确认) {
            char *t = 型名(对象);
            错(处, "这是 %s，可能为空，不能直接取 `.%.*s`。先写 如果 它 != 空 就 { ... }，或者写 它.取值()", t, 长, 名);
            free(t);
            return T未知;
        }
    }

    类型 *内 = 查内置(对象, 名, 长);
    if (内) return 内;

    if (对象->种 == 型_命名) {
        符号 *s = 查全局(对象->名, 对象->名长);
        if (s && (s->类 == 符_结构 || s->类 == 符_外部类型)) {
            类型 *f = 查字段(s->定义体, 名, 长);
            if (f) return f;
            类型 *m = 查实现方法(对象, 名, 长);
            if (m) return m;
        }
    }
    类型 *m2 = 查接口默认(对象, 名, 长);
    if (m2) return m2;

    char *t = 型名(对象);
    错(处, "%s 没有叫 `%.*s` 的字段或方法", t, 长, 名);
    free(t);
    return T未知;
}

/* ============================================================================
 *  第八部分：借用的账本
 *  ----------------------------------------------------------------------------
 *  "借用"就是"我只看不改"或"我要改，别人先别看"。
 *  规则只有两条，好记：
 *      1. 同一时刻，要么很多人看（不可变借用），要么只有一个人改（可变借用）
 *      2. 被别人看着/改着的时候，主人自己不能动它
 *
 *  借到什么时候为止？到这一句结束为止。这比真正的编译器宽松（它算得更细），
 *  但足够挡住"边遍历边删除"这类真会出事的写法，而且不会冤枉好人。
 * ========================================================================== */

typedef struct { 符号 *符; int 可变; } 借用项;
static 借用项 借用栈[512];
static int 借用量 = 0;

static void 借用回滚(int 标记)
{
    while (借用量 > 标记) {
        借用项 *b = &借用栈[--借用量];
        if (b->可变) b->符->可变借出 = 0;
        else if (b->符->借出次数 > 0) b->符->借出次数--;
    }
}

static int 记借用(符号 *s, int 可变, 节点 *处)
{
    if (可变) {
        if (s->可变借出) {
            错(处, "`%.*s` 已经被可变借用了。同一时刻只能有一个人改它", s->名长, s->名);
            return 0;
        }
        if (s->借出次数 > 0) {
            错(处, "`%.*s` 正被别人借着看，不能同时可变借用。等那句用完再改", s->名长, s->名);
            return 0;
        }
        if (!s->可变) {
            错(处, "`%.*s` 是常量或不可变变量，不能可变借用。声明时去掉 不可变 / 别用 常量", s->名长, s->名);
            return 0;
        }
        if (s->已移动) {
            错(处, "`%.*s` 已经被移动走了，不能再借用", s->名长, s->名);
            return 0;
        }
        s->可变借出 = 1;
    } else {
        if (s->可变借出) {
            错(处, "`%.*s` 正被可变借用，这期间不能借去看。等改完再借", s->名长, s->名);
            return 0;
        }
        if (s->已移动) {
            错(处, "`%.*s` 已经被移动走了，不能再借用", s->名长, s->名);
            return 0;
        }
        s->借出次数++;
    }
    if (借用量 < 512) 借用栈[借用量++] = (借用项){ s, 可变 };
    return 1;
}

