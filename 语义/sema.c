/* 一个值是"复制"还是"移动"？只有这几种简单的按位拷贝才复制。
 * 字符串虽然简单，但它背后有堆内存，所以按移动处理（和 Rust 的 String 一致）。 */
static int 是复制类型(类型 *t)
{
    if (!t) return 1;
    switch (t->种) {
    case 型_整数: case 型_浮点: case 型_布尔: case 型_空:
    case 型_未知: case 型_任意: case 型_类型:
    /* 大整数与小数在 C 里是一个指针，而且我们保证不可变——
     * 赋值只是复制 8 字节，复制完两边各说各的，谁也不用担心对方改。
     * 所以它们算"复制类型"，传参不必写 `借用`，这是刻意的设计取舍：
     * 用"不可变"换掉一整片生命周期标注。 */
    case 型_大整数: case 型_小数:
    /* 图 与 声音 是句柄：赋值只搬 { 长度, 指针 } 这么个小结构体，
     * 两个变量指向同一块像素/采样。要独立副本就 .缩放 / .放大，那里会真拷贝。 */
    case 型_图: case 型_声音:
    /* 套接字、监听器也是句柄：里面只有一个堆上的结构体指针，
     * 复制变量就是复制指针，两边指向同一个连接——这正是我们要的。 */
    case 型_套接字: case 型_监听器:
        return 1;
    default:
        return 0;
    }
}

/* ============================================================================
 *  第二部分：符号表（花名册）
 *  ----------------------------------------------------------------------------
 *  每声明一个东西，就在花名册上记一行：叫什么、是什么、什么类型、在哪儿声明。
 *  花名册分层：函数里的一层，函数里每个 { } 再一层。查名字从里往外找，
 *  找到内层的就停——内层的同名变量"遮住"外层的，这正是人期待的行为。
 *
 *      全局：函数 加法 / 结构 学生 / 常量 圆周率
 *        └ 函数 加法 的参数表：甲、乙
 *             └ 函数体 { } 里的：和
 *
 *  为什么要分层？因为出了这个 { }，里面的变量就该消失了。
 *  分层还能顺带把"重名"查出来：同一层里不许两个同名。
 * ========================================================================== */

enum {
    符_变量, 符_常量, 符_函数, 符_结构, 符_枚举, 符_接口, 符_类型别名,
    符_外部类型, 符_类型参数, 符_方法
};

typedef struct 符号 符号;
struct 符号 {
    const char *名;
    int 名长;
    int 类;
    类型 *型;
    节点 *声明;
    节点 *定义体;            /* 结构/枚举/接口的节点本身，用来查字段、变体、方法 */
    int 可变;                /* 变量是否可改 */
    int 已移动;              /* 被 移动 走了，之后不许再用 */
    int 借出次数;            /* 当前有几次不可变借用 */
    int 可变借出;            /* 当前是否被可变借用（0/1） */
    int 已判空;              /* 已经确认非空（在 `如果 x != 空` 的块里） */
    int 层;                  /* 声明在第几层，报错时用 */
    int 内置;                /* 编译器自带的（打印/开方/读图……），用户可同名覆盖 */
    struct 符号 *链;         /* 同一层的下一个 */
};

typedef struct 作用域 作用域;
struct 作用域 {
    作用域 *外;
    符号 *头;                /* 这一层的符号链 */
    int 个数;
    int 是不是函数体;        /* 函数体这一层要把参数也放进来 */
};

/* 全局名字表：桶数组 + 链 */
#define 全局桶数 1024
static 符号 *全局表[全局桶数];

static unsigned 名字哈希(const char *p, int 长)
{
    unsigned h = 2166136261u;
    for (int i = 0; i < 长; i++) { h ^= (unsigned char)p[i]; h *= 16777619u; }
    return h % 全局桶数;
}

static 符号 *造符号(const char *名, int 名长, int 类, 类型 *型, 节点 *声明)
{
    符号 *s = calloc(1, sizeof(符号));
    if (!s) { fprintf(stderr, "内存不够了\n"); exit(2); }
    s->名 = 名; s->名长 = 名长;
    s->类 = 类; s->型 = 型 ? 型 : T未知;
    s->声明 = 声明;
    s->可变 = 1;
    return s;
}

/* 登记到全局表（顶层声明用） */
static void 登全局(符号 *s)
{
    unsigned h = 名字哈希(s->名, s->名长);
    s->链 = 全局表[h];
    全局表[h] = s;
}

static 符号 *查全局(const char *名, int 长)
{
    for (符号 *s = 全局表[名字哈希(名, 长)]; s; s = s->链)
        if (s->名长 == 长 && memcmp(s->名, 名, 长) == 0) return s;
    return NULL;
}

static 作用域 *当前域 = NULL;
static int 当前层 = 0;
static long 符号总数 = 0;

/* 正处在几层 `线程 { }` 里；-1 表示不在任何线程块中。
 * 线程体是抬成独立函数跑的，外层变量按**值**拷进新函数——
 * 所以在里面给外层变量赋值不会传回来。这种"写了等于没写"必须当错误报，
 * 不能让它编译通过然后静默丢写。 */
static int 线程层 = -1;

static void 进层(void)
{
    作用域 *z = calloc(1, sizeof(作用域));
    z->外 = 当前域;
    当前域 = z;
    当前层++;
}

static void 出层(void)
{
    if (!当前域) return;
    作用域 *z = 当前域;
    当前域 = z->外;
    当前层--;
    /* 符号本身留在符号池里不释放：报错信息里可能还指着它的名字 */
    free(z);
}

static 符号 *本层找(const char *名, int 长)
{
    for (符号 *s = 当前域 ? 当前域->头 : NULL; s; s = s->链)
        if (s->名长 == 长 && memcmp(s->名, 名, 长) == 0) return s;
    return NULL;
}

static 符号 *查名字(const char *名, int 长)
{
    for (作用域 *z = 当前域; z; z = z->外)
        for (符号 *s = z->头; s; s = s->链)
            if (s->名长 == 长 && memcmp(s->名, 名, 长) == 0) return s;
    return 查全局(名, 长);
}

/* 登记一个局部符号。同一层重名要报错——这是最常见的手滑。 */
static 符号 *登记(符号 *s)
{
    s->层 = 当前层;
    s->链 = 当前域->头;
    当前域->头 = s;
    当前域->个数++;
    符号总数++;
    return s;
}

/* ============================================================================
 *  第三部分：报错
 *  ----------------------------------------------------------------------------
 *  每条报错都要能回答三个问题：哪儿、错在哪、怎么改。
 *  位置精确到行列，因为人看的是编辑器里的光标。
 * ========================================================================== */

typedef struct {
    int 行, 列;
    int 级;                 /* 0 错误，1 提示 */
    char 话[768];
} 诊断;

#define 最多诊断 512
static 诊断 诊断表[最多诊断];
static int 诊断数 = 0;
static int 错误数 = 0, 提示数 = 0;
static int 静默 = 0;         /* 试读时不报错 */

static void 报(int 级, int 行, int 列, const char *格式, ...)
{
    if (静默) return;
    /* 同一个位置同一句话只说一次，避免一个错误引发十行重复 */
    for (int i = 0; i < 诊断数; i++)
        if (诊断表[i].行 == 行 && 诊断表[i].列 == 列 && 诊断表[i].级 == 级)
            return;

    if (级 == 0) 错误数++; else 提示数++;
    if (诊断数 >= 最多诊断) return;

    诊断 *d = &诊断表[诊断数++];
    d->行 = 行; d->列 = 列; d->级 = 级;
    va_list 参;
    va_start(参, 格式);
    vsnprintf(d->话, sizeof(d->话), 格式, 参);
    va_end(参);
}

#define 错(节点, ...)  报(0, (节点)->行, (节点)->列, __VA_ARGS__)
#define 提示(节点, ...) 报(1, (节点)->行, (节点)->列, __VA_ARGS__)

/* 打印一个类型名，用于报错。用完要 free。 */
static char *型名(类型 *t) { return 类型文字(t); }

/* ============================================================================
 *  第四部分：把类型文字变成类型
 *  ----------------------------------------------------------------------------
 *  语法分析器已经不折腾类型结构了，它只把类型拼成一段规范文字存下来：
 *      "映射[字符串, 整数] 组"
 *  这一步就是把这段文字再读回来，变成能查成员、能比较的类型对象。
 *
 *  读法还是递归下降——和当初解析源码一个套路，只不过这次读的是类型字符串：
 *      类型 = 前缀 ["组" ["[" 数字 "]"]]
 *      前缀 = 整数 | 映射[类型, 类型] | 可空[类型] | 函数(类型,...) -> 类型 | 名字
 * ========================================================================== */

/* 当前正在分析的声明有哪些泛型参数（T、U 这些），解析类型时要认得出它们 */
static const char *泛型名[32];
static int 泛型名长[32];
/* 单态化时填：T 到底换成了什么。语义分析阶段全是 NULL，
 * 于是 T 仍然是「型_参数」，检查时一律放行。 */
static 类型 *泛型实参[32];
static int 泛型个数 = 0;

/* `实现 X 为 Y` 块里，`自身` 指的就是 X */
static 类型 *当前自身 = NULL;

typedef struct { const char *p; int 长, 位, 行, 列; } 型串;

static void 型跳空(型串 *q)
{
    while (q->位 < q->长 && (q->p[q->位] == ' ' || q->p[q->位] == '\t')) q->位++;
}

static int 型看(型串 *q, const char *词)
{
    型跳空(q);
    int n = (int)strlen(词);
    if (q->位 + n > q->长) return 0;
    return memcmp(q->p + q->位, 词, n) == 0;
}

static int 型吃(型串 *q, const char *词)
{
    if (!型看(q, 词)) return 0;
    q->位 += (int)strlen(词);
    return 1;
}

/* 读一个名字（到空格、逗号、括号、方括号为止） */
static int 型读名(型串 *q, const char **出, int *出长)
{
    型跳空(q);
    int 起 = q->位;
    while (q->位 < q->长) {
        char c = q->p[q->位];
        if (c == ' ' || c == ',' || c == ']' || c == ')' || c == '[' || c == '(') break;
        q->位++;
    }
    if (q->位 == 起) return 0;
    *出 = q->p + 起;
    *出长 = q->位 - 起;
    return 1;
}

static 类型 *解析型文(型串 *q);

/* 解析型文 只吃"基本类型"这一段，`组` 后缀要调用方自己接——
 * 解析器那边是在 解析类型文 里接的，这里也得接，否则签名表里的
 * `-> @ 组` 会被读成"返回元素类型"，`组.复制()` 就变成了返回 整数。 */
static 类型 *读类型后缀(型串 *q, 类型 *基)
{
    for (;;) {
        型跳空(q);
        if (!型吃(q, "组")) break;
        int 长 = -1;
        if (型吃(q, "[")) {
            型跳空(q);
            int v = 0;
            while (q->位 < q->长 && q->p[q->位] >= '0' && q->p[q->位] <= '9') {
                v = v * 10 + (q->p[q->位] - '0'); q->位++;
            }
            长 = v;
            型吃(q, "]");
        }
        基 = 组类型(基, 长);
    }
    return 基;
}

/* 逗号分隔的类型清单，读到 收 为止 */
static int 型读清单(型串 *q, 类型 **项, int 上限, char 收)
{
    int 数 = 0;
    型跳空(q);
    if (q->位 < q->长 && q->p[q->位] == 收) return 0;
    for (;;) {
        类型 *t = 读类型后缀(q, 解析型文(q));
        if (数 < 上限) 项[数] = t;
        数++;
        型跳空(q);
        if (q->位 < q->长 && q->p[q->位] == ',') { q->位++; continue; }
        break;
    }
    return 数 < 上限 ? 数 : 上限;
}

static 类型 *查类型名(const char *名, int 长, int 行, int 列)
{
    /* 泛型参数优先：函数里的 T 会遮住外面的同名类型 */
    for (int i = 0; i < 泛型个数; i++)
        if (泛型名长[i] == 长 && memcmp(泛型名[i], 名, 长) == 0) {
            /* 已经知道 T 是什么了（单态化阶段），直接用具体类型 */
            if (泛型实参[i]) return 泛型实参[i];
            类型 *t = 新类型(型_参数);
            char *副本 = malloc(长 + 1);
            memcpy(副本, 名, 长);
            副本[长] = '\0';
            t->名 = 副本; t->名长 = 长;
            return 入池(t);
        }

    符号 *s = 查全局(名, 长);
    if (!s) {
        报(0, 行, 列, "不认识的类型 `%.*s`。检查一下拼写，或者这个类型是不是忘了定义", 长, 名);
        return T未知;
    }
    switch (s->类) {
    case 符_结构: case 符_枚举: case 符_接口: case 符_外部类型:
        return 命名类型(名, 长);
    case 符_类型别名:
        return s->型 ? s->型 : T未知;
    case 符_类型参数:
        return s->型 ? s->型 : T未知;
    default:
        报(0, 行, 列, "`%.*s` 是个%s，不能当类型用",
            长, 名,
            s->类 == 符_函数 ? "函数" : s->类 == 符_常量 ? "常量" : "变量");
        return T未知;
    }
}

static 类型 *解析型文(型串 *q)
{
    型跳空(q);
    if (q->位 >= q->长) return T未知;

    /* 基本类型 */
    struct { const char *名; 类型 *型; } 基本[] = {
        { "整数64", NULL }, { "整数32", NULL }, { "整数16", NULL }, { "整数8", NULL },
        { "整数", NULL }, { "浮点", NULL }, { "布尔值", NULL }, { "字符串", NULL },
        { "空值", NULL }, { "任意", NULL }, { "类型", NULL }, { "图", NULL },
        { "大整数", NULL }, { "小数", NULL }, { "声音", NULL },
        { "套接字", NULL }, { "监听器", NULL }
    };
    int 基本数 = (int)(sizeof(基本) / sizeof(基本[0]));
    /* 先长后短，否则 "整数64" 会被 "整数" 抢走。
     * "大整数"、"小数" 放在最后：没有谁以"大"或"小"开头，不会被前 12 项截胡。 */
    const char *顺序[] = { "整数64", "整数32", "整数16", "整数8", "整数",
                           "浮点", "布尔值", "字符串", "空值", "任意", "类型", "图",
                           "大整数", "小数", "声音", "套接字", "监听器" };
    for (int i = 0; i < 基本数; i++) {
        const char *w = 顺序[i];
        int n = (int)strlen(w);
        if (q->位 + n <= q->长 && memcmp(q->p + q->位, w, n) == 0) {
            /* 后面不能直接接字母数字，否则 "整数字段" 会被当成 "整数" */
            if (q->位 + n < q->长) {
                char c = q->p[q->位 + n];
                if ((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (unsigned char)c >= 0x80) continue;
            }
            q->位 += n;
            if (i == 0) return T整数64;
            if (i == 1) return T整数32;
            if (i == 2) return T整数16;
            if (i == 3) return T整数8;
            if (i == 4) return T整数;
            if (i == 5) return T浮点;
            if (i == 6) return T布尔;
            if (i == 7) return T字符串;
            if (i == 8) return T空;
            if (i == 9) return T任意;
            if (i == 10) return T类型;
            if (i == 11) return T图;
            if (i == 12) return T大整数;
            if (i == 13) return T小数;
            if (i == 14) return T声音;
            if (i == 15) return T套接字;
            return T监听器;
        }
    }

    if (型吃(q, "自身")) {
        if (当前自身) return 当前自身;
        /* 接口里写 `自身` 时还不知道将来是谁实现它，先当成一个类型参数。
         * 检查实现时，"类型参数"跟谁都对得上，正好合适。 */
        类型 *t = 新类型(型_参数);
        char *副本 = malloc(7);
        memcpy(副本, "自身", 6);
        副本[6] = '\0';
        t->名 = 副本; t->名长 = 6;
        return 入池(t);
    }

    if (型吃(q, "映射")) {
        类型 *项[2]; int 数 = 0;
        if (型吃(q, "[")) { 数 = 型读清单(q, 项, 2, ']'); 型吃(q, "]"); }
        if (数 < 2) {
            报(0, q->行, q->列, "映射 要写两个类型：键和值，比如 映射[字符串, 整数]");
            return T未知;
        }
        return 双参类型(型_映射, 项[0], 项[1]);
    }

    if (型吃(q, "可空")) {
        类型 *项[1]; int 数 = 0;
        if (型吃(q, "[")) { 数 = 型读清单(q, 项, 1, ']'); 型吃(q, "]"); }
        if (数 < 1) { 报(0, q->行, q->列, "可空 要写里面的类型，比如 可空[整数]"); return T未知; }
        return 包装类型(型_可空, 项[0]);
    }

    if (型吃(q, "通道")) {
        类型 *项[1]; int 数 = 0;
        if (型吃(q, "[")) { 数 = 型读清单(q, 项, 1, ']'); 型吃(q, "]"); }
        if (数 < 1) { 报(0, q->行, q->列, "通道 要写里面装什么，比如 通道[整数]"); return T未知; }
        return 包装类型(型_通道, 项[0]);
    }

    if (型吃(q, "结果")) {
        类型 *项[2]; int 数 = 0;
        if (型吃(q, "[")) { 数 = 型读清单(q, 项, 2, ']'); 型吃(q, "]"); }
        if (数 < 2) {
            报(0, q->行, q->列, "结果 要写两个类型：成功值和错误原因，比如 结果[字符串, 字符串]");
            return T未知;
        }
        return 双参类型(型_结果, 项[0], 项[1]);
    }

    if (型吃(q, "元组")) {
        类型 *项[16]; int 数 = 0;
        if (型吃(q, "[")) { 数 = 型读清单(q, 项, 16, ']'); 型吃(q, "]"); }
        if (数 == 0) { 报(0, q->行, q->列, "元组 至少要有一个类型"); return T未知; }
        类型 *t = 新类型(型_元组);
        t->项 = malloc(sizeof(类型 *) * 数);
        for (int i = 0; i < 数; i++) t->项[i] = 项[i];
        t->项数 = 数;
        return 入池(t);
    }

    if (型吃(q, "函数")) {
        类型 *项[16]; int 数 = 0;
        if (型吃(q, "(")) { 数 = 型读清单(q, 项, 16, ')'); 型吃(q, ")"); }
        类型 *返 = T空;
        if (型吃(q, "->")) { 型跳空(q); 返 = 解析型文(q); }
        return 函数类型(项, 数, 返);
    }

    /* 剩下的都是名字 */
    const char *名; int 长;
    int 起 = q->位;
    if (!型读名(q, &名, &长)) return T未知;
    类型 *基 = 查类型名(名, 长, q->行, q->列);
    (void)起;
    return 基;
}

/* 入口：读一段类型文字，处理完 "…… 组[10]" 这类后缀 */
static 类型 *读类型(const char *文, int 长, int 行, int 列)
{
    型串 q = { 文, 长, 0, 行, 列 };
    类型 *t = 解析型文(&q);
    for (;;) {
        型跳空(&q);
        if (!型吃(&q, "组")) break;
        int 长度 = 0;
        if (型吃(&q, "[")) {
            int 数 = 0;
            while (q.位 < q.长 && q.p[q.位] >= '0' && q.p[q.位] <= '9') {
                数 = 数 * 10 + (q.p[q.位] - '0');
                q.位++;
            }
            if (型吃(&q, "]")) 长度 = 数;
        }
        t = 组类型(t, 长度);
    }
    return t;
}

/* 节点上的类型 → 类型对象 */
static 类型 *节点类型(节点 *类型节点)
{
    if (!类型节点 || 类型节点->种类 != 节_类型) return T未知;
    return 读类型(类型节点->文字, 类型节点->文字长, 类型节点->行, 类型节点->列);
}

/* ============================================================================
 *  第五部分：第一遍——建花名册
 *  ----------------------------------------------------------------------------
 *  这一步只干一件事：把"有哪些名字"记下来。不看函数体，不查类型对不对。
 *  分两小步，因为名字之间会互相引用：
 *      A. 先把所有名字占个位（结构 学生、函数 查找……），类型暂时空着
 *      B. 再把每个名字的真实类型填上（这时 学生 已经在册，字段就能写 学生 了）
 * ========================================================================== */

typedef struct {
    类型 *类型;
    const char *接口名;
    int 接口名长;
    节点 *块;
} 实现记录;

static 实现记录 实现表[128];
static int 实现数 = 0;

static int 名同(const char *a, int 长a, const char *b, int 长b)
{
    return 长a == 长b && memcmp(a, b, 长a) == 0;
}

/* 顶层节点里，真正"声明了东西"的是这几种 */
static int 是声明节点(节点 *n)
{
    switch (n->种类) {
    case 节_函数: case 节_结构: case 节_枚举: case 节_接口:
    case 节_常量: case 节_变量: case 节_令:
        return 1;
    default:
        return 0;
    }
}

/* 把泛型参数清单（节_泛型 节点，文字形如 "T: 可比较"）设进当前环境 */
static void 设泛型环境(节点 *声明)
{
    泛型个数 = 0;
    for (int i = 0; i < 声明->子数 && 泛型个数 < 32; i++) {
        节点 *g = 声明->子[i];
        if (g->种类 != 节_泛型) continue;
        int 长 = g->文字长;
        for (int k = 0; k < g->文字长; k++) if (g->文字[k] == ':') { 长 = k; break; }
        while (长 > 0 && g->文字[长 - 1] == ' ') 长--;
        泛型名[泛型个数] = g->文字;
        泛型名长[泛型个数] = 长;
        泛型实参[泛型个数] = NULL;
        泛型个数++;
    }
}

static void 清泛型环境(void) { 泛型个数 = 0; }

/* 给第 i 个泛型参数绑一个具体类型（单态化用）。i 从 0 开始 */
static void 绑泛型(int i, 类型 *t)
{
    if (i >= 0 && i < 泛型个数) 泛型实参[i] = t;
}

/* 从函数节点里取：返回类型节点（没有就返回 NULL） */
static 节点 *取返回类型(节点 *函数)
{
    for (int i = 0; i < 函数->子数; i++)
        if (函数->子[i]->种类 == 节_类型) return 函数->子[i];
    return NULL;
}

/* 把函数签名算成 型_函数 */
static 类型 *函数签名(节点 *函数)
{
    类型 *项[32];
    int 数 = 0;
    for (int i = 0; i < 函数->子数; i++) {
        节点 *p = 函数->子[i];
        if (p->种类 != 节_参数) continue;
        类型 *t = T未知;
        for (int k = 0; k < p->子数; k++)
            if (p->子[k]->种类 == 节_类型) t = 节点类型(p->子[k]);
        /* 借用只是"传的时候不搬走"，类型本身不变，所以签名里不体现借用。
         * 检查实参时再去函数的声明节点上看 `借用` 标志。 */
        if (数 < 32) 项[数++] = t;
    }
    类型 *返 = T空;
    节点 *r = 取返回类型(函数);
    if (r) 返 = 节点类型(r);
    return 函数类型(项, 数, 返);
}

/* ---- A 步：占位 ---- */
static void 占位(节点 *n)
{
    if (!n || !是声明节点(n)) return;
    if (n->文字长 == 0) return;

    int 类 = 符_变量;
    switch (n->种类) {
    case 节_函数:   类 = 符_函数; break;
    case 节_结构:   类 = 符_结构; break;
    case 节_枚举:   类 = 符_枚举; break;
    case 节_接口:   类 = 符_接口; break;
    case 节_常量:   类 = 符_常量; break;
    default:        类 = 符_变量; break;
    }

    符号 *旧 = 查全局(n->文字, n->文字长);
    if (旧) {
        if (旧->声明 == n) return;
        /* 内置的名字可以被用户顶掉。
         * 理由：`开方`、`最大` 这种名字太自然，用户手写一份差不多的实现很常见。
         * 让编译器自带的那份让位，比逼用户改名（`开方2`？）合理。
         * 反过来不行——用户写完，内置再抢回去，那就成了"我写的函数没被调用"。 */
        if (旧->内置) {
            旧->内置 = 0;
            旧->声明 = n;
            旧->定义体 = n;
            旧->型 = T未知;
            旧->类 = 类;
            旧->可变 = !(n->标志 & 标_不可变);
            return;
        }
        return;
    }
    符号 *s = 造符号(n->文字, n->文字长, 类, T未知, n);
    s->定义体 = n;
    s->可变 = !(n->标志 & 标_不可变);
    登全局(s);
}

/* ---- B 步：填类型 ---- */
static void 填类型(节点 *n)
{
    if (!n || !是声明节点(n)) return;
    符号 *s = 查全局(n->文字, n->文字长);
    if (!s || s->声明 != n) return;

    设泛型环境(n);

    switch (n->种类) {
    case 节_函数:
        s->型 = 函数签名(n);
        break;

    case 节_结构:
    case 节_枚举:
    case 节_接口:
        s->型 = 命名类型(n->文字, n->文字长);
        break;

    case 节_变量:
    case 节_常量: {
        类型 *t = T未知;
        if (n->子数 > 0 && n->子[0]->种类 == 节_类型) t = 节点类型(n->子[0]);
        s->型 = t;
        break;
    }
    default: break;
    }

    清泛型环境();
}

/* 从 节_外部 节点里把声明捞出来，登记成 符_外部类型 / 符_函数 */
static void 收集外部(节点 *n)
{
    for (int i = 0; i < n->子数; i++) {
        节点 *c = n->子[i];
        if (c->种类 == 节_名字) {
            符号 *s = 造符号(c->文字, c->文字长, 符_外部类型, 命名类型(c->文字, c->文字长), c);
            s->定义体 = c;
            登全局(s);
        } else if (c->种类 == 节_函数) {
            符号 *s = 造符号(c->文字, c->文字长, 符_函数, T未知, c);
            s->定义体 = c;
            /* 外部函数没有函数体，标记一下 */
            s->已移动 = 1;  /* 借用"已移动"这个位表示"没有函数体可查"，别的地方不读它 */
            登全局(s);
            s->型 = 函数签名(c);
        }
    }
}

