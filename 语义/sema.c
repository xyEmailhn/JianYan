/* ============================================================================
 *  第一部分：类型怎么表示
 *  ----------------------------------------------------------------------------
 *  源码里的类型是一串文字（"映射[字符串, 整数]"）。分析的时候得把它变成
 *  能比较、能查成员的结构。所以这里给类型拍一张"证件照"：
 *
 *      种    —— 它属于哪一类（整数？组？映射？）
 *      位宽  —— 整数是几位的（8/16/32/64）
 *      元素  —— 组/可空/通道 里面装的是什么
 *      键 值 —— 映射的键和值，结果的"成功类型"和"错误类型"
 *      项    —— 元组的各元素，函数的各参数
 *      返回  —— 函数的返回类型
 *      长度  —— 定长数组的长度
 *
 *  同一张"证件照"只留一份（去重），比较两个类型就是比较指针。这样快，也不容易错。
 * ========================================================================== */

enum {
    型_未知,     /* 分析不下去时的占位。它对谁都能赋值，绝不引发连环报错 */
    型_空,       /* 空值：没有值的值 */
    型_整数, 型_浮点, 型_布尔, 型_字符串,
    型_任意,     /* 任意：FFI、宏之类确实说不清类型的地方用它 */
    型_类型,     /* 类型的类型，写 类型 时用 */
    型_命名,     /* 结构、枚举、接口、外部类型 */
    型_参数,     /* 泛型参数 T：还不确定具体是什么，检查时一律放行 */
    型_组, 型_映射, 型_元组, 型_可空, 型_结果, 型_通道, 型_函数,
    型_图,       /* 图片：RGBA8 像素缓冲 + 宽高。改动见 规范/第三方_v0.7.md */
    型_大整数,   /* 任意精度整数：libtommath，见 规范 第 13 节 */
    型_小数,     /* 十进制高精度浮点：mpdecimal，按全局精度舍入 */
    型_声音,     /* 音频：float32 交错采样 + 帧数/声道/采样率。见 规范 第 14 节 */
    型_套接字,   /* TCP 连接：句柄 + 读写缓冲。见 规范/标准库_v0.2 第 3 节 */
    型_监听器    /* TCP 监听：句柄，等来的连接叫 套接字 */
};

typedef struct 类型 类型;
struct 类型 {
    unsigned char 种;
    unsigned char 位宽;      /* 整数的位数；浮点固定 64 */
    const char *名;          /* 型_命名 / 型_参数 时，名字是什么 */
    int 名长;
    类型 *元素;              /* 组/可空/通道 */
    类型 *键, *值;           /* 映射；结果 里 键=成功类型，值=错误类型 */
    类型 **项;               /* 元组、函数参数 */
    int 项数;
    类型 *返回;              /* 函数返回类型 */
    int 长度;                /* 定长数组长度，0 表示不定长 */
    unsigned 哈希;           /* 算过一次就记住，报错和去重都要用 */
    unsigned 已哈希;
    struct 类型 *池链;        /* 总链，退出时统一释放 */
    struct 类型 *桶链;        /* 去重表里的链 */
};

static 类型 *类型池 = NULL;
static 类型 *类型桶[4096];    /* 按签名去重 */

static 类型 *新类型(int 种)
{
    类型 *t = calloc(1, sizeof(类型));
    if (!t) { fprintf(stderr, "内存不够了\n"); exit(2); }
    t->种 = (unsigned char)种;
    t->池链 = 类型池;
    类型池 = t;
    return t;
}

/* 把类型写成一段规范文字，比如 "映射[字符串, 整数] 组"。
 * 这段文字既用来去重，也用来在报错里描述类型（"你给的是 X，要的是 Y"）。 */
typedef struct { char *p; int 长, 容量; } 段;

static void 段放(段 *s, const char *文)
{
    int 加 = (int)strlen(文);
    if (s->长 + 加 + 1 > s->容量) {
        s->容量 = (s->长 + 加 + 1) * 2;
        s->p = realloc(s->p, s->容量);
        if (!s->p) { fprintf(stderr, "内存不够了\n"); exit(2); }
    }
    memcpy(s->p + s->长, 文, 加 + 1);
    s->长 += 加;
}

static void 段格式(段 *s, const char *格式, ...)
{
    char 缓[128];
    va_list 参;
    va_start(参, 格式);
    vsnprintf(缓, sizeof(缓), 格式, 参);
    va_end(参);
    段放(s, 缓);
}

static void 类型写文(类型 *t, 段 *s);

static void 类型写文(类型 *t, 段 *s)
{
    if (!t) { 段放(s, "未知"); return; }
    switch (t->种) {
    case 型_未知:   段放(s, "未知"); break;
    case 型_空:     段放(s, "空值"); break;
    case 型_整数:
        if (t->位宽 == 8)  段放(s, "整数8");
        else if (t->位宽 == 16) 段放(s, "整数16");
        else if (t->位宽 == 64) 段放(s, "整数64");
        else if (t->位宽 == 32) 段放(s, "整数32");
        else 段放(s, "整数");
        break;
    case 型_浮点:   段放(s, "浮点"); break;
    case 型_布尔:   段放(s, "布尔值"); break;
    case 型_字符串: 段放(s, "字符串"); break;
    case 型_图:     段放(s, "图"); break;
    case 型_大整数: 段放(s, "大整数"); break;
    case 型_小数:   段放(s, "小数"); break;
    case 型_声音:   段放(s, "声音"); break;
    case 型_套接字: 段放(s, "套接字"); break;
    case 型_监听器: 段放(s, "监听器"); break;
    case 型_任意:   段放(s, "任意"); break;
    case 型_类型:   段放(s, "类型"); break;
    case 型_命名:   段放(s, t->名 ? t->名 : "?"); break;
    case 型_参数:   段放(s, t->名 ? t->名 : "?"); break;
    case 型_组:
        类型写文(t->元素, s);
        段放(s, " 组");
        if (t->长度) 段格式(s, "[%d]", t->长度);
        break;
    case 型_映射:
        段放(s, "映射[");
        类型写文(t->键, s); 段放(s, ", ");
        类型写文(t->值, s); 段放(s, "]");
        break;
    case 型_元组:
        段放(s, "元组[");
        for (int i = 0; i < t->项数; i++) {
            if (i) 段放(s, ", ");
            类型写文(t->项[i], s);
        }
        段放(s, "]");
        break;
    case 型_可空:
        段放(s, "可空["); 类型写文(t->元素, s); 段放(s, "]");
        break;
    case 型_结果:
        段放(s, "结果[");
        类型写文(t->键, s); 段放(s, ", ");
        类型写文(t->值, s); 段放(s, "]");
        break;
    case 型_通道:
        段放(s, "通道["); 类型写文(t->元素, s); 段放(s, "]");
        break;
    case 型_函数:
        段放(s, "函数(");
        for (int i = 0; i < t->项数; i++) {
            if (i) 段放(s, ", ");
            类型写文(t->项[i], s);
        }
        段放(s, ")");
        if (t->返回 && t->返回->种 != 型_空) {
            段放(s, " -> ");
            类型写文(t->返回, s);
        }
        break;
    }
}

/* 取类型的规范文字（调用者负责 free） */
static char *类型文字(类型 *t)
{
    段 s = {0};
    段放(&s, "");
    类型写文(t, &s);
    return s.p ? s.p : strdup("?");
}

/* 去重：同样的结构只留一份，比较类型时比指针就行。
 * 哈希值算一次就存进类型里，因为报错、去重都要反复用。 */
static unsigned 类型哈希(类型 *t)
{
    if (t->已哈希) return t->哈希;
    char *文 = 类型文字(t);
    unsigned h = 2166136261u;
    for (char *q = 文; *q; q++) { h ^= (unsigned char)*q; h *= 16777619u; }
    free(文);
    t->哈希 = h & 4095u;
    t->已哈希 = 1;
    return t->哈希;
}

static int 类型同构(类型 *a, 类型 *b)
{
    if (a == b) return 1;
    if (!a || !b) return 0;
    if (a->种 != b->种) return 0;
    if (a->位宽 != b->位宽 || a->长度 != b->长度) return 0;
    if (a->种 == 型_命名 || a->种 == 型_参数) {
        return a->名长 == b->名长 && a->名 && b->名 && memcmp(a->名, b->名, a->名长) == 0;
    }
    if (!类型同构(a->元素, b->元素)) return 0;
    if (!类型同构(a->键, b->键)) return 0;
    if (!类型同构(a->值, b->值)) return 0;
    if (!类型同构(a->返回, b->返回)) return 0;
    if (a->项数 != b->项数) return 0;
    for (int i = 0; i < a->项数; i++)
        if (!类型同构(a->项[i], b->项[i])) return 0;
    return 1;
}

static 类型 *入池(类型 *t)
{
    unsigned h = 类型哈希(t);
    for (类型 *q = 类型桶[h]; q; q = q->桶链)
        if (q->哈希 == h && 类型同构(q, t)) return q;
    t->桶链 = 类型桶[h];
    类型桶[h] = t;
    return t;
}

static 类型 *型_取(int 种)
{
    类型 *n = 新类型(种);
    return 入池(n);
}

static 类型 *整数类型(int 位宽)
{
    类型 *t = 新类型(型_整数);
    t->位宽 = (unsigned char)位宽;
    return 入池(t);
}

static 类型 *包装类型(int 种, 类型 *内)
{
    类型 *t = 新类型(种);
    t->元素 = 内;
    return 入池(t);
}

static 类型 *双参类型(int 种, 类型 *a, 类型 *b)
{
    类型 *t = 新类型(种);
    t->键 = a; t->值 = b;
    return 入池(t);
}

static 类型 *命名类型(const char *名, int 长)
{
    类型 *t = 新类型(型_命名);
    char *副本 = malloc(长 + 1);
    memcpy(副本, 名, 长);
    副本[长] = '\0';
    t->名 = 副本; t->名长 = 长;
    return 入池(t);
}

static 类型 *组类型(类型 *元素, int 长度)
{
    类型 *t = 新类型(型_组);
    t->元素 = 元素; t->长度 = 长度;
    return 入池(t);
}

static 类型 *函数类型(类型 **项, int 项数, 类型 *返回)
{
    /* 项数 为负只可能是上游算错了，但让它流进 malloc 就是"申请 2^64 字节"，
     * gcc 会当场警告，运行时则直接崩。这里兜住，坏数据变成一个零参函数。 */
    if (项数 < 0) 项数 = 0;
    类型 *t = 新类型(型_函数);
    t->项 = malloc(sizeof(类型 *) * (项数 ? 项数 : 1));
    for (int i = 0; i < 项数; i++) t->项[i] = 项[i];
    t->项数 = 项数; t->返回 = 返回;
    return 入池(t);
}

