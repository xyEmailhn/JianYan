/* ============================================================================
 *  简渲 · 场景文件（场景.c）
 *  ----------------------------------------------------------------------------
 *  场景文件的唯一设计目标：**AI 写三行就能出图，人读一遍就能改**。
 *
 *  所以它长这样：
 *
 *      球 (0, 0.8, 0) 0.8 材质 金
 *      光 面 (3, 4, 2) 大小 (3, 2) 强度 8
 *
 *  三条规矩：
 *    1. 键可以省。`球 位置 (0,0,0) 半径 0.5` 和 `球 (0,0,0) 0.5` 等价。
 *    2. 键可以换顺序。参数按名字找，不按位置。
 *    3. 缺的都有一份"好看"的默认值：材质白瓷、相机自动取景、灯光柔和。
 *
 *  这不是在发明新语法——它就是简言函数调用的空格版：
 *      `球(位置: (0,0,0), 半径: 0.5, 材质: 金)`
 *  去掉括号和冒号，就是场景文件。
 * ========================================================================== */

