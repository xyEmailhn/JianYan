static 图元 *造形(场景 *s, const char *命令, 参数 *p, 值 *参, int 参n)
{
    /* 先按位置参数补默认：`球 (0,0,0) 0.5` */
    if (参n > 0 && 参[0].是向量) p->位 = 参[0].v;
    else if (参n > 0) p->位 = 三一(参[0].f);

    if (同(命令, "球") || 同(命令, "球体")) {
        if (p->半径 < 0) p->半径 = (参n > 1) ? 参[1].f : 0.5f;
        return 造图元(元_球, p->位, p->半径, 三零(), 0);
    }
    if (同(命令, "盒") || 同(命令, "方块") || 同(命令, "立方体")) {
        if (参n > 1 && 参[1].是向量) p->大小 = 参[1].v;
        else if (参n > 1 && p->大小.x == 0.5f) p->大小 = 三一(参[1].f);
        图元 *q = 造图元(元_盒, p->位, 0, p->大小, 0);
        q->圆角 = p->圆角;
        return q;
    }
    if (同(命令, "圆柱")) {
        if (p->半径 < 0) p->半径 = (参n > 1) ? 参[1].f : 0.4f;
        if (p->高 < 0) p->高 = (参n > 2) ? 参[2].f : 0.6f;
        图元 *q = 造图元(元_圆柱, p->位, p->半径, 三零(), p->高);
        q->圆角 = p->圆角;
        return q;
    }
    if (同(命令, "圆环") || 同(命令, "甜甜圈")) {
        if (p->半径 < 0) p->半径 = (参n > 1) ? 参[1].f : 0.6f;
        if (p->管 < 0) p->管 = (参n > 2) ? 参[2].f : 0.18f;
        return 造图元(元_圆环, p->位, p->半径, 三零(), p->管);
    }
    if (同(命令, "胶囊")) {
        if (p->半径 < 0) p->半径 = (参n > 1) ? 参[1].f : 0.25f;
        if (p->高 < 0) p->高 = (参n > 2) ? 参[2].f : 0.5f;
        return 造图元(元_胶囊, p->位, p->半径, 三零(), p->高);
    }
    if (同(命令, "平面") || 同(命令, "地面")) {
        图元 *q = 造图元(元_平面, p->位, 0, 三零(), 0);
        q->轴 = 归(p->法线);
        return q;
    }
    return NULL;
}

static void 落形(场景 *s, 图元 *形, 参数 *p)
{
    if (!形) return;

    if (p->操作 && p->目标[0]) {
        物体 *o = 找物体(s, p->目标);
        if (!o) {
            fprintf(stderr, "警告：找不到物体 `%s`，这句被忽略\n", p->目标);
            return;
        }
        int 类型 = p->操作 == 1 ? 元_差 : (p->操作 == 2 ? 元_交 : (p->操作 == 3 ? 元_并 : 元_平滑并));
        o->形 = 合并(o->形, 形, 类型, p->平滑);
        return;
    }

    int 材 = 找材质(s, p->材质);
    if (材 < 0) {
        fprintf(stderr, "警告：没有材质 `%s`，改用白瓷\n", p->材质);
        材 = 找材质(s, "白瓷");
    }
    char 自动名[名长];
    if (!p->名字[0]) {
        snprintf(自动名, sizeof(自动名), "物%d", s->物数 + 1);
    } else {
        snprintf(自动名, sizeof(自动名), "%s", p->名字);
    }
    物体 *o = 加物体(s, 自动名, 材);
    o->形 = 形;
}

/* 一行 → 一条命令 */
static void 解析行(场景 *s, const char *行)
{
    int n = 切词(行);
    if (n == 0) return;
    char *命令 = 词[0];
    参数 p;
    值 参[8];
    参数清零(&p);

    if (同(命令, "尺寸") || 同(命令, "分辨率")) {
        if (n >= 3) { s->宽 = atoi(词[1]); s->高 = atoi(词[2]); }
        return;
    }
    if (同(命令, "采样") || 同(命令, "spp")) {
        if (n >= 2) s->采样 = atoi(词[1]);
        return;
    }
    if (同(命令, "曝光")) {
        if (n >= 2) s->曝光 = strtof(词[1], NULL);
        return;
    }
    if (同(命令, "泛光") || 同(命令, "bloom")) {
        if (n >= 2) s->泛光 = strtof(词[1], NULL);
        return;
    }
    if (同(命令, "暗角")) {
        if (n >= 2) s->暗角 = strtof(词[1], NULL);
        return;
    }
    if (同(命令, "颗粒") || 同(命令, "噪点")) {
        if (n >= 2) s->颗粒 = strtof(词[1], NULL);
        return;
    }
    if (同(命令, "输出")) {
        if (n >= 2) snprintf(s->输出, sizeof(s->输出), "%s", 词[1]);
        return;
    }
    if (同(命令, "导出") || 同(命令, "模型")) {
        s->导出网格 = 1;
        if (n >= 2) snprintf(s->输出, sizeof(s->输出), "%s", 词[1]);
        return;
    }
    if (同(命令, "天空") || 同(命令, "环境")) {
        int 数 = 解析参数(s, 词, n, 1, &p, 参);
        (void)数;
        /* 天空的键：天顶/地平/地面 走 位置-类键，这里复用 颜色 三个字段 */
        for (int i = 1; i < n; i++) {
            if ((同(词[i], "天顶") || 同(词[i], "顶")) && i + 1 < n) s->天顶色 = 读色(s, 词[i + 1]);
            else if ((同(词[i], "地平") || 同(词[i], "地平线")) && i + 1 < n) s->地平色 = 读色(s, 词[i + 1]);
            else if (同(词[i], "地面") && i + 1 < n) s->地面色 = 读色(s, 词[i + 1]);
        }
        s->环境强度 = p.强度 > 0 ? p.强度 : 2.2f;
        if (s->天顶色.x == 0 && s->天顶色.y == 0 && s->天顶色.z == 0) {
            s->天顶色 = 颜色线性(三造(0.30f, 0.52f, 0.88f));
            s->地平色 = 颜色线性(三造(0.86f, 0.91f, 0.97f));
            s->地面色 = 颜色线性(三造(0.30f, 0.30f, 0.30f));
        }
        return;
    }
    if (同(命令, "雾")) {
        for (int i = 1; i < n; i++) {
            if ((同(词[i], "密度") || 同(词[i], "浓度")) && i + 1 < n) s->雾密度 = strtof(词[i + 1], NULL);
            else if ((同(词[i], "颜色") || 同(词[i], "色")) && i + 1 < n) s->雾色 = 读色(s, 词[i + 1]);
        }
        return;
    }
    if (同(命令, "相机")) {
        int 参n = 解析参数(s, 词, n, 1, &p, 参);
        if (p.有位置) s->机.位置 = p.位;
        else if (参n > 0 && 参[0].是向量) s->机.位置 = 参[0].v;
        if (p.有看向) s->机.目标 = p.看向;
        else if (参n > 1 && 参[1].是向量) s->机.目标 = 参[1].v;
        s->相机已设 = 1;
        s->机.视场 = p.视场;
        s->机.光圈 = p.光圈;
        s->机.焦距 = p.焦距;
        s->机.上 = 三造(0, 1, 0);
        return;
    }
    if (同(命令, "材质")) {
        /* 材质 名字 颜色 (...) 粗糙 0.3 金属 0 ... */
        if (n < 2) return;
        char 名[24];
        snprintf(名, sizeof(名), "%s", 词[1]);
        参数 q;
        参数清零(&q);
        int 材参n = 解析参数(s, 词, n, 2, &q, 参);
        if (!q.有颜色 && 材参n > 0 && 参[0].是向量) {
            q.颜色 = 颜色线性(参[0].v);
            q.有颜色 = 1;
        }
        材质 m;
        memset(&m, 0, sizeof(m));
        snprintf(m.名, sizeof(m.名), "%s", 名);
        m.基色 = q.有颜色 ? q.颜色 : 颜色线性(三造(0.8f, 0.8f, 0.8f));
        m.纹理色 = m.基色;
        m.粗糙 = q.粗糙;
        m.金属 = q.金属;
        m.透射 = q.透射;
        m.折射率 = q.折射率 > 0 ? q.折射率 : 1.5f;
        m.纹理尺度 = q.尺度 > 0 ? q.尺度 : 1.0f;
        m.发光 = q.发光;
        if (同(q.纹理, "水波") || 同(q.纹理, "波纹")) m.纹理 = 纹_水波;
        else if (同(q.纹理, "棋盘")) m.纹理 = 纹_棋盘;
        else if (同(q.纹理, "木纹") || 同(q.纹理, "木")) m.纹理 = 纹_木纹;
        else if (同(q.纹理, "大理石")) m.纹理 = 纹_大理石;
        else if (同(q.纹理, "条纹") || 同(q.纹理, "布")) m.纹理 = 纹_条纹;
        加材质(s, m);
        return;
    }
    if (同(命令, "光") || 同(命令, "灯")) {
        if (n < 2) return;
        char *类 = 词[1];
        参数 q;
        参数清零(&q);
        int 参n = 解析参数(s, 词, n, 2, &q, 参);
        if (!q.有位置 && 参n > 0 && 参[0].是向量) {
            q.位 = 参[0].v;
            q.有位置 = 1;
        }
        if (!q.有大小 && 参n > 1 && 参[1].是向量) {
            q.大小 = 参[1].v;
            q.有大小 = 1;
        }
        if (s->光数 == s->光容) {
            s->光容 = s->光容 ? s->光容 * 2 : 8;
            s->光 = (光源 *)realloc(s->光, sizeof(光源) * (size_t)s->光容);
        }
        光源 L;
        memset(&L, 0, sizeof(L));
        L.色 = q.颜色.x == 0 && q.颜色.y == 0 && q.颜色.z == 0
                   ? 颜色线性(三造(1, 1, 1)) : q.颜色;
        L.强度 = q.强度 > 0 ? q.强度 : 1.0f;

        if (同(类, "太阳") || 同(类, "平行光")) {
            L.类型 = 光_太阳;
            L.朝向 = q.有方向 ? 归(q.方向) : 归(三造(-0.4f, -1.0f, -0.3f));
            L.半径 = q.角度 > 0 ? q.角度 : 2.0f;
        } else if (同(类, "球") || 同(类, "点光") || 同(类, "灯泡")) {
            L.类型 = 光_球;
            L.位置 = q.位;
            L.半径 = q.半径 > 0 ? q.半径 : 0.25f;
        } else {
            L.类型 = 光_面;
            L.位置 = q.位;
            L.宽 = q.有大小 ? 最大(q.大小.x, 0.01f) : (q.宽 > 0 ? q.宽 : 1.0f);
            L.高 = q.有大小 ? 最大(q.大小.y, 0.01f) : (q.高度 > 0 ? q.高度 : 1.0f);
            if (q.有看向) L.朝向 = 归(减(q.看向, q.位));
            else if (q.有方向) L.朝向 = 归(q.方向);
            else L.朝向 = 三造(0, -1, 0);
        }
        s->光[s->光数++] = L;
        return;
    }

    /* 剩下的都是几何 */
    int 参n = 解析参数(s, 词, n, 1, &p, 参);
    图元 *形 = 造形(s, 命令, &p, 参, 参n);
    if (!形) {
        fprintf(stderr, "警告：不认识 `%s`，这句被忽略\n", 命令);
        return;
    }
    落形(s, 形, &p);
}

/* --------------------------------------------------------------- 读文件 --
 */
static int 读场景(场景 *s, const char *路径)
{
    FILE *f = fopen(路径, "rb");
    if (!f) return 0;
    char 行[1024];
    while (fgets(行, sizeof(行), f)) 解析行(s, 行);
    fclose(f);
    return 1;
}

