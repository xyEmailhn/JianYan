#define 词最多 160
#define 词长 256

static char 词缓[词最多][词长];
static char *词[词最多];

static int 切词(const char *行)
{
    int n = 0;
    const char *p = 行;
    while (*p && n < 词最多 - 1) {
        while (*p == ' ' || *p == '\t' || *p == '\r' || *p == '\n' || *p == ',') p++;
        if (!*p) break;
        if (*p == '#' || (*p == '-' && p[1] == '-')) break;

        int k = 0;
        if (*p == '(') {
            词缓[n][k++] = *p++;
            while (*p && *p != ')' && k < 词长 - 2) 词缓[n][k++] = *p++;
            if (*p == ')') { 词缓[n][k++] = ')'; p++; }
        } else {
            while (*p && *p != ' ' && *p != '\t' && *p != '\r' && *p != '\n' &&
                   *p != ',' && *p != '#' && k < 词长 - 2)
                词缓[n][k++] = *p++;
        }
        词缓[n][k] = 0;
        词[n] = 词缓[n];
        n++;
    }
    return n;
}

static int 同(const char *a, const char *b) { return strcmp(a, b) == 0; }

/* ------------------------------------------------------------ 值解析 --
 */
static 三 读三(const char *s)
{
    if (s[0] == '(') {
        float v[3] = {0, 0, 0};
        int k = 0;
        const char *p = s + 1;
        while (*p && *p != ')' && k < 3) {
            v[k++] = strtof(p, (char **)&p);
            while (*p == ' ' || *p == ',') p++;
        }
        if (k == 1) return 三造(v[0], v[0], v[0]);
        return 三造(v[0], k > 1 ? v[1] : 0, k > 2 ? v[2] : 0);
    }
    float f = strtof(s, NULL);
    return 三造(f, f, f);
}

static 三 读色(场景 *s, const char *w)
{
    if (w[0] == '#') {
        char 十六[7] = {0};
        int n = 1;
        for (int i = 0; i < 6 && w[1 + i]; i++) 十六[i] = w[1 + i];
        (void)n;
        unsigned v = (unsigned)strtoul(十六, NULL, 16);
        return 颜色线性(三造(((v >> 16) & 255) / 255.0f, ((v >> 8) & 255) / 255.0f, (v & 255) / 255.0f));
    }
    if (w[0] == '(') return 颜色线性(读三(w));
    /* 名字：先找材质，它的基色就是这个名字的颜色 */
    int i = 找材质(s, w);
    if (i >= 0) return s->材[i].基色;
    int j = 找材质(s, "白瓷");
    if (j >= 0) return s->材[j].基色; /* 还没装预设时给个白的 */
    return 三一(0.8f);
}

