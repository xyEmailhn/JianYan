/* 颜色从 sRGB 转线性：用户在文件里写的 0.5 是"看起来中灰"，
   渲染器内部的 0.5 是"一半的光"。不转这一步，整张图会发灰发脏。 */
static float srgb转线性(float v)
{
    if (v <= 0.04045f) return v / 12.92f;
    return powf((v + 0.055f) / 1.055f, 2.4f);
}

static 三 颜色线性(三 c)
{
    return 三造(srgb转线性(c.x), srgb转线性(c.y), srgb转线性(c.z));
}

