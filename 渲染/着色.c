/* 直接光：对每个光源采样一个点，判可见，累加漫反射 + GGX 高光 */
static 三 直接光(场景 *s, 三 p, 三 n, 三 视, const 材质 *m, 三 固有色, 随机 *r)
{
    三 和 = 三零();
    float 糙 = 夹(m->粗糙, 0.02f, 1.0f);
    float a2 = 糙 * 糙 * 糙 * 糙; /* Disney: α = 粗糙², D 里用 α² */

    for (int i = 0; i < s->光数; i++) {
        光源 *L = &s->光[i];
        三 采样点, 灯法;
        float 距离, 面积 = 1.0f, cosL = 1.0f;

        if (L->类型 == 光_太阳) {
            三 方向 = 归(L->朝向);
            /* 角度 → 圆锥抖动，太阳也有软阴影 */
            float 张角 = 夹(L->半径, 0.05f, 20.0f) * 派 / 180.0f;
            三 u, v;
            正交基(方向, &u, &v);
            float rr = sqrtf(随机浮(r)) * tanf(张角);
            float aa = 随机浮(r) * 2.0f * 派;
            三 入 = 归(加(方向, 加(乘(u, cosf(aa) * rr), 乘(v, sinf(aa) * rr))));
            三 反 = 乘(入, -1.0f);
            float cosP = 点(n, 反);
            if (cosP <= 0.0f) continue;
            float 可 = 软阴影(s, 加(p, 乘(n, 0.002f)), 反, 60.0f);
            if (可 <= 0.0f) continue;

            三 辐 = 乘(L->色, L->强度);
            /* 太阳的漫反射：辐照度 × 固有色 × cos / π。漏掉固有色就会把整个场景刷成白模。 */
            和 = 加(和, 乘(逐乘(辐, 固有色),
                          可 * cosP * (1.0f - m->金属) * (1.0f - m->透射) / 派));
            /* 太阳的镜面高光 */
            三 h = 归(加(反, 乘(视, -1.0f)));
            float cosH = 最大(点(n, h), 0.0f);
            float D = a2 / (派 * (cosH * cosH * (a2 - 1.0f) + 1.0f) * (cosH * cosH * (a2 - 1.0f) + 1.0f) + 1e-7f);
            float cosV = 最大(点(n, 乘(视, -1.0f)), 0.0f);
            三 F0 = 混(三一(0.05f), m->基色, m->金属);
            三 F = 加(F0, 乘(减(三一(1.0f), F0), powf(1.0f - 最大(点(h, 乘(视, -1.0f)), 0.0f), 5.0f)));
            和 = 加(和, 乘(逐乘(辐, F), 可 * D * cosP / (4.0f * 最大(cosP * cosV, 0.02f))));
            continue;
        }

        if (!采样光源(L, r, &采样点, &灯法)) continue;
        三 差 = 减(采样点, p);
        距离 = 长(差);
        if (距离 < 1e-4f) continue;
        三 w = 乘(差, 1.0f / 距离);
        float cosP2 = 点(n, w);
        if (cosP2 <= 0.0f) continue;
        cosL = 最大(-点(w, 灯法), 0.0f);
        if (cosL <= 0.0f) continue;

        if (L->类型 == 光_面) 面积 = L->宽 * L->高;
        else 面积 = 4.0f * 派 * L->半径 * L->半径;

        float 几何 = cosP2 * cosL * 面积 / (距离 * 距离);
        float 可 = 软阴影(s, 加(p, 乘(n, 0.0025f)), w, 距离 - 0.02f);
        if (可 <= 0.0f) continue;

        三 辐 = 乘(L->色, L->强度);
        三 漫 = 乘(逐乘(辐, 固有色), 可 * 几何 * (1.0f - m->金属) * (1.0f - m->透射) / 派);
        和 = 加(和, 漫);

        /* 高光 */
        if (m->透射 < 0.99f) {
            三 h = 归(加(w, 乘(视, -1.0f)));
            float cosH = 最大(点(n, h), 0.0f);
            float 分母 = cosH * cosH * (a2 - 1.0f) + 1.0f;
            float D = a2 / (派 * 分母 * 分母 + 1e-7f);
            float cosV = 最大(点(n, 乘(视, -1.0f)), 0.0f);
            三 F0 = 混(三一(0.05f), m->基色, m->金属);
            三 F = 加(F0, 乘(减(三一(1.0f), F0),
                          powf(1.0f - 最大(点(h, 乘(视, -1.0f)), 0.0f), 5.0f)));
            三 高 = 乘(逐乘(辐, F), 可 * 几何 * D / (4.0f * 最大(cosP2 * cosV, 0.02f)));
            和 = 加(和, 高);
        }
    }
    return 和;
}

/* 主追踪：一条射线进来，一个颜色出去 */
static 三 追踪(场景 *s, 三 起, 三 向, 随机 *r, int 深)
{
    if (深 > 7) return 三零();

    float t;
    int 有 = 场景求交(s, 起, 向, &t, 160);

    /* 灯是发光几何，比场景更近时直接返回灯的亮度 */
    float 灯t = 无穷大;
    int 灯号 = -1;
    for (int i = 0; i < s->光数; i++) {
        if (s->光[i].类型 == 光_太阳) continue;
        float lt;
        if (灯求交(&s->光[i], 起, 向, &lt) && lt < 灯t) { 灯t = lt; 灯号 = i; }
    }
    if (灯号 >= 0 && 深 > 0 && (!有 || 灯t < t)) {
        /* 灯是发光几何，但它不该在画面里显形：
           主视线直接穿过灯，只有反射/折射里才看得见它。 */
        光源 *L = &s->光[灯号];
        return 乘(L->色, L->强度);
    }

    if (!有 || t > 300.0f) return 天空色(s, 向);

    三 p = 加(起, 乘(向, t));
    int 材号 = 找材质号(s, p);
    材质 *m = &s->材[材号];
    三 n = 场法线(s, p);
    int 在内 = 点(n, 向) > 0.0f;      /* 射线从物体内部打到表面 */
    if (在内) n = 乘(n, -1.0f);        /* 法线翻过来，永远对着来向 */
    if (m->纹理 == 纹_水波) n = 波纹法线(p, n, m->纹理尺度);

    三 固有色 = 材质色(m, p);
    三 视 = 向; /* 视线方向（从相机指向表面） */
    三 结果 = 三零();

    /* 自发光 */
    结果 = 加(结果, 乘(m->发光, 2.0f));

    /* 直接光 */
    结果 = 加(结果, 直接光(s, p, n, 视, m, 固有色, r));

    /* 环境漫反射：天空当一个大光源，AO 让缝隙变暗 */
    float ao = 遮蔽(s, p, n);
    三 天 = 天空色(s, n);
    三 漫反 = 乘(逐乘(天, 固有色), ao * (1.0f - m->金属) * (1.0f - m->透射) * 0.9f);
    结果 = 加(结果, 漫反);

    /* 镜面反射。
       粗糙度大于 0.5 的材质不再追射线：模糊反射的方差太大，
       16 个样本根本压不住，画面会变成"撒了盐"。改用天空近似，
       视觉上相差无几，噪点直接归零。 */
    if (m->金属 > 0.0f || m->透射 > 0.0f || m->粗糙 < 0.5f) {
        三 rd = 反射向(向, n);
        rd = 归(加(rd, 乘(随机方向(r), m->粗糙 * 0.75f)));
        if (点(rd, n) < 0.0f) rd = 反射向(向, n);
        三 反 = 追踪(s, 加(p, 乘(n, 0.0025f)), rd, r, 深 + 1);

        float cosV = 最大(点(n, 乘(视, -1.0f)), 0.0f);
        三 F0 = 混(三一(0.045f), 固有色, m->金属);
        三 F = 加(F0, 乘(减(三一(1.0f), F0), powf(1.0f - cosV, 5.0f)));
        /* 粗糙表面：微观朝向随机，掠射角的"全反射"被平均掉。
           不修这一步，地面在远处会变成一面镜子，看着像水面。 */
        F = 混(三一(0.045f), F, 1.0f - m->粗糙);
        if (m->金属 <= 0.0f && m->透射 <= 0.0f) F = 乘(F, 0.55f);
        结果 = 加(结果, 乘(逐乘(反, F), 1.0f - m->透射));
    } else {
        /* 便宜的替代：拿天空当环境反射，只在边缘留一点菲涅尔亮边 */
        float cosV = 最大(点(n, 乘(视, -1.0f)), 0.0f);
        float 菲 = 0.03f + 0.97f * powf(1.0f - cosV, 5.0f);
        结果 = 加(结果, 乘(天空色(s, 反射向(向, n)), 菲 * 0.55f * (1.0f - m->透射)));
    }

    /* 玻璃：Fresnel 选反射还是折射，颜色随厚度衰减 */
    if (m->透射 > 0.0f && 深 < 7) {
        /* 从空气进玻璃用 1/n，从玻璃出空气用 n。弄反了会全反射，玻璃球变成黑球。 */
        float 入射 = 在内 ? 最大(m->折射率, 1.0001f) : 1.0f / 最大(m->折射率, 1.0001f);
        float cosI = -最大(点(向, n), -1.0f);
        float sinI2 = 1.0f - cosI * cosI;
        float sinT2 = 入射 * 入射 * sinI2;
        float 菲涅 = 0.04f + 0.96f * powf(1.0f - 最大(cosI, 0.0f), 5.0f);

        if (sinT2 < 1.0f && 随机浮(r) > 菲涅) {
            float cosT = sqrtf(1.0f - sinT2);
            三 rd = 归(加(乘(向, 入射), 乘(n, 入射 * cosI - cosT)));
            三 内 = 追踪(s, 加(p, 乘(rd, 0.004f)), rd, r, 深 + 1);
            /* Beer-Lambert 吸收：厚处更绿更暗，玻璃才有"体感" */
            三 吸 = 三造(expf(-0.35f * 0.6f), expf(-0.35f * 0.9f), expf(-0.35f * 1.0f));
            结果 = 加(结果, 乘(逐乘(内, 吸), m->透射 * 0.9f));
        } else {
            三 rd = 反射向(向, n);
            三 反 = 追踪(s, 加(p, 乘(n, 0.003f)), rd, r, 深 + 1);
            结果 = 加(结果, 乘(反, m->透射));
        }
    }

    /* 雾：远处混进雾色，画面才有纵深 */
    if (s->雾密度 > 0.0f) {
        float 透 = expf(-s->雾密度 * t);
        结果 = 混(乘(s->雾色, s->环境强度), 结果, 透);
    }

    return 结果;
}

/* ------------------------------------------------------------ 多线程 --
 * 按行切块，一块一个线程。像素之间互不相干，所以不用锁，
 * 每个线程只写自己那条带，缓存也不打架。
 */
typedef struct {
    场景 *s;
    float *缓;     /* 线性 HDR 缓冲，3 float / 像素 */
    int 行起, 行止;
    uint64_t 种子;
} 渲染任务;

static void *渲染线程(void *参数)
{
    渲染任务 *任 = (渲染任务 *)参数;
    场景 *s = 任->s;
    随机 r;
    随机播种(&r, 任->种子);
    int spp = 最大(s->采样, 1);
    float 缩 = 1.0f / (float)spp;

    for (int y = 任->行起; y < 任->行止; y++) {
        for (int x = 0; x < s->宽; x++) {
            三 和 = 三零();
            for (int k = 0; k < spp; k++) {
                三 向 = 相机射线(&s->机, (float)x, (float)y, s->宽, s->高, &r);
                三 起 = s->机.位置;
                和 = 加(和, 追踪(s, 起, 向, &r, 0));
            }
            size_t 位 = ((size_t)y * (size_t)s->宽 + (size_t)x) * 3;
            任->缓[位 + 0] = 和.x * 缩;
            任->缓[位 + 1] = 和.y * 缩;
            任->缓[位 + 2] = 和.z * 缩;
        }
    }
    return NULL;
}

static void 渲染(场景 *s, float *缓)
{
    int 线程数 = 8;
    const char *环 = getenv("简渲线程");
    if (环) 线程数 = atoi(环);
    if (线程数 <= 0) {
#ifdef _SC_NPROCESSORS_ONLN
        线程数 = (int)sysconf(_SC_NPROCESSORS_ONLN);
#else
        线程数 = 8;
#endif
    }
    if (线程数 > s->高) 线程数 = s->高;
    线程数 = 最大(线程数, 1);
    /* 小块更好做负载均衡：图元分布不均时，大块会让某些线程早收工 */
    int 块 = 最大(1, s->高 / (线程数 * 4));

    pthread_t 线[256];
    渲染任务 任[256];
    int 已发 = 0, 行 = 0;

    while (行 < s->高) {
        while (已发 < 线程数 && 行 < s->高) {
            渲染任务 *t = &任[已发];
            t->s = s;
            t->缓 = 缓;
            t->行起 = 行;
            t->行止 = 最小(行 + 块, s->高);
            t->种子 = 0x9E3779B97F4A7C15ULL * (uint64_t)(已发 + 1) + 12345u;
            行 = t->行止;
            if (pthread_create(&线[已发], NULL, 渲染线程, t) != 0) {
                渲染线程(t); /* 起不了线程就自己干，别崩 */
            } else {
                已发++;
            }
        }
        /* 等一轮做完再发下一轮（简单，且块小，等的时间很短） */
        for (int i = 0; i < 已发; i++) pthread_join(线[i], NULL);
        已发 = 0;
    }
}

