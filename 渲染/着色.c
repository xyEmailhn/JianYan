/* 半分辨率高斯模糊，bloom 用。分离两趟，O(n) 而不 O(n²)。 */
static void 模糊(float *图, int 宽, int 高, float 半径)
{
    int 核 = (int)(半径 * 3.0f) | 1;
    float *权 = (float *)取内存(sizeof(float) * (size_t)核);
    float 总 = 0.0f;
    for (int i = 0; i < 核; i++) {
        float d = (float)(i - 核 / 2) / 半径;
        权[i] = expf(-0.5f * d * d);
        总 += 权[i];
    }
    for (int i = 0; i < 核; i++) 权[i] /= 总;

    float *临 = (float *)取内存(sizeof(float) * (size_t)宽 * (size_t)高 * 3);
    for (int y = 0; y < 高; y++) {
        for (int x = 0; x < 宽; x++) {
            float 和[3] = {0, 0, 0};
            for (int i = 0; i < 核; i++) {
                int xx = x + i - 核 / 2;
                if (xx < 0) xx = 0;
                if (xx >= 宽) xx = 宽 - 1;
                size_t 位 = ((size_t)y * (size_t)宽 + (size_t)xx) * 3;
                和[0] += 图[位] * 权[i];
                和[1] += 图[位 + 1] * 权[i];
                和[2] += 图[位 + 2] * 权[i];
            }
            size_t 位 = ((size_t)y * (size_t)宽 + (size_t)x) * 3;
            临[位] = 和[0]; 临[位 + 1] = 和[1]; 临[位 + 2] = 和[2];
        }
    }
    for (int y = 0; y < 高; y++) {
        for (int x = 0; x < 宽; x++) {
            float 和[3] = {0, 0, 0};
            for (int i = 0; i < 核; i++) {
                int yy = y + i - 核 / 2;
                if (yy < 0) yy = 0;
                if (yy >= 高) yy = 高 - 1;
                size_t 位 = ((size_t)yy * (size_t)宽 + (size_t)x) * 3;
                和[0] += 临[位] * 权[i];
                和[1] += 临[位 + 1] * 权[i];
                和[2] += 临[位 + 2] * 权[i];
            }
            size_t 位 = ((size_t)y * (size_t)宽 + (size_t)x) * 3;
            图[位] = 和[0]; 图[位 + 1] = 和[1]; 图[位 + 2] = 和[2];
        }
    }
    free(临);
    free(权);
}

/* HDR → 8 位：先 bloom，再曝光，再 ACES，再 sRGB，最后暗角与颗粒。
   顺序不能换：在色调映射之后做 bloom，光会变成一坨白饼。 */
static unsigned char *成像(场景 *s, float *缓)
{
    int 宽 = s->宽, 高 = s->高;
    size_t 总数 = (size_t)宽 * (size_t)高;

    if (s->泛光 > 0.0f) {
        /* 只提亮部，1/4 分辨率模糊，再叠回去 */
        int 小宽 = 最大(宽 / 4, 1), 小高 = 最大(高 / 4, 1);
        float *亮 = (float *)取内存(sizeof(float) * (size_t)小宽 * (size_t)小高 * 3);
        for (int y = 0; y < 小高; y++) {
            for (int x = 0; x < 小宽; x++) {
                float 和[3] = {0, 0, 0};
                int cnt = 0;
                for (int dy = 0; dy < 4; dy++) {
                    for (int dx = 0; dx < 4; dx++) {
                        int sx = x * 4 + dx, sy = y * 4 + dy;
                        if (sx >= 宽 || sy >= 高) continue;
                        size_t 位 = ((size_t)sy * (size_t)宽 + (size_t)sx) * 3;
                        float 阈 = 亮度(三造(缓[位], 缓[位 + 1], 缓[位 + 2]));
                        float k = 阈 > 1.0f ? (阈 - 1.0f) / 阈 : 0.0f;
                        和[0] += 缓[位] * k;
                        和[1] += 缓[位 + 1] * k;
                        和[2] += 缓[位 + 2] * k;
                        cnt++;
                    }
                }
                size_t 位 = ((size_t)y * (size_t)小宽 + (size_t)x) * 3;
                亮[位] = cnt ? 和[0] / cnt : 0;
                亮[位 + 1] = cnt ? 和[1] / cnt : 0;
                亮[位 + 2] = cnt ? 和[2] / cnt : 0;
            }
        }
        模糊(亮, 小宽, 小高, 6.0f);
        模糊(亮, 小宽, 小高, 14.0f);

        for (int y = 0; y < 高; y++) {
            for (int x = 0; x < 宽; x++) {
                int sx = 最小(x * 小宽 / 宽, 小宽 - 1);
                int sy = 最小(y * 小高 / 高, 小高 - 1);
                size_t a = ((size_t)y * (size_t)宽 + (size_t)x) * 3;
                size_t b = ((size_t)sy * (size_t)小宽 + (size_t)sx) * 3;
                缓[a] += 亮[b] * s->泛光;
                缓[a + 1] += 亮[b + 1] * s->泛光;
                缓[a + 2] += 亮[b + 2] * s->泛光;
            }
        }
        free(亮);
    }

    unsigned char *出 = (unsigned char *)取内存(总数 * 3);
    for (int y = 0; y < 高; y++) {
        for (int x = 0; x < 宽; x++) {
            size_t 位 = ((size_t)y * (size_t)宽 + (size_t)x) * 3;
            三 c = 三造(缓[位], 缓[位 + 1], 缓[位 + 2]);
            c = 乘(c, s->曝光);

            if (s->暗角 > 0.0f) {
                float dx = (float)x / (float)宽 - 0.5f;
                float dy = (float)y / (float)高 - 0.5f;
                float d = sqrtf(dx * dx + dy * dy) * 1.41421f;
                c = 乘(c, 1.0f - s->暗角 * d * d);
            }

            c = ACES(c);
            c = 伽马前(c);

            if (s->颗粒 > 0.0f) {
                /* 确定性哈希噪声：同一个坐标两次渲染结果一致 */
                uint32_t h = (uint32_t)x * 374761393u + (uint32_t)y * 668265263u;
                h = (h ^ (h >> 13)) * 1274126177u;
                float 噪 = ((float)((h ^ (h >> 16)) & 1023) / 1023.0f - 0.5f) * s->颗粒;
                c = 加(c, 三一(噪));
            }

            出[位] = (unsigned char)(夹(c.x, 0.0f, 1.0f) * 255.0f + 0.5f);
            出[位 + 1] = (unsigned char)(夹(c.y, 0.0f, 1.0f) * 255.0f + 0.5f);
            出[位 + 2] = (unsigned char)(夹(c.z, 0.0f, 1.0f) * 255.0f + 0.5f);
        }
    }
    return 出;
}

