/* ---------------------------------------------------------------- 工具 --
 */
static inline float 亮度(三 c) { return 0.2126f * c.x + 0.7152f * c.y + 0.0722f * c.z; }

static inline 三 伽马前(三 c)
{
    return 三造(c.x <= 0 ? 0 : (c.x <= 0.0031308f ? c.x * 12.92f : 1.055f * powf(c.x, 1.0f / 2.4f) - 0.055f),
                c.y <= 0 ? 0 : (c.y <= 0.0031308f ? c.y * 12.92f : 1.055f * powf(c.y, 1.0f / 2.4f) - 0.055f),
                c.z <= 0 ? 0 : (c.z <= 0.0031308f ? c.z * 12.92f : 1.055f * powf(c.z, 1.0f / 2.4f) - 0.055f));
}

/* ACES 胶片曲线：高光滚降不突兀，颜色不会一过曝就发白 */
static inline 三 ACES(三 x)
{
    const float a = 2.51f, b = 0.03f, c = 2.43f, d = 0.59f, e = 0.14f;
    x.x = 夹((x.x * (a * x.x + b)) / (x.x * (c * x.x + d) + e), 0.0f, 1.0f);
    x.y = 夹((x.y * (a * x.y + b)) / (x.y * (c * x.y + d) + e), 0.0f, 1.0f);
    x.z = 夹((x.z * (a * x.z + b)) / (x.z * (c * x.z + d) + e), 0.0f, 1.0f);
    return x;
}

/* ------------------------------------------------------------ 材质取样 --
 * 程序化纹理：不加载贴图也能有细节。棋盘给"参考板"，
 * 木纹给桌面，大理石给雕塑，条纹给织物。
 */
static 三 材质色(const 材质 *m, 三 p)
{
    if (m->纹理 == 纹_无 || m->纹理 == 纹_水波) return m->基色;
    float k = m->纹理尺度 > 0 ? m->纹理尺度 : 1.0f;
    float t = 0.0f;

    if (m->纹理 == 纹_棋盘) {
        int a = (int)floorf(p.x * k), b = (int)floorf(p.z * k);
        t = ((a + b) & 1) ? 1.0f : 0.0f;
    } else if (m->纹理 == 纹_木纹) {
        /* 沿 x 方向的年轮纹 + 分形噪声，看起来像木地板而不是水波 */
        float n = 分形噪声(三造(p.x * 0.35f, p.y * 2.0f, p.z * 1.6f));
        float 纹 = sinf(p.x * 3.6f * k + n * 5.5f + sinf(p.z * 1.2f + p.x * 0.4f) * 1.1f);
        t = 0.28f + 0.72f * (0.5f + 0.5f * 纹);
        t = t * t;
    } else if (m->纹理 == 纹_大理石) {
        float n = 分形噪声(乘(p, 0.9f * k));
        t = 0.5f + 0.5f * sinf((p.x + p.y * 0.4f) * 4.0f + n * 7.0f);
        t = powf(fabsf(t), 0.5f);
    } else if (m->纹理 == 纹_条纹) {
        t = 0.5f + 0.5f * sinf(p.y * 40.0f * k);
        t = t > 0.5f ? 1.0f : 0.0f;
    }
    return 混(m->基色, m->纹理色, 夹(t, 0.0f, 1.0f));
}

/* 水面波纹：用噪声梯度扰动法线。反射方向一变，倒影就碎成一片粼光。
   没有这一步，水面就是一块蓝玻璃。 */
static 三 波纹法线(三 p, 三 n, float 强度)
{
    float e = 0.012f;
    float h0 = 分形噪声(乘(p, 11.0f));
    float hx = 分形噪声(乘(加(p, 三造(e, 0, 0)), 11.0f));
    float hz = 分形噪声(乘(加(p, 三造(0, 0, e)), 11.0f));
    三 斜 = 三造((hx - h0) / e * 强度, 0.0f, (hz - h0) / e * 强度);
    return 归(加(n, 斜));
}

/* 灯也是几何：反射线打到灯，要看见灯的亮度。
   没有这一步，金属球里只有天空，没有高光。 */
static int 灯求交(const 光源 *L, 三 起, 三 向, float *出t)
{
    if (L->类型 == 光_面) {
        三 n = 归(L->朝向);
        float 分母 = 点(向, n);
        if (fabsf(分母) < 1e-7f) return 0;
        float t = 点(减(L->位置, 起), n) / 分母;
        if (t <= 0.002f) return 0;
        三 p = 加(起, 乘(向, t));
        三 d = 减(p, L->位置);
        三 u, v;
        正交基(n, &u, &v);
        if (fabsf(点(d, u)) <= L->宽 * 0.5f && fabsf(点(d, v)) <= L->高 * 0.5f) {
            *出t = t;
            return 1;
        }
        return 0;
    }
    if (L->类型 == 光_球) {
        三 oc = 减(起, L->位置);
        float b = 点(oc, 向);
        float c = 点(oc, oc) - L->半径 * L->半径;
        float 判 = b * b - c;
        if (判 < 0) return 0;
        float t = -b - sqrtf(判);
        if (t <= 0.002f) return 0;
        *出t = t;
        return 1;
    }
    return 0;
}

