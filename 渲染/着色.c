/* ============================================================================
 *  简渲 · 着色（着色.c）
 *  ----------------------------------------------------------------------------
 *  一条射线打到表面之后，要回答两个问题：
 *      1. 这个点被谁照亮？（直接光 + 环境 + 反射 + 折射）
 *      2. 它自己发什么光？（自发光、材质固有颜色）
 *
 *  这里用的是「Whitted 光线追踪 + 距离场软阴影 + 环境光遮蔽」：
 *    - 直接光：每个光源采样一次，阴影用 SDF 估半影 → 软阴影免费；
 *    - 环境光：天空渐变 × AO，缝隙自然变暗 → 落地感；
 *    - 镜面：递归一条反射线，粗糙度用来抖方向 → 磨砂金属；
 *    - 玻璃：Fresnel 决定反射还是折射，递归；
 *    - 面光本身就是几何，所以金属球里能看见柔光箱的形状。
 *
 *  没有做全局光照的多次弹射——那要路径追踪，噪声大、收敛慢。
 *  产品图要的是"干净"，不是"物理全对"，这笔账很划算。
 * ========================================================================== */

