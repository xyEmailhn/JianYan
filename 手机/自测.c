/* ============================================================================
 *  自测.c —— 在桌面上验证手机壳的执行链路
 *  ----------------------------------------------------------------------------
 *  手机上跑不了自动化测试（没有模拟器），所以把「写临时文件 → fork → 读管道
 *  → 收尾」这整条链路搬到桌面上跑。JNI 那层只剩下把 jstring 转成 char*，
 *  薄到不值得单独测。
 *
 *  重点验四件事：
 *    1. 正常程序的输出原样回来；
 *    2. 编译期诊断也能回来（诊断走 stderr，得和 stdout 合流）；
 *    3. 死循环被步数闸拦下，不是永远不返回；
 *    4. 子进程段错误时父进程安然无恙，并给出「异常终止」。
 * ========================================================================== */

#define 手机_无JNI 1
#include "jni.c"

static int 通过 = 0, 失败 = 0;

static void 验(const char *名, const char *代码, const char *应含, int 不该崩)
{
    char *出 = 简言_执行(代码, "/tmp/简言自测");
    int 好 = 出 && strstr(出, 应含) != NULL;
    if (不该崩 && 出 && strstr(出, "异常终止")) 好 = 0;
    if (好) { 通过++; printf("  ✓ %s\n", 名); }
    else {
        失败++;
        printf("  ✗ %s\n    期望含：%s\n    实际：%.400s\n", 名, 应含, 出 ? 出 : "(空)");
    }
    free(出);
}

int main(void)
{
    if (system("rm -rf /tmp/简言自测 && mkdir -p /tmp/简言自测") != 0) return 3;

    printf("手机执行链路自测\n");

    验("你好",
       "模块 试.你好\n函数 主() -> 整数 {\n    打印行(\"你好，简言\")\n    返回 0\n}\n",
       "你好，简言", 1);

    验("算术与循环",
       "模块 试.算\n函数 主() -> 整数 {\n"
       "    私有 整数 和 = 0\n"
       "    对 i: 1~10 { 和 = 和 + i }\n"
       "    打印行(和)\n    返回 0\n}\n",
       "55", 1);

    验("递归",
       "模块 试.递\n函数 斐(n: 整数) -> 整数 {\n"
       "    如果 n << 2 就 { 返回 n }\n"
       "    返回 斐(n-1) + 斐(n-2)\n}\n"
       "函数 主() -> 整数 { 打印行(斐(12)) 返回 0 }\n",
       "144", 1);

    验("编译期诊断",
       "模块 试.错\n函数 主() -> 整数 {\n    打印行(未定义的名字)\n    返回 0\n}\n",
       "找不到", 1);

    验("除零不崩",
       "模块 试.零\n函数 主() -> 整数 {\n"
       "    私有 整数 a = 7\n    私有 整数 b = 0\n"
       "    打印行(a // b)\n    返回 0\n}\n",
       "0", 1);

    /* 死循环：必须被步数闸拦下，且要说人话 */
    验("死循环有闸",
       "模块 试.死\n函数 主() -> 整数 {\n"
       "    私有 整数 i = 0\n    当 1 == 1 { i = i + 1 }\n    返回 0\n}\n",
       "运行太久", 1);

    /* 真崩一个：无限递归把子进程的栈打穿。父进程必须活着，还能说清楚。
        * 这条以前用了一个正常的程序，等于什么都没验。 */
    {
        char *出 = 简言_执行(
            "模块 试.崩\n函数 深(n: 整数) -> 整数 { 返回 深(n + 1) }\n"
            "函数 主() -> 整数 { 打印行(深(0)) 返回 0 }\n", "/tmp/简言自测");
        int 好 = 出 && strstr(出, "异常终止");
        if (好) { 通过++; printf("  ✓ 崩溃隔离（子进程被杀，父进程活着）\n"); }
        else { 失败++; printf("  ✗ 崩溃隔离：%.300s\n", 出 ? 出 : "(空)"); }
        free(出);
    }

    printf("\n通过 %d，失败 %d\n", 通过, 失败);
    return 失败 ? 1 : 0;
}
