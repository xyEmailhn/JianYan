def 是汉字(c):
    """这个字是汉字吗？认三个区间，覆盖日常所有汉字，但不会把全角标点算进来。"""
    o = ord(c)
    return (0x4E00 <= o <= 0x9FFF) or (0x3400 <= o <= 0x4DBF) or (0xF900 <= o <= 0xFAFF)


def 是名字的开头(c):
    """能不能当一个名字的第一个字？字母、下划线、汉字都行。"""
    return c.isascii() and (c.isalpha() or c == "_") or 是汉字(c)


def 是名字的一部分(c):
    """名字后面的字：多一个数字也可以。"""
    return (c.isascii() and (c.isalnum() or c == "_")) or 是汉字(c)


