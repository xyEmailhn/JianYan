# 四、扫描器
# ============================================================================

class 扫描器:
    def __init__(self, 源):
        self.源 = 源
        self.位置 = 0
        self.行 = 1
        self.列 = 1
        self.词们 = []
        self.错误数 = 0
        self.计数 = [0] * 9

    # ---------- 基础动作 ----------

    def 看(self, 偏移=0):
        """看当前位置往后第几个字，越界返回空字符串（这样就不用到处判断边界）"""
        位置 = self.位置 + 偏移
        return self.源[位置] if 位置 < len(self.源) else ""

    def 走(self, 几个=1):
        """往前走几个字，顺便维护行列号"""
        for _ in range(几个):
            if self.位置 >= len(self.源):
                return
            if self.源[self.位置] == "\n":
                self.行 += 1
                self.列 = 1
            else:
                self.列 += 1
            self.位置 += 1

    def 记(self, 种类, 起点位置, 起行, 起列, 类别=None):
        self.计数[种类] += 1
        self.词们.append({
            "种类": 种类,
            "文字": self.源[起点位置:self.位置],
            "行": 起行,
            "列": 起列,
            "类别": 类别,
        })

    def 报错(self, 起行, 起列, 原因):
        self.错误数 += 1
        self.计数[错] += 1
        print(f"词法错误 {起行}:{起列}  {原因}", file=sys.stderr)

    # ---------- 跳过空白与注释 ----------

    def 跳过注释(self):
        """当前位置是 "--" 吗？是的话整段跳过去，返回 True"""
        if self.看() != "-" or self.看(1) != "-":
            return False

        if self.看(2) == "[" and self.看(3) == "[":
            # 块注释 --[[ ... ]]
            self.走(4)
            while self.位置 < len(self.源):
                if self.看() == "]" and self.看(1) == "]":
                    self.走(2)
                    return True
                self.走()
            print(f"词法错误 {self.行}:{self.列}  块注释没有收尾的 ]]", file=sys.stderr)
            return True

        # 行注释：吃到换行为止（换行留给外面处理，它是正式的词）
        while self.位置 < len(self.源) and self.看() != "\n":
            self.走()
        return True

    # ---------- 读各种词 ----------

    def 读名字(self):
        """字母、下划线、汉字开头，一直吃到不能再吃为止"""
        起行, 起列, 起点 = self.行, self.列, self.位置
        while self.位置 < len(self.源) and 是名字的一部分(self.看()):
            self.走()

        文字 = self.源[起点:self.位置]
        if 文字 in 关键字:
            self.记(关, 起点, 起行, 起列, 关键字[文字])
        else:
            self.记(标, 起点, 起行, 起列)

    def 读数字(self):
        """三种写法：123 / 0xFF / 3.14e-3"""
        起行, 起列, 起点 = self.行, self.列, self.位置
        是浮点 = False

        if self.看() == "0" and self.看(1) in ("x", "X"):
            self.走(2)
            while self.看() and (self.看() in "0123456789abcdefABCDEF_"):
                self.走()
            self.记(数, 起点, 起行, 起列)
            return

        if self.看() == "0" and self.看(1) in ("b", "B"):
            self.走(2)
            while self.看() in ("0", "1", "_") and self.看():
                self.走()
            self.记(数, 起点, 起行, 起列)
            return

        while self.看() and (self.看().isdigit() or self.看() == "_"):
            self.走()

        # 小数点：点后面必须还是数字，而且不能是 ".."（那是拼接运算符）
        if self.看() == "." and self.看(1).isdigit():
            是浮点 = True
            self.走()
            while self.看() and (self.看().isdigit() or self.看() == "_"):
                self.走()

        # 科学计数法
        if self.看() in ("e", "E") and self.看():
            后面 = self.看(1)
            if 后面.isdigit() or (后面 in ("+", "-") and self.看(2).isdigit()):
                是浮点 = True
                self.走()
                if self.看() in ("+", "-"):
                    self.走()
                while self.看() and self.看().isdigit():
                    self.走()

        self.记(浮 if 是浮点 else 数, 起点, 起行, 起列)

    def 读字符串(self):
        起行, 起列, 起点 = self.行, self.列, self.位置

        # 长字符串 [[ ... ]]
        if self.看() == "[" and self.看(1) == "[":
            self.走(2)
            while self.位置 < len(self.源):
                if self.看() == "]" and self.看(1) == "]":
                    self.走(2)
                    self.记(串, 起点, 起行, 起列)
                    return
                self.走()
            self.报错(起行, 起列, "长字符串没有收尾的 ]]")
            self.记(错, 起点, 起行, 起列)
            return

        # 普通字符串 "..."
        self.走()
        while self.位置 < len(self.源):
            c = self.看()
            if c == '"':
                self.走()
                self.记(串, 起点, 起行, 起列)
                return
            if c == "\n":
                self.报错(起行, 起列, "字符串写到一半换行了，少了右边的引号")
                self.记(错, 起点, 起行, 起列)
                return
            if c == "\\":
                self.走(2)      # 反斜杠和它后面那个字一起跳过
                continue
            self.走()
        self.报错(起行, 起列, "字符串没有收尾的引号")
        self.记(错, 起点, 起行, 起列)

    def 读符号(self):
        """最长匹配：先试三个字符，不行试两个，再不行就是一个"""
        起行, 起列, 起点 = self.行, self.列, self.位置
        三字 = self.看() + self.看(1) + self.看(2)
        两字 = self.看() + self.看(1)

        if 三字 in ("<<<", ">>>"):
            长 = 3
        elif 两字 in ("<<", ">>", "<=", ">=", "==", "!=", "^^", "~~", "//", "->", ".."):
            长 = 2
        else:
            长 = 1

        self.走(长)
        self.记(符, 起点, 起行, 起列)

    # ---------- 主循环 ----------

    def 跑(self):
        while self.位置 < len(self.源):
            c = self.看()

            if c in " \t\r":
                self.走()
                continue

            if self.跳过注释():
                continue

            if c == "\n":
                起行, 起列, 起点 = self.行, self.列, self.位置
                self.走()
                self.记(换, 起点, 起行, 起列)
                continue

            if c == '"' or (c == "[" and self.看(1) == "["):
                self.读字符串()
                continue

            if c.isdigit():
                self.读数字()
                continue

            if 是名字的开头(c):
                self.读名字()
                continue

            if c.isascii() and c.isprintable():
                self.读符号()
                continue

            # 到这儿说明是认不出来的字了
            起行, 起列, 起点 = self.行, self.列, self.位置
            错误对照 = {"，": ",", "。": ".", "；": ";", "：": ":", "（": "(", "）": ")",
                        "【": "[", "】": "]", "“": '"', "”": '"', "＝": "=", "＋": "+", "＆": "&", "｜": "|", "％": "%", "＃": "#",
                        "～": "~", "＠": "@", "＄": "$"}
            提示 = 错误对照.get(c)
            self.走()
            self.报错(起行, 起列,
                     f"这里用了全角符号，简言只认半角，应该写 {提示}" if 提示
                     else "不认识的字符（简言只用半角符号和汉字）")
            self.记(错, 起点, 起行, 起列)

        self.计数[终] += 1
        self.词们.append({"种类": 终, "文字": "", "行": self.行, "列": self.列, "类别": None})
        return self.词们


# ============================================================================
# 五、命令行
# ============================================================================

def 主函数():
    if len(sys.argv) < 2:
        print("用法：python3 lexer_参考实现.py 文件.简 [-统计]", file=sys.stderr)
        return 2

    路径 = sys.argv[1]
    统计 = "-统计" in sys.argv

    with open(路径, "rb") as f:
        源 = f.read().decode("utf-8")
    if 源.startswith("\ufeff"):
        源 = 源[1:]

    扫描 = 扫描器(源)
    词们 = 扫描.跑()

    if 统计:
        print(f"文件       {路径}")
        print(f"字符数     {len(源)}")
        合计 = 0
        for i in range(1, 9):
            if 扫描.计数[i]:
                print(f"{名称[i]:　<8} {扫描.计数[i]:>8}")
                合计 += 扫描.计数[i]
        print(f"{'合计':　<8} {合计:>8}")
        return 1 if 扫描.错误数 else 0

    for t in 词们:
        文字 = "\\n" if t["种类"] == 换 else t["文字"]
        尾巴 = f"    （{t['类别']}）" if t["种类"] == 关 else ""
        print(f"{t['行']:4d}:{t['列']:3d}  {标签[t['种类']]}  {文字}{尾巴}")

    print(f"\n共 {len(词们)} 个词，{扫描.错误数} 个错误", file=sys.stderr)
    return 1 if 扫描.错误数 else 0


if __name__ == "__main__":
    sys.exit(主函数())
