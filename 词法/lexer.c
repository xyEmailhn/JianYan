/* ============================================================================
 *  简言 · 词法分析器
 *  ----------------------------------------------------------------------------
 *  它的工作只有一件：把一段源码（一串字符）切成一个个"词"，并给每个词贴上标签。
 *
 *      源码:   整数 甲 = 1 + 2
 *      切完:   [整数] [甲] [=] [1] [+] [2] [换行]
 *              关键字  标识符 符号 整数 符号 整数 换行
 *
 *  后面的语法分析器只看这些标签，不再看原始字符。所以词法分析是编译的第一步。
 *
 *  ----------------------------------------------------------------------------
 *  这份代码为什么快（"接近 C"其实它本身就是 C，这里说的是接近手写汇编的极限）：
 *    1. 只扫一遍。每个字符最多看一两次，看完就往前走，绝不回头。
 *    2. 不复制字符串。词只记住"在原文里的起点和长度"，一个字节都不搬。
 *    3. 不申请内存。除了开头一次性读完文件，跑起来 malloc 次数为 0。
 *    4. 查关键字用哈希表。60 多个关键字，一次哈希 + 一次比较就命中，O(1)。
 *    5. 中文按 3 字节整块跳过，不逐字节解码。
 *
 *  这份代码为什么"看得懂"：
 *    - 每个函数上面都写了它在干什么、为什么这么干。
 *    - 没有宏魔法，没有位运算技巧，没有 goto，没有函数指针。
 *    - 变量名是有意义的英文单词（kind / start / len），注释是中文。
 *
 *  ----------------------------------------------------------------------------
 *  编译（追求最小体积 + 最快速度，产物不需要可逆，所以放心 strip、放心内联）：
 *      gcc -O3 -flto -fno-plt -fno-asynchronous-unwind-tables \
 *          -fno-unwind-tables -fno-ident -s -static -o 简词法 lexer.c
 * ========================================================================== */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
