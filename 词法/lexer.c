/* ============================================================================
 *  第一部分：词的种类
 *  ----------------------------------------------------------------------------
 *  每种词给一个编号。C 的 enum 就是"给整数起名字"，写 词_关键字 比写 3 好读。
 * ========================================================================== */

typedef enum {
    词_文件结束,   /* 读到文件末尾了，给语法分析器一个明确的收尾信号 */
    词_换行,       /* 简言不用分号，换行就是语句的结束符，所以它是个正式的词 */
    词_标识符,     /* 名字：变量名、函数名，可以是英文、数字、下划线、汉字 */
    词_关键字,     /* 语言自己保留的字：函数、如果、返回…… 不能拿来当名字 */
    词_整数,       /* 123、1_000、0xFF、0b1010 */
    词_浮点,       /* 3.14、1e9、2.5e-3 */
    词_字符串,     /* "你好" 或者 [[ 跨行原样文本 ]] */
    词_符号,       /* ( ) { } + - * / 这些标点 */
    词_错误        /* 认不出来的字，比如全角逗号 "，" */
} 词种类;

/* 打印时用的单字标签，一个汉字占两格，对齐好看 */
static const char *种类标签[] = { "终", "换", "标", "关", "数", "浮", "串", "符", "错" };

/* 关键字表里的一行 */
typedef struct 关键字 {
    const char *文字;   /* 这个关键字长什么样，比如 "如果" */
    int 长度;           /* 占几个字节，中文一个字 3 字节 */
    const char *类别;   /* 只用来给人看：它属于哪一类 */
} 关键字;

/* 一个"词"的全部信息 */
typedef struct {
    词种类 种类;              /* 它是哪一类 */
    const char *起点;         /* 指向源文件缓冲区里的某个位置（不复制文字！） */
    int 长度;                 /* 从起点往后数几个字节是这个词 */
    int 行, 列;               /* 位置，报错时告诉用户"第几行第几列" */
    const 关键字 *关;         /* 如果它是关键字，指向表里那一行；否则是 NULL */
} 词;

/* 词法分析器的全部状态。你可以把它想成一台扫地机器人：src 是房间，pos 是它现在的位置 */
typedef struct {
    const char *src;   /* 整份源码，一次性读进内存 */
    int 长度;          /* 源码有多少字节 */
    int pos;           /* 现在扫到第几个字节 */
    int 行;            /* 现在第几行 */
    int 列;            /* 现在第几列（按"字"算，一个汉字算一列，不是按字节） */
    int 错误数;        /* 出了几次错 */
    long 计数[9];      /* 每类词各出现多少次，最后统计用 */
} 扫描器;


