static const int 关键字数量 = (int)(sizeof(关键字表) / sizeof(关键字表[0]));

/* ---- 哈希表：把关键字摊到 256 个格子里，查的时候算一下位置就直接跳过去 ----
 *
 *  为什么用 256？关键字 70 个左右，256 个格子装得下，冲突少。
 *  g_格子[i] 存的是"关键字表里的下标 + 1"，0 表示这个格子是空的。
 *  加 1 是为了让"空"和"第 0 个"能区分开。
 */
#define 格子数 256
static int g_格子[格子数];

/* FNV-1a 哈希：业界最常用的小字符串哈希，几行代码，散得很均匀 */
static uint32_t 算哈希(const char *s, int n)
{
    uint32_t h = 2166136261u;
    for (int i = 0; i < n; i++) {
        h ^= (unsigned char)s[i];
        h *= 16777619u;
    }
    return h;
}

/* 启动时把关键字表塞进哈希表。只在程序开头跑一次，不影响扫描速度 */
static void 建关键字表(void)
{
    memset(g_格子, 0, sizeof(g_格子));
    for (int i = 0; i < 关键字数量; i++) {
        int n = (int)strlen(关键字表[i].文字);
        关键字表[i].长度 = n;                       /* 长度只算一次，以后白用 */
        uint32_t h = 算哈希(关键字表[i].文字, n) & (格子数 - 1);
        while (g_格子[h] != 0) h = (h + 1) & (格子数 - 1);   /* 撞了就往后挪一格 */
        g_格子[h] = i + 1;
    }
}

/* 查表：给我一段文字，返回它是哪个关键字；不是关键字就返回 NULL */
static const 关键字 *查关键字(const char *s, int n)
{
    uint32_t h = 算哈希(s, n) & (格子数 - 1);
    for (;;) {
        int 号 = g_格子[h];
        if (号 == 0) return NULL;                       /* 空格子 → 肯定没有 */
        const 关键字 *k = &关键字表[号 - 1];
        if (k->长度 == n && memcmp(k->文字, s, n) == 0) return k;
        h = (h + 1) & (格子数 - 1);                     /* 撞了，试下一格 */
    }
}


/* ============================================================================
 *  第三部分：几个"看一个字"的小工具
 * ========================================================================== */

/* 数字？'0' 到 '9' */
static int 是数字(unsigned char c) { return c >= '0' && c <= '9'; }

/* 英文字母？ */
static int 是字母(unsigned char c) { return (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z'); }

/* 十六进制数字？0-9 a-f A-F */
static int 是十六进制(unsigned char c)
{
    return 是数字(c) || (c >= 'a' && c <= 'f') || (c >= 'A' && c <= 'F');
}

/* 空白？空格、制表符、回车。注意：换行不在里面，换行是正式的词 */
static int 是空白(unsigned char c) { return c == ' ' || c == '\t' || c == '\r'; }

/* 把一个 UTF-8 字符解码成"字编号"（码点），顺便告诉调用者它占几个字节。
 *
 * 为什么需要它？因为中文在文件里不是一个字节，是三个字节。
 * 比如 "如" 在文件里是 E5 A6 82 三个字节。要判断它是不是汉字，
 * 得先把三个字节拼回一个编号 0x5982，再看这个编号在不在汉字的区间里。
 */
static int 解码(const unsigned char *p, int *宽度)
{
    unsigned char c = p[0];
    if (c < 0x80)                { *宽度 = 1; return c; }
    if ((c & 0xE0) == 0xC0)      { *宽度 = 2; return ((c & 0x1F) << 6) | (p[1] & 0x3F); }
    if ((c & 0xF0) == 0xE0)      { *宽度 = 3; return ((c & 0x0F) << 12) | ((p[1] & 0x3F) << 6) | (p[2] & 0x3F); }
    if ((c & 0xF8) == 0xF0)      { *宽度 = 4; return ((c & 0x07) << 18) | ((p[1] & 0x3F) << 12)
                                                       | ((p[2] & 0x3F) << 6) | (p[3] & 0x3F); }
    *宽度 = 1; return -1;        /* 不是合法的 UTF-8 */
}

/* 这个码点是汉字吗？
 * 只认三个区间，覆盖 99.9% 的日常汉字。这样全角标点（，。：）就不会被当成汉字了。 */
static int 是汉字(int cp)
{
    return (cp >= 0x4E00 && cp <= 0x9FFF)     /* 常用汉字，两万多字 */
        || (cp >= 0x3400 && cp <= 0x4DBF)     /* 扩展 A，生僻字 */
        || (cp >= 0xF900 && cp <= 0xFAFF);    /* 兼容汉字 */
}

/* 快速判断：这个位置起的三个字节是不是一个汉字。
 * 先看首字节范围，再看码点——绝大多数情况看一眼就否掉了，很快。 */
static int 是汉字开头(const unsigned char *p)
{
    unsigned char c = p[0];
    if (c < 0xE0 || c > 0xEF) return 0;       /* 汉字一定落在三字节区 */
    int 宽;
    return 是汉字(解码(p, &宽));
}


/* ============================================================================
 *  第四部分：往前走
 *  ----------------------------------------------------------------------------
 *  扫描器只有两个动作：看（读 src[pos]）和走（pos 往后挪）。
 *  所有"走"都走下面这两个函数，这样行列号永远不会算乱。
 * ========================================================================== */

/* 走一个字（一个 UTF-8 字符，不是字节） */
static void 走(扫描器 *L)
{
    unsigned char c = (unsigned char)L->src[L->pos];
    if (c == '\n') {
        L->pos++; L->行++; L->列 = 1;
        return;
    }
    if (c < 0x80)      L->pos += 1;
    else if (c < 0xE0) L->pos += 2;
    else if (c < 0xF0) L->pos += 3;
    else               L->pos += 4;
    L->列++;
}

/* 造一个词并交给调用者。起点、长度、行列都在这里一次性拍好 */
static 词 造词(扫描器 *L, 词种类 种类, int 起点, int 起点行, int 起点列)
{
    int 长度 = L->pos - 起点;
    L->计数[种类]++;
    return (词){ 种类, L->src + 起点, 长度, 起点行, 起点列, NULL };
}

/* 造一个报错的词，并顺手打印一条人话提示 */
static 词 造错误(扫描器 *L, int 起点, int 起点行, int 起点列, const char *原因)
{
    L->错误数++;
    L->计数[词_错误]++;
    fprintf(stderr, "词法错误 %d:%d  %s\n", 起点行, 起点列, 原因);
    return (词){ 词_错误, L->src + 起点, L->pos - 起点, 起点行, 起点列, NULL };
}


/* ============================================================================
 *  第五部分：跳过不要的东西（空白和注释）
 *  ----------------------------------------------------------------------------
 *  注释不产生词。"--" 后面到行尾都是给人看的，扫描器直接跨过去。
 *  注意：简言的整除是 "//"，注释是 "--"，两者不冲突，这也是当初这么设计的原因之一。
 * ========================================================================== */

/* 返回 1 表示"这里有个注释，我跳过了"；返回 0 表示"这里不是注释" */
static int 跳过注释(扫描器 *L)
{
    const char *s = L->src;
    int p = L->pos;

    if (s[p] != '-' || s[p + 1] != '-') return 0;

    /* --[[ 块注释，可以跨行 ]]
     * 写法上多两个方括号，是为了让"块注释"和"行注释"一眼分得开。 */
    if (s[p + 2] == '[' && s[p + 3] == '[') {
        L->pos += 4; L->列 += 4;
        while (L->pos < L->长度) {
            if (L->src[L->pos] == ']' && L->src[L->pos + 1] == ']') {
                L->pos += 2; L->列 += 2;
                return 1;
            }
            走(L);
        }
        L->错误数++;
        fprintf(stderr, "词法错误 %d:%d  块注释没有收尾的 ]]\n", L->行, L->列);
        return 1;
    }

    /* 普通行注释：一路吃到换行为止（换行本身留着，它要当语句结束符） */
    while (L->pos < L->长度 && L->src[L->pos] != '\n') 走(L);
    return 1;
}


/* ============================================================================
 *  第六部分：读各种词
 * ========================================================================== */

/* ---- 读标识符或关键字 ----
 *
 *  规则：首字是字母 / 下划线 / 汉字，后面可以跟字母、数字、下划线、汉字。
 *  读完之后去关键字表里查一下，查到就是关键字，查不到就是普通名字。
 */
static 词 读标识符(扫描器 *L)
{
    int 起点 = L->pos, 起行 = L->行, 起列 = L->列;

    for (;;) {
        unsigned char c = (unsigned char)L->src[L->pos];

        if (是字母(c) || 是数字(c) || c == '_') {   /* 常见情况：ASCII，直接走一个字节 */
            L->pos++; L->列++;
        } else if (是汉字开头((const unsigned char *)L->src + L->pos)) {
            L->pos += 3; L->列++;                   /* 汉字整块跳 3 字节，不逐字节解 */
        } else {
            break;
        }
    }

    词 t = 造词(L, 词_标识符, 起点, 起行, 起列);
    const 关键字 *k = 查关键字(t.起点, t.长度);
    if (k != NULL) {                                /* 查到了 → 升级成关键字 */
        t.种类 = 词_关键字;
        t.关 = k;
        L->计数[词_标识符]--;                       /* 前面按标识符记过一次，改回来 */
        L->计数[词_关键字]++;
    }
    return t;
}

/* ---- 读数字 ----
 *
 *  三种写法：
 *      123  1_000_000      → 整数（下划线只是为了好看，会被编译器忽略）
 *      0xFF  0b1010        → 整数（十六进制 / 二进制）
 *      3.14  1e9  2.5e-3   → 浮点
 *
 *  难点在于 "1..2"：这是 1 拼接 2，不是小数。所以看到点还要看下一个字符。
 */
static 词 读数字(扫描器 *L)
{
    int 起点 = L->pos, 起行 = L->行, 起列 = L->列;
    int 是浮点 = 0;
    const char *s = L->src;

    if (s[L->pos] == '0' && (s[L->pos + 1] == 'x' || s[L->pos + 1] == 'X')) {
        L->pos += 2; L->列 += 2;                      /* 0x 前缀 */
        while (是十六进制((unsigned char)s[L->pos]) || s[L->pos] == '_') { L->pos++; L->列++; }
        return 造词(L, 词_整数, 起点, 起行, 起列);
    }
    if (s[L->pos] == '0' && (s[L->pos + 1] == 'b' || s[L->pos + 1] == 'B')) {
        L->pos += 2; L->列 += 2;                      /* 0b 前缀 */
        while (s[L->pos] == '0' || s[L->pos] == '1' || s[L->pos] == '_') { L->pos++; L->列++; }
        return 造词(L, 词_整数, 起点, 起行, 起列);
    }

    while (是数字((unsigned char)s[L->pos]) || s[L->pos] == '_') { L->pos++; L->列++; }

    /* 小数点：必须"点后面还是数字"，而且不能是 ".."（那是拼接） */
    if (s[L->pos] == '.' && 是数字((unsigned char)s[L->pos + 1])) {
        是浮点 = 1;
        L->pos++; L->列++;
        while (是数字((unsigned char)s[L->pos]) || s[L->pos] == '_') { L->pos++; L->列++; }
    }

    /* 科学计数法：1e9、2.5E-3 */
    if ((s[L->pos] == 'e' || s[L->pos] == 'E')
        && (是数字((unsigned char)s[L->pos + 1])
            || ((s[L->pos + 1] == '+' || s[L->pos + 1] == '-') && 是数字((unsigned char)s[L->pos + 2])))) {
        是浮点 = 1;
        L->pos++; L->列++;
        if (s[L->pos] == '+' || s[L->pos] == '-') { L->pos++; L->列++; }
        while (是数字((unsigned char)s[L->pos])) { L->pos++; L->列++; }
    }

    return 造词(L, 是浮点 ? 词_浮点 : 词_整数, 起点, 起行, 起列);
}

/* ---- 读字符串 ----
 *
 *  两种：
 *      "普通字符串\n 支持转义"
 *      [[ 长字符串，里面可以随便换行，写正则和 HTML 很方便 ]]
 */
static 词 读字符串(扫描器 *L)
{
    int 起点 = L->pos, 起行 = L->行, 起列 = L->列;
    const char *s = L->src;

    /* 长字符串 [[ ... ]] */
    if (s[L->pos] == '[' && s[L->pos + 1] == '[') {
        L->pos += 2; L->列 += 2;
        while (L->pos < L->长度) {
            if (s[L->pos] == ']' && s[L->pos + 1] == ']') {
                L->pos += 2; L->列 += 2;
                return 造词(L, 词_字符串, 起点, 起行, 起列);
            }
            走(L);
        }
        return 造错误(L, 起点, 起行, 起列, "长字符串没有收尾的 ]]");
    }

    /* 普通字符串 "..." */
    L->pos++; L->列++;                       /* 吃掉开头的引号 */
    while (L->pos < L->长度) {
        unsigned char c = (unsigned char)s[L->pos];

        if (c == '"') { L->pos++; L->列++; return 造词(L, 词_字符串, 起点, 起行, 起列); }

        if (c == '\n') return 造错误(L, 起点, 起行, 起列, "字符串写到一半换行了，少了右边的引号");

        if (c == '\\') {                     /* 转义：反斜杠后面那个字不是普通的字 */
            L->pos++; L->列++;
            unsigned char e = (unsigned char)s[L->pos];
            if (e == '\0' || e == '\n') return 造错误(L, 起点, 起行, 起列, "字符串以反斜杠结尾");
            if (e == 'n' || e == 't' || e == 'r' || e == '\\' || e == '"' || e == '0' || e == '\'') {
                L->pos++; L->列++;
                continue;
            }
            /* 不认识的转义，只警告不中断，方便一次性看完全部问题 */
            L->错误数++;
            fprintf(stderr, "词法警告 %d:%d  不认识的转义 \\%c\n", L->行, L->列 - 1, e);
            L->pos++; L->列++;
            continue;
        }

        走(L);
    }
    return 造错误(L, 起点, 起行, 起列, "字符串没有收尾的引号");
}

/* ---- 读符号 ----
 *
 *  这里是"最长匹配"原则：能读三个字符就读三个，读不了再退两个，再退一个。
 *  因为 <<< 是左移、<< 是小于、< 是……（简言里没有单独的小于），
 *  如果不先试长的，<<< 会被拆成 << 和 <，意思就全变了。
 */
static 词 读符号(扫描器 *L)
{
    int 起点 = L->pos, 起行 = L->行, 起列 = L->列;
    const char *s = L->src;
    int 长 = 1;

    switch (s[L->pos]) {

    case '<':                                     /* <<< 左移   << 小于   <= 小于等于 */
        长 = (s[L->pos + 1] == '<' && s[L->pos + 2] == '<') ? 3
           : (s[L->pos + 1] == '<' || s[L->pos + 1] == '=') ? 2 : 1;
        break;

    case '>':                                     /* >>> 右移   >> 大于   >= 大于等于 */
        长 = (s[L->pos + 1] == '>' && s[L->pos + 2] == '>') ? 3
           : (s[L->pos + 1] == '>' || s[L->pos + 1] == '=') ? 2 : 1;
        break;

    case '=': 长 = (s[L->pos + 1] == '=') ? 2 : 1; break;   /* ==   = */
    case '!': 长 = (s[L->pos + 1] == '=') ? 2 : 1; break;   /* !=   ! */
    case '^': 长 = (s[L->pos + 1] == '^') ? 2 : 1; break;   /* ^^ 异或   ^ 乘方 */
    case '~': 长 = (s[L->pos + 1] == '~') ? 2 : 1; break;   /* ~~ 取反   ~ 范围 */
    case '/': 长 = (s[L->pos + 1] == '/') ? 2 : 1; break;   /* // 整除   / 除 */
    case '-': 长 = (s[L->pos + 1] == '>') ? 2 : 1; break;   /* -> 箭头   - 减（-- 是注释，上面已处理） */
    case '.': 长 = (s[L->pos + 1] == '.') ? 2 : 1; break;   /* .. 拼接   . 取成员 */
    default:  长 = 1; break;
    }

    /* 剩下的符号都是一个字节：(){}[],:&|# 之类 */
    L->pos += 长;
    L->列 += 长;
    return 造词(L, 词_符号, 起点, 起行, 起列);
}


/* ============================================================================
 *  第七部分：主循环 —— 整个程序的心脏
 *  ----------------------------------------------------------------------------
 *  伪代码，看不懂 C 也能读：
 *
 *      只要还没到文件末尾：
 *          如果是空白     → 跳过
 *          如果是注释     → 跳过
 *          如果是换行     → 吐出一个"换行"词
 *          如果是引号     → 读字符串
 *          如果是数字     → 读数字
 *          如果是字母/汉字 → 读名字（再查一下是不是关键字）
 *          如果是符号     → 读符号
 *          什么都不是     → 报错，跳过这个字，继续
 * ========================================================================== */

static 词 下一个词(扫描器 *L)
{
    for (;;) {
        /* 已经到文件末尾 */
        if (L->pos >= L->长度) {
            L->计数[词_文件结束]++;
            return (词){ 词_文件结束, L->src + L->长度, 0, L->行, L->列, NULL };
        }

        unsigned char c = (unsigned char)L->src[L->pos];

        /* 1) 空白：跳过，不产生词 */
        if (是空白(c)) { L->pos++; L->列++; continue; }

        /* 2) 注释：跳过，不产生词 */
        if (c == '-' && 跳过注释(L)) continue;

        /* 3) 换行：产生一个词。简言没有分号，它就等于语句的句号 */
        if (c == '\n') {
            int 起行 = L->行, 起列 = L->列;
            L->pos++; L->行++; L->列 = 1;
            L->计数[词_换行]++;
            return (词){ 词_换行, L->src + (L->pos - 1), 1, 起行, 起列, NULL };
        }

        /* 4) 字符串：一个字节就能判断，先判掉 */
        if (c == '"' || (c == '[' && L->src[L->pos + 1] == '[')) return 读字符串(L);

        /* 5) 数字 */
        if (是数字(c)) return 读数字(L);

        /* 6) 名字（字母、下划线开头；汉字开头） */
        if (是字母(c) || c == '_') return 读标识符(L);
        if (c >= 0xE0 && 是汉字开头((const unsigned char *)L->src + L->pos)) return 读标识符(L);

        /* 7) 符号：ASCII 可见字符里除了上面挑走的，都在这里 */
        if (c > 0x20 && c < 0x7F) return 读符号(L);

        /* 8) 剩下的就是非法字符了 */

        /* 顺手给全角符号一句人话提示——新手最常犯的错 */
        {
            static const struct { const char *错; const char *对; } 对照[] = {
                { "，", "," }, { "。", "." }, { "；", ";" }, { "：", ":" },
                { "（", "(" }, { "）", ")" }, { "【", "[" }, { "】", "]" },
                { "｛", "{" }, { "｝", "}" }, { "“", "\"" }, { "”", "\"" },
                { "＝", "=" }, { "＋", "+" }, { "－", "-" }, { "＊", "*" },
                { "／", "/" }, { "！", "!" }, { "＜", "<" }, { "＞", ">" },
                { "＆", "&" }, { "｜", "|" }, { "％", "%" }, { "＃", "#" },
                { "～", "~" }, { "＠", "@" }, { "＝", "=" }, { "＄", "$" },
                { "　", "空格" }
            };
            int 起点 = L->pos, 起行 = L->行, 起列 = L->列;
            const char *提示 = NULL;
            for (int i = 0; i < (int)(sizeof(对照) / sizeof(对照[0])); i++) {
                if (strncmp(L->src + L->pos, 对照[i].错, strlen(对照[i].错)) == 0) { 提示 = 对照[i].对; break; }
            }
            走(L);
            if (提示) {
                char 话[96];
                snprintf(话, sizeof(话), "这里用了全角符号，简言只认半角，应该写 %s", 提示);
                return 造错误(L, 起点, 起行, 起列, 话);
            }
            return 造错误(L, 起点, 起行, 起列, "不认识的字符（简言只用半角符号和汉字）");
        }
    }
}


/* ============================================================================
 *  第八部分：命令行外壳
 *  ----------------------------------------------------------------------------
 *  用法：
 *      简词法 文件.简            把每个词打出来
 *      简词法 -统计 文件.简      只打每种词出现多少次
 *      简词法 -机器 文件.简      机器格式（给可视化网页用）
 *      简词法 -基准 文件.简      跑性能测试
 * ========================================================================== */

/* 把整个文件一次读进内存。读文件只在开头做一次，之后扫描完全不碰硬盘 */
static char *读文件(const char *路径, int *out长度)
{
    FILE *f = fopen(路径, "rb");
    if (!f) return NULL;
    fseek(f, 0, SEEK_END);
    long n = ftell(f);
    fseek(f, 0, SEEK_SET);
    if (n < 0) { fclose(f); return NULL; }

    /* 多申请 8 个字节并清零：这样读到末尾时，往前多看两三个字节永远是 '\0'，
     * 循环不用到处写 "pos + 1 < 长度" 这种边界判断，代码短，也快。 */
    char *buf = (char *)malloc((size_t)n + 8);
    if (!buf) { fclose(f); return NULL; }
    size_t 读到 = fread(buf, 1, (size_t)n, f);
    fclose(f);
    memset(buf + 读到, 0, 8);
    *out长度 = (int)读到;
    return buf;
}

static void 打印词(词 t)
{
    /* 列宽固定，中文按字符数算，看起来是齐的 */
    printf("%4d:%3d  %s  ", t.行, t.列, 种类标签[t.种类]);
    if (t.种类 == 词_换行) printf("\\n");
    else printf("%.*s", t.长度, t.起点);
    if (t.种类 == 词_关键字) printf("    （%s）", t.关->类别);
    printf("\n");
}

/* 准备一个扫描器，指向缓冲区开头 */
static void 初始化(扫描器 *L, const char *src, int 长度)
{
    memset(L, 0, sizeof(*L));
    L->src = src;
    L->长度 = 长度;
    L->行 = 1;
    L->列 = 1;
    /* 跳过 UTF-8 BOM（有些编辑器会在文件开头偷偷加三个字节 EF BB BF） */
    if (长度 >= 3 && (unsigned char)src[0] == 0xEF && (unsigned char)src[1] == 0xBB
        && (unsigned char)src[2] == 0xBF) {
        L->pos = 3;
    }
}

/* 语法分析器要复用这个文件里的取词函数。定义 简_只要词法 再 #include 本文件，
 * 主函数就被挡在门外，只留下"造词"的能力。
 * 这是 C 里的老办法：把同一份代码编进另一个程序，避免复制粘贴出两份会跑偏的实现。 */
#ifndef 简_只要词法
int main(int argc, char **argv)
{
    if (argc < 2) {
        fprintf(stderr,
            "简言 · 词法分析器\n"
            "用法：\n"
            "  简词法 文件.简            打印每个词\n"
            "  简词法 -统计 文件.简      统计各类词的数量\n"
            "  简词法 -机器 文件.简      输出机器格式（给可视化用）\n"
            "  简词法 -基准 文件.简      跑性能测试\n");
        return 2;
    }

    建关键字表();

    const char *模式 = "打印";
    const char *路径 = argv[1];
    if (argc >= 3 && argv[1][0] == '-') {
        模式 = argv[1];
        路径 = argv[2];
    }

    int 长度 = 0;
    char *源 = 读文件(路径, &长度);
    if (!源) {
        fprintf(stderr, "打不开文件：%s\n", 路径);
        return 1;
    }

    扫描器 L;

    /* ---------------- 基准模式 ---------------- */
    if (strcmp(模式, "-基准") == 0) {
        /* 先热身一次，让 CPU 缓存热起来、分支预测学好 */
        volatile long 校验和 = 0;
        for (int 轮 = 0; 轮 < 3; 轮++) {
            初始化(&L, 源, 长度);
            for (;;) { 词 t = 下一个词(&L); 校验和 += t.长度; if (t.种类 == 词_文件结束) break; }
        }

        /* 正式测：跑够 0.5 秒，算出每秒处理多少 MB */
        struct timespec 起, 止;
        clock_gettime(CLOCK_MONOTONIC, &起);
        long 总词数 = 0, 轮数 = 0;
        double 秒 = 0;
        do {
            初始化(&L, 源, 长度);
            for (;;) { 词 t = 下一个词(&L); 校验和 += t.长度; 总词数++; if (t.种类 == 词_文件结束) break; }
            轮数++;
            clock_gettime(CLOCK_MONOTONIC, &止);
            秒 = (止.tv_sec - 起.tv_sec) + (止.tv_nsec - 起.tv_nsec) / 1e9;
        } while (秒 < 0.5);

        double MB = (double)长度 * 轮数 / (1024.0 * 1024.0);
        printf("文件       %s（%.2f KB）\n", 路径, 长度 / 1024.0);
        printf("轮数       %ld\n", 轮数);
        printf("总词数     %ld\n", 总词数);
        printf("耗时       %.3f 秒\n", 秒);
        printf("吞吐       %.1f MB/s\n", MB / 秒);
        printf("速度       %.1f 万词/秒\n", 总词数 / 秒 / 10000.0);
        printf("（校验和 %ld，防止编译器把整个循环优化掉）\n", 校验和);
        free(源);
        return 0;
    }

    /* ---------------- 普通模式 ---------------- */
    初始化(&L, 源, 长度);

    if (strcmp(模式, "-机器") == 0) {
        /* 机器格式：行 列 种类(数字) 起点 长度，一行一个词，给网页画色块用 */
        for (;;) {
            词 t = 下一个词(&L);
            printf("%d\t%d\t%d\t%d\t%d\n", t.行, t.列, (int)t.种类, (int)(t.起点 - 源), t.长度);
            if (t.种类 == 词_文件结束) break;
        }
    } else if (strcmp(模式, "-统计") == 0) {
        for (;;) {
            词 t = 下一个词(&L);
            if (t.种类 == 词_文件结束) break;
        }
        printf("文件       %s\n", 路径);
        printf("字节数     %d\n", 长度);
        const char *名[] = { "文件结束", "换行", "标识符", "关键字", "整数", "浮点", "字符串", "符号", "错误" };
        long 合计 = 0;
        for (int i = 0; i < 9; i++) {
            if (i == 词_文件结束) continue;
            if (L.计数[i] == 0) continue;
            printf("%-10s %8ld\n", 名[i], L.计数[i]);
            合计 += L.计数[i];
        }
        printf("%-10s %8ld\n", "合计", 合计);
    } else {
        long 总数 = 0;
        for (;;) {
            词 t = 下一个词(&L);
            打印词(t);
            总数++;
            if (t.种类 == 词_文件结束) break;
        }
        fprintf(stderr, "\n共 %ld 个词，%d 个错误\n", 总数, L.错误数);
    }

    free(源);
    return L.错误数 > 0 ? 1 : 0;
}

#endif /* 简_只要词法 */
