/* 值表：每个值号对应一个类型，变量还额外记名字。
 * 有了它，打印时能写 `%甲` 而不是 `%3`，读起来是个人话。 */
typedef struct {
    类型 *型;
    const char *名;
    int 名长;
    int 是变量;
} 值项;


struct 指令 {
    unsigned char 码;
    int 结果;                /* 结果值号；-1 表示这条指令不产值 */
    int 甲, 乙, 丙;          /* 操作数（值号），-1 表示没有 */
    const char *文;          /* 名字：变量名、字段名、函数名、常量原文 */
    int 文长;
    类型 *型;                /* 结果类型；常量则是它自己的类型 */
    /* 指令只有甲乙丙三个位置装不下多参数调用，所以另开一串。
     * 调用、构造数组/映射/结构/变体 都用它。 */
    int 多[8];
    int 多量;
    指令 *下;
};

struct 基本块 {
    int 号;
    指令 *头, *尾;
    int 指令数;
    int 已访问;              /* 打印时用：按执行流走一遍，别按创建顺序 */
    基本块 *下;
};

struct 中间函数 {
    const char *名;
    int 名长;
    类型 *型;                /* 型_函数：参数与返回类型 */
    基本块 *首块, *尾块, *当前块;
    int 下个块号;
    int 指令数;
    /* 每个函数自己一套值表：匿名函数是在外层函数降级途中创建的，
     * 共用一个表会互相踩。 */
    值项 *值; int 值数, 值容量;
    int 下个值;
    节点 *源;                /* 这个 IR 函数是从哪个语法节点来的，打印参数名要用 */
    struct 中间函数 *下;
};

typedef struct {
    中间函数 *头, *尾;
    int 个数;
    int 实例数;              /* 其中有多少个是单态化出来的 */
} 模块;

