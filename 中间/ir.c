/* ============================================================================
 *  简言 · 中间表示与单态化（ir.c）
 *  ----------------------------------------------------------------------------
 *  前四棒依次是：切词 → 搭树 → 查名字查类型 → ？？
 *  这一棒要回答一个很实际的问题：
 *
 *      「这棵树，怎么变成一串能让机器一条一条执行的命令？」
 *
 *  树是给人看的：`甲 + 乙 * 2` 一眼就懂，但它没说清"先算哪个、结果放哪"。
 *  机器要的是一串平铺的、每步只做一件事的指令，这种形式叫「中间表示」，简称 IR：
 *
 *      %t0 = 载 甲
 *      %t1 = 载 乙
 *      %t2 = 常量 2
 *      %t3 = 乘 %t1, %t2
 *      %t4 = 加 %t0, %t3
 *
 *  为什么要有这一层？因为从树直接出机器码，等于一次跨两级台阶，
 *  中间任何一步出错都极难查。中间表示是「半成品」：
 *    - 比树低：每个操作都明确了先后和存放位置；
 *    - 比机器码高：还认得出"这是加法""这是调用函数"，不绑死某个 CPU。
 *  优化（常量折叠、死代码消除、寄存器分配）全都在这层做，做完再翻译成机器码。
 *
 *  ----------------------------------------------------------------------------
 *  这一棒具体干四件事：
 *    1. 降级：把语法树翻译成一串指令，装进基本块（basic block）。
 *    2. 单态化：泛型函数 `最大[T](甲: T, 乙: T)` 在 C 里是没法直接生成的——
 *       T 必须变成具体类型。所以每遇到一种实参类型，就复制一份专用版本：
 *       `最大$整数`、`最大$浮点`。这叫单态化（monomorphization）。
 *    3. 常量折叠：`2 * 3 + 1` 不该在运行时算，编译时就算成 7。
 *    4. 打印：输出人能读的 IR 文本，方便肉眼检查每一步。
 *
 *  ----------------------------------------------------------------------------
 *  三个原则，和前面几棒一致：
 *    - 只做这一层该做的事。不分配寄存器、不排指令顺序，那些是下一棒。
 *    - 每个值都有编号和类型，绝不出现"这个值是啥不知道"。
 *    - 生成的 IR 要能被人读懂。看不懂的中间产物，等于没有。
 *
 *  编译：
 *      gcc -O3 -flto -s -o 简中间 ir.c
 * ========================================================================== */

