/* ============================================================================
 *  第一部分：IR 长什么样
 *  ----------------------------------------------------------------------------
 *  三层结构，和真正的编译器一样：
 *
 *      函数 ── 一串基本块 ── 每个块里一串指令
 *
 *  为什么要有"基本块"这一层？因为跳转只能发生在块的边界上：
 *  一个块一旦开始执行，就会一直执行到最后一条，不会中途跳走。
 *  这条约束让后面做优化时"块内可以随便重排"，省掉无数麻烦。
 * ========================================================================== */

